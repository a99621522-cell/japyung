/**
 * ohaeng_seosa.js — 오행으로 된 이야기 층
 *
 * 문제: 「정재가 온다」는 **관계의 이름**이지 그림이 아니다.
 *   상담에서 그렇게 말하면 듣는 사람 머릿속에 아무것도 안 그려진다.
 *   「불이 온다」고 해야 그림이 생기고, 그 다음에 「그 불이 당신에게는
 *   다루는 실물(정재)입니다」로 이름을 붙여야 한다.
 *
 * 그래서 말하는 순서를 뒤집는다:
 *   ① 나는 무엇인가              → 「선생님은 물입니다」
 *   ② 나를 낳아주는 게 무엇인가    → 「쇠 위에 서 계십니다」
 *   ③ 그것을 위협하는 건 무엇인가  → 「불이 그 쇠를 녹입니다」
 *   ④ 그걸 막아주는 건 무엇인가    → 「같은 물이 그 불을 끕니다」
 *   ⑤ 지금 무엇이 오는가          → 「불이 세 겹으로 옵니다」
 *
 * **그림이 먼저, 십성 이름은 괄호로 나중.**
 *
 * ※ 이 층은 원문에 없다. 원문은 격과 상신으로 말하지 오행 서사로 말하지 않는다.
 *   다만 27편·5편이 이미 생극을 오행으로 설명하므로, 그 말을 상담 언어로
 *   옮기는 것까지가 이 모듈의 일이다. 판정은 바꾸지 않는다.
 */

const { GAN, JIJANGGAN, sipseong } = require('./jijanggan');

const 우리말 = { 木:'나무', 火:'불', 土:'흙', 金:'쇠', 水:'물' };
const 생 = { 木:'火', 火:'土', 土:'金', 金:'水', 水:'木' };
const 극 = { 木:'土', 土:'水', 水:'火', 火:'金', 金:'木' };
const 역생 = Object.fromEntries(Object.entries(생).map(([a, b]) => [b, a]));
const 역극 = Object.fromEntries(Object.entries(극).map(([a, b]) => [b, a]));

/** 두 오행 사이에 무슨 일이 일어나는지 — 사람이 읽을 동사로 */
// 앞에 목적어를 이미 쓰므로 동사만 남긴다 — 「그 쇠를 녹입니다」처럼 이어지게
const 동사 = {
  '木火':'태워 불을 일으킵니다', '火土':'타고 남아 흙이 됩니다', '土金':'굳어 쇠가 됩니다',
  '金水':'서려 물이 됩니다', '水木':'적셔 키웁니다',
  '木土':'뿌리로 파고듭니다', '土水':'둑이 되어 막습니다',
  '水火':'끕니다', '火金':'녹입니다', '金木':'벱니다',
};
const 무슨일 = (a, b) => 동사[a + b] ?? null;

/** 명식에서 각 오행이 어디에 얼마나 놓였는지 — 세지 않고 본다 */
function 자리(m) {
  const 천간 = [['년', m.yeonGan], ['월', m.wolGan], ['시', m.siGan]].filter(x => x[1]);
  const 지지 = [['년', m.yeonJi], ['월', m.wolJi], ['일', m.ilJi], ['시', m.siJi]].filter(x => x[1]);
  const out = {};
  for (const o of Object.keys(우리말)) out[o] = { 드러남: [], 숨음: [] };
  for (const [p, g] of 천간) out[GAN[g].ohaeng].드러남.push(`${g}(${p})`);
  for (const [p, j] of 지지)
    for (const x of JIJANGGAN[j])
      out[GAN[x.gan].ohaeng].숨음.push(`${x.gan}(${p}${j})`);
  return out;
}

/**
 * 명식 하나를 오행 이야기로 옮긴다.
 * @param {object} r interpret() 결과
 */
function 다섯표(나) {
  const 역생 = { 火:'木', 土:'火', 金:'土', 水:'金', 木:'水' };
  return {
    나: { 오행:나, 우리말:우리말[나], 뜻:'나 자신 · 같은 편', 십성:'비겁' },
    낳아주는: { 오행:역생[나], 우리말:우리말[역생[나]], 뜻:'나를 낳아주는 것 — 밑천', 십성:'인수' },
    내가낳는: { 오행:생[나], 우리말:우리말[생[나]], 뜻:'내가 낳는 것 — 내보내는 힘', 십성:'식상' },
    내가극하는: { 오행:극[나], 우리말:우리말[극[나]], 뜻:'내가 다루는 것 — 실물', 십성:'재' },
    나를극하는: { 오행:역극[나], 우리말:우리말[역극[나]], 뜻:'나를 누르는 것 — 틀', 십성:'관살' },
  };
}

function analyze(r) {
  const m = r.명식;
  const 나 = GAN[m.ilGan].ohaeng;
  const 낳아주는 = 역생[나];      // 나를 낳는 것 = 인수
  const 같은 = 나;                // 비겁
  const 내가낳는 = 생[나];        // 식상
  const 내가극하는 = 극[나];      // 재
  const 나를극하는 = 역극[나];    // 관살

  const 놓임 = 자리(m);
  const 격오행 = ({ 정인:낳아주는, 편인:낳아주는, 비견:같은, 겁재:같은, 건록:같은, 월겁:같은, 양인:같은,
                    식신:내가낳는, 상관:내가낳는, 정재:내가극하는, 편재:내가극하는,
                    정관:나를극하는, 편관:나를극하는 })[r.결론.격] ?? null;
  const 상신오행 = ({ 정인:낳아주는, 편인:낳아주는, 비견:같은, 겁재:같은, 양인:같은,
                      식신:내가낳는, 상관:내가낳는, 식상:내가낳는,
                      정재:내가극하는, 편재:내가극하는, 재:내가극하는,
                      정관:나를극하는, 편관:나를극하는, 관살:나를극하는 })[r.결론.상신] ?? null;

  // 격을 극하는 오행이 「위협」인가 「다스림」인가는 격의 성질이 정한다.
  //   8편 — 순용(財官印食)은 살려 쓰므로 그것을 극하면 위협이다.
  //         역용(煞傷劫刃)은 다스려 쓰므로 그것을 극하는 것이 곧 상신이다.
  //   이 구분을 안 하면 「물이 불을 끕니다 / 떠받치는 것도 물입니다」처럼
  //   같은 오행이 위협이자 상신으로 나와 말이 어긋난다.
  const 역용격 = ['상관', '편관', '양인', '건록', '월겁'].includes(r.결론.격);
  const 극하는것 = 격오행 ? 역극[격오행] : null;
  const 위협 = 역용격 ? null : 극하는것;
  const 다스림 = 역용격 ? 극하는것 : null;

  // 조사를 받침에 맞춘다 — 읽는 사람이 걸리지 않게
  const 은는 = w => (w.charCodeAt(w.length - 1) - 0xAC00) % 28 ? `${w}은` : `${w}는`;
  const 이가 = w => (w.charCodeAt(w.length - 1) - 0xAC00) % 28 ? `${w}이` : `${w}가`;
  const 을를 = w => (w.charCodeAt(w.length - 1) - 0xAC00) % 28 ? `${w}을` : `${w}를`;
  const 이니 = w => `${w}이니`;
  const 으로 = w => (w.charCodeAt(w.length - 1) - 0xAC00) % 28 ? `${w}으로` : `${w}로`;   // 「쇠이니」「물이니」 — 모두 이쪽이 자연스럽다

  const 문장 = [];
  문장.push(`선생님은 **${우리말[나]}**이십니다.`);
  if (격오행) {
    // 격오행이 나에게 무엇이냐로 문장이 갈린다.
    //   나를 낳는다 / 내가 낳는다 / 내가 극한다 / 나를 극한다 / 나와 같다
    let 문 = null;
    if (격오행 === 나)
      문 = `태어난 달이 **저와 같은 ${이니(우리말[나])}** — 밖에서 쓸 것을 찾아야 하는 자리입니다.`;
    else if (생[격오행] === 나)
      문 = `태어난 달이 **${이니(우리말[격오행])}** — **${이가(우리말[격오행])} 저를 낳아줍니다**. 그 자리 위에 서 계십니다.`;
    else if (생[나] === 격오행)
      문 = `태어난 달이 **${이니(우리말[격오행])}** — **제가 낳는 것**입니다. **${을를(우리말[격오행])} 만들어 내보내며** 사는 자리지요.`;
    else if (극[나] === 격오행)
      문 = `태어난 달이 **${이니(우리말[격오행])}** — **제가 다루는 것**입니다. **${을를(우리말[격오행])} 부려 쓰며** 사는 자리지요.`;
    else if (극[격오행] === 나)
      문 = `태어난 달이 **${이니(우리말[격오행])}** — **${이가(우리말[격오행])} 저를 누릅니다**. **그것을 감당하며** 사는 자리지요.`;
    문장.push(문 ?? `태어난 달이 **${이니(우리말[격오행])}**입니다.`);
  }
  if (위협 && 위협 !== 나) {
    const 일 = 무슨일(위협, 격오행);
    문장.push(`그런데 **${이가(우리말[위협])}** 그 ${을를(우리말[격오행])} **${일 ?? '칩니다'}**.`);
  } else if (다스림) {
    // 역용격 — 그 힘이 세면 나를 축내므로 눌러야 한다
    const 일 = 무슨일(다스림, 격오행);
    문장.push(`이 힘은 세면 저를 축내므로 **다스려야** 합니다 — **${이가(우리말[다스림])} ${일 ?? '누릅니다'}**.`);
  }
  if (상신오행) {
    // 상신이 하는 일은 둘 중 하나다.
    //   ① 위협을 직접 극한다      → 「막는다」
    //   ② 다른 길을 낸다          → 「돌린다」  (선생님 명식이 이쪽이다)
    // 「나무가 그 불을 태워 불을 일으킵니다」 같은 말이 나오면 ②인데 ①로 쓴 것이다.
    // 역용격이면 상신이 격을 직접 누르는 것이 정상이다
    if (다스림 && 상신오행 === 다스림) {
      문장.push(`그 일을 맡은 것이 **${우리말[상신오행]}**입니다.`);
      return { 나, 격오행, 상오행: 상신오행, 위협: null, 다스림, 놓임, 이야기: 문장, 다섯: 다섯표(나) };
    }
    const 막나 = 극[상신오행] === 위협;
    const 일 = 막나 ? 무슨일(상신오행, 위협) : null;
    if (막나 && 일)
      문장.push(`그것을 막아주는 것이 **${우리말[상신오행]}**입니다 — **${이가(우리말[상신오행])} 그 ${을를(우리말[위협])} ${일}**.`);
    else if (상신오행 === 나)
      문장.push(`그것을 지켜주는 것이 **같은 ${우리말[나]}**입니다.`);
    else {
      // 상신 → 무언가 → 나 로 이어지는 두 단계를 다 보인다
      const 중간 = 생[상신오행];
      문장.push(중간 && 생[중간] === 나
        ? `막는 대신 **${으로(우리말[상신오행])}** 길을 냅니다 — **${이가(우리말[상신오행])} ${을를(우리말[중간])} 낳고, ${이가(우리말[중간])} 저를 낳습니다**.`
        : `그것을 떠받치는 것이 **${우리말[상신오행]}**입니다.`);
    }
  }

  return {
    나: { 오행: 나, 우리말: 우리말[나], 글자: m.ilGan },
    다섯: {
      나: { 오행: 나, 우리말: 우리말[나], 뜻: '나 자신 · 같은 편', 십성: '비겁' },
      낳아주는: { 오행: 낳아주는, 우리말: 우리말[낳아주는], 뜻: '나를 낳아주는 것 — 밑천', 십성: '인수' },
      내가낳는: { 오행: 내가낳는, 우리말: 우리말[내가낳는], 뜻: '내가 낳는 것 — 내보내는 힘', 십성: '식상' },
      내가극하는: { 오행: 내가극하는, 우리말: 우리말[내가극하는], 뜻: '내가 다루는 것 — 실물', 십성: '재' },
      나를극하는: { 오행: 나를극하는, 우리말: 우리말[나를극하는], 뜻: '나를 누르는 것 — 틀', 십성: '관살' },
    },
    격오행, 상신오행, 위협, 놓임,
    이야기: 문장,
    주의: '십성 이름은 괄호로만 쓴다. 그림을 먼저 보이고 이름은 나중에 붙인다',
  };
}

/** 운 한 칸을 오행 말로 옮긴다 */
function 운풀이(seosa, un) {
  const 천 = GAN[un.천간]?.ohaeng;
  const 지 = (JIJANGGAN[un.지지] ?? []).find(x => x.wi === '정기');
  const 지오 = 지 ? GAN[지.gan].ohaeng : null;
  const 이름 = o => 우리말[o];
  const 무엇 = o => {
    const d = seosa.다섯;
    for (const k of Object.keys(d)) if (d[k].오행 === o) return d[k].뜻;
    return '';
  };
  // 받침에 맞춘 조사 — 「쇠가 옵니다」「나무가 옵니다」
  const 이가 = w => (w.charCodeAt(w.length - 1) - 0xAC00) % 28 ? `${w}이` : `${w}가`;
  const out = [];
  if (천) out.push(`천간에 **${이가(이름(천))}** 옵니다 — ${무엇(천)} (${un.천간십성})`);
  if (지오) out.push(`지지에 **${이가(이름(지오))}** 옵니다 — ${무엇(지오)} (${un.지지십성})`);
  // 같은 오행이 겹치면 그 말을 보탠다
  if (천 && 천 === 지오) out.push(`**${이름(천)}이 두 겹**입니다.`);   // 「불이 두 겹」 — 이쪽은 그대로가 자연스럽다
  return out;
}

module.exports = { analyze, 운풀이, 우리말, 생, 극 };
