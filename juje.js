function 고르기(말) {
  if (!말) return null;
  const s = String(말).trim();
  if (주제표[s]) return s;
  if (별칭[s]) return 별칭[s];
  for (const [k, v] of Object.entries(별칭)) if (s.includes(k)) return v;
  for (const k of 카테고리) if (s.includes(k)) return k;
  return null;
}

/** 그 십성이 원국 어디에 있는지 — 천간에 드러났는지, 지지에 숨었는지 */
function 어디있나(m, 십) {
  const 곳 = [];
  const 자리 = [['년', m.yeonGan, m.yeonJi], ['월', m.wolGan, m.wolJi],
                ['일', m.ilGan, m.ilJi], ['시', m.siGan, m.siJi]];
  for (const [이름, 간, 지] of 자리) {
    if (간 && 간 !== m.ilGan && sipseong(m.ilGan, 간) === 십)
      곳.push({ 자리: 이름, 위: '천간', 글자: 간, 드러남: true });
    if (!지) continue;
    for (const jg of (JIJANGGAN[지] || [])) {
      if (sipseong(m.ilGan, jg.gan) !== 십) continue;
      const 투출 = [m.yeonGan, m.wolGan, m.siGan].includes(jg.gan);
      곳.push({ 자리: 이름, 위: '지지 속', 글자: jg.gan, 지지: 지,
                본기: jg === JIJANGGAN[지][0], 드러남: 투출 });
    }
  }
  return 곳;
}

/**
 * 주제를 재료로 편다.
 * @returns null이면 주제를 옮기지 않는 종류(나라는 사람 / 올해와 앞으로 / 몸)
 */
function analyze(m, 물음) {
  const 이름 = 고르기(물음);
  if (!이름) return null;
  const t = 주제표[이름];
  // 사용자가 검색창에 쓴 문장 그대로도 들고 간다.
  // 「승진할 수 있을까요」를 「일과 자리」로 옮기더라도, 답은 그 문장에 해야 한다.
  const 원문 = String(물음).trim();
  const out = { 주제: 이름, 물음: 원문 !== 이름 ? 원문 : null,
                옮김: t.옮김, 설명: t.설명, 몸: !!t.몸,
                축: [], 보탬: [], 없음: [] };

  for (const 십 of t.십성) {
    const 곳 = 어디있나(m, 십);
    if (곳.length) out.축.push({ 십성: 십, 곳 });
    else out.없음.push(십);
  }
  for (const 십 of t.보탬) {
    const 곳 = 어디있나(m, 십);
    if (곳.length) out.보탬.push({ 십성: 십, 곳 });
  }
  return out;
}

/** 브리프에 실을 줄들 */
function 재료줄(a) {
  if (!a) return [];
  const L = [`**[묻는 주제] ${a.주제}**`];
  if (a.물음) {
    L.push(`- **이분이 실제로 물으신 말: 「${a.물음}」**`);
    L.push(`- 답은 이 문장에 하세요. 주제 이름을 설명하지 말고, 물으신 그 말에 답하듯 쓰세요`);
  }
  L.push(`- 이 물음은 이 사람에게 「${a.옮김}」으로 옮긴다`);
  L.push(`- 근거: ${a.설명}`);
  const 적기 = g => g.map(x => x.위 === '천간'
      ? `${x.자리}간 ${x.글자}(천간에 드러남)`
      : `${x.자리}지 ${x.지지} 속 ${x.글자}${x.본기 ? '(본기)' : ''}${x.드러남 ? ' — 천간으로 투출' : ' — 숨어 있음'}`)
    .join(' / ');
  if (a.축.length) for (const x of a.축) L.push(`- **축이 되는 십성 ${x.십성}** — ${적기(x.곳)}`);
  if (a.없음.length) L.push(`- **원국에 없는 십성: ${a.없음.join('·')}** — 없다는 것도 재료다. 없으면 운에서 올 때 크게 움직인다고 보되, 없어서 나쁘다고는 하지 말 것`);
  if (a.보탬.length) for (const x of a.보탬) L.push(`- 곁들여 볼 ${x.십성} — ${적기(x.곳)}`);
  if (a.몸) L.push('- **몸에 관한 물음이다. 병·수명·사고는 한 글자도 쓰지 말 것.** 조후와 오행의 치우침으로 「무엇에 지치고 무엇을 무리하게 되는 사람인가」까지만 쓰고, 몸이 걱정되면 의사를 보시라고 한 줄 붙일 것');
  L.push(`- 이 주제를 축으로 삼되, 격과 상신을 버리지 말 것. **격이 뼈대고 주제는 그 뼈대를 어디에 대어 보느냐다**`);
  return L;
}

