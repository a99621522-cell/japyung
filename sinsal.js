/**
 * 24편에서 배제하기로 한 흉단(凶斷) 표현.
 * 낱말 하나로 잡으면 오탐이 난다 — "다섯 해로 나눠"의 '해로'가 걸린 적이 있다.
 * 그래서 구(句) 단위로 둔다.
 */
// 사람에게 등급을 매기는 말은 내보내지 않는다 — 국의 이름으로 대신한다
const 등급어 = ['상격', '중격', '하격', '上格', '中格', '下格', '귀격', '천격'];

function lintDeunggeup(text) {
  const 본문 = text.split(원칙문).join('')
    .split('\n').filter(l => !/^\*.*\*$/.test(l.trim())).join('\n');
  const hit = 등급어.filter(w => 본문.includes(w));
  return { 통과: hit.length === 0, 검출: hit,
    사유: hit.length ? `사람에게 등급을 매기는 말이 섞였다: ${hit.join(', ')}` : '등급 표현 없음' };
}

