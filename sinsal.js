/**
 * 21편 「貴眾則舞裙歌扇」 논파 — 십성이 많다는 이유로 사람의 품행을 재는 말.
 *
 * 원문이 이 속설을 이름 붙여 반박한다.
 *   「貴眾者，官眾也 … 若作貴人，乃是天星，並非夫主，
 *    何礙於眾，而必爲娼妓乎？」
 *
 * 앞의 신살 검사(lint)는 「도화」 같은 **낱말**을 잡는다.
 * 그런데 낱말 없이도 같은 말을 할 수 있다 —
 * 「관성이 많으니 품행을 조심하라」처럼.
 * **낱말이 아니라 그 논법**을 잡아야 한다.
 */
const 십성명 = ['비견','겁재','식신','상관','정재','편재','정관','편관','칠살','정인','편인','관성','재성','인성','식상'];
const 품행어 = ['품행','정조','행실','바람','외도','문란','헤프', '몸가짐','정숙','음란','부정','불륜'];
const 다수어 = ['많', '여럿', '겹', '중첩', '혼잡', '태과', '지나치게'];

function lintPumhaeng(text) {
  const 검출 = [];
  // 한 문장 안에 「십성 + 많다 + 품행」이 함께 오면 그 논법이다
  for (const 문장 of text.split(/(?<=[.!?。])\s*|\n/)) {
    if (!문장.trim()) continue;
    const 십 = 십성명.filter(x => 문장.includes(x));
    const 다 = 다수어.filter(x => 문장.includes(x));
    const 품 = 품행어.filter(x => 문장.includes(x));
    if (십.length && 다.length && 품.length)
      검출.push(`${십[0]}+${다[0]}+${품[0]}`);
    // 십성 없이도 「많아서 품행」이면 같은 논법
    else if (다.length && 품.length && /사주|명식|글자|자리/.test(문장))
      검출.push(`${다[0]}+${품[0]}`);
  }
  return {
    통과: 검출.length === 0, 검출,
    사유: 검출.length
      ? '십성이 많다는 이유로 사람의 품행을 재는 논법 — 21편이 직접 논파한 것'
      : '해당 없음',
  };
}

