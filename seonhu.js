/**
 * seonhu.js — 20편 「論生尅先後分吉凶」
 * 사주팔자집 (2026-08-02)
 *
 * 「月令用神，配以四柱，固有每字之生尅以分吉凶，
 *   然有同此生尅，而**先後之間，遂分吉凶**者，尤談命之奧也。」
 *
 * 같은 여덟 글자라도 **어느 것이 앞에 놓이느냐**로 길흉이 갈린다는 편이다.
 * 앞선 편들이 '무엇이 있느냐'를 물었다면 이 편은 '어디에 있느냐'를 묻는다.
 *
 * 원문이 든 네 쌍 — 모두 病(해치는 글자)과 藥(푸는 글자)의 순서 문제다.
 *   正官格 財傷並透 — 甲用酉官에 丁(傷)先 戊(財)後면 재가 상관을 풀어주어 後運에 결국이 있고,
 *                     戊先 丁後면 관이 재생을 받다가 뒤에 상관에게 깨져 끝내 결국이 없다
 *   印格 貪財壞印   — 甲用子印에 己(財)先 癸(印)後면 만년이 그런대로 순하고,
 *                     癸先 己在時면 만년이 초췌하다
 *   食神格 財梟並透 — 壬用甲食에 庚(梟)先 丙(財)後면 만운이 형통하고,
 *                     丙先 庚在時면 만운이 담박해 부귀가 모두 빈다
 *   七煞格 財食並透 — 己生卯月에 癸(財)先 辛(食)後면 대귀를 잃지 않고,
 *                     辛先 癸在時면 재가 식신을 돌려 살을 도와 귀하지 못하다
 *
 * 하나로 꿰면 — **藥이 病보다 뒤에 있어야 한다.**
 * 그리고 시주가 특히 무겁다. 시는 돌아가 머무는 자리(歸宿之地)이기 때문이다.
 *
 * 간격(隔)도 이 편에서 다시 나온다.
 *   「丙生甲寅月，年癸時戊 … 戊**不得越甲以合癸**」 — 사이에 글자가 끼면 合도 막힌다
 *   「丙生辛酉，年癸時己，**傷因財間**，傷之無力」 — 사이에 글자가 끼면 尅도 막힌다
 * 이는 13편의 越尅과 같은 원리이며, 이미 합거·조문 판정에 반영돼 있다.
 */

const { sipseong } = require('./jijanggan');

const POS = ['년', '월', '일', '시'];

/**
 * 격별 病(해치는 글자)과 藥(푸는 글자).
 * 원문이 든 넷을 그대로 옮기고, 「餘如印畏財破，財懼比劫，食傷忌梟印，意義相同」에 따라
 * 재격·상관격까지 같은 방식으로 확장했다.
 */
const 병약 = {
  정관: { 병:['상관'],           약:['정재','편재','정인','편인'],
    원문:'正官同是財傷並透，而先後有殊' },
  정인: { 병:['정재','편재'],    약:['비견','겁재'],
    원문:'印格同是貪財壞印，而先後有殊' },
  편인: { 병:['정재','편재'],    약:['비견','겁재'],
    원문:'印格同是貪財壞印，而先後有殊' },
  식신: { 병:['편인'],           약:['정재','편재'],
    원문:'食神同是財梟並透，而先後有殊' },
  편관: { 병:['정재','편재'],    약:['식신','상관'],
    원문:'七煞同是財食並透，而先後大殊' },
  정재: { 병:['비견','겁재'],    약:['식신','상관','정관'],
    원문:'財懼比劫，意義相同' },
  편재: { 병:['비견','겁재'],    약:['식신','상관','정관'],
    원문:'財懼比劫，意義相同' },
  상관: { 병:['정관'],           약:['정인','편인','정재','편재'],
    원문:'食傷忌梟印，意義相同' },
};

function 찾기(m, 십성목록) {
  const out = [];
  for (const [p, g] of [['년', m.yeonGan], ['월', m.wolGan], ['시', m.siGan]]) {
    if (g && 십성목록.includes(sipseong(m.ilGan, g)))
      out.push({ 자리:p, 글자:g, 십성:sipseong(m.ilGan, g), 순서:POS.indexOf(p) });
  }
  return out;
}

function analyze(ctx, m) {
  const 표 = 병약[ctx.gyeok];
  if (!표) {
    return { 해당:false, 판정:'해당 없음',
      사유:`${ctx.gyeok}격은 원문이 선후를 논한 격이 아니다` };
  }

  const 병 = 찾기(m, 표.병);
  const 약 = 찾기(m, 표.약);

  if (병.length === 0) {
    return { 해당:true, 판정:'해당 없음',
      사유:`격을 해치는 ${표.병.join('·')}이 원국에 드러나지 않아 선후를 논할 것이 없다` };
  }
  if (약.length === 0) {
    return { 해당:true, 판정:'약이 없음',
      병:병.map(x => `${x.십성}(${x.글자}·${x.자리})`),
      설명:`${병.map(x => `${x.십성}(${x.글자})`).join('·')}이 격을 해치는데 이를 풀어줄 글자가 없다`,
      원문:표.원문 };
  }

  // 藥이 病보다 뒤에 있는가
  const 병최전 = Math.min(...병.map(x => x.순서));
  const 약최후 = Math.max(...약.map(x => x.순서));
  const 약이뒤 = 약최후 > 병최전;

  // 시주는 돌아가 머무는 자리다
  const 병이시 = 병.some(x => x.자리 === '시');
  const 약이시 = 약.some(x => x.자리 === '시');

  const 판정 = 약이뒤 ? (약이시 ? '약이 시주에 있음 — 가장 좋은 순서' : '약이 병보다 뒤')
                     : (병이시 ? '병이 시주에 있음 — 가장 나쁜 순서' : '병이 약보다 뒤');

  return {
    해당:true, 판정,
    병:병.map(x => `${x.십성}(${x.글자}·${x.자리})`),
    약:약.map(x => `${x.십성}(${x.글자}·${x.자리})`),
    약이뒤, 병이시, 약이시,
    설명: 약이뒤
      ? `격을 해치는 ${병[0].십성}(${병[0].글자}·${병[0].자리}간)보다 이를 푸는 ${약[약.length-1].십성}(${약[약.length-1].글자}·${약[약.length-1].자리}간)이 뒤에 놓였다${약이시 ? '. 시는 돌아가 머무는 자리라 말년의 결국이 있다' : ''}`
      : `이를 푸는 ${약[0].십성}(${약[0].글자}·${약[0].자리}간)이 앞서고 해치는 ${병[병.length-1].십성}(${병[병.length-1].글자}·${병[병.length-1].자리}간)이 뒤에 놓였다. 앞은 순해도 끝내 결국을 보기 어려운 배치다${병이시 ? '. 병이 시주에 있어 말년이 특히 그렇다' : ''}`,
    원문: 표.원문,
    총론: '「同此生尅，而先後之間，遂分吉凶」 — 무엇이 있느냐만이 아니라 어디에 있느냐가 길흉을 가른다',
  };
}

module.exports = { 병약, analyze };
