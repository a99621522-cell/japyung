/**
 * japgi.js — 16편 「論雜氣如何取用」
 * 사주팔자집 (2026-08-02)
 *
 * 「四墓者，沖氣也 … 以其所藏者多，用神不一，故謂之雜氣也。
 *  然而甚易也，**透干會支，取其清者用之，雜而不雜也**。」
 *
 * 이 편에서 얻은 것 넷.
 *
 * ① 취용 수단이 둘이다 — 透干과 會支.
 *    甲生辰月에 戊가 투간하면 편재를 쓰고, 癸면 정인, 乙이면 월겁.
 *    甲生辰月에 申·子가 회국하면 水印을 쓴다.
 *    나는 그동안 透干만 취용으로 보고 會支는 '변화'로만 다뤘는데, 원문은 대등하게 놓는다.
 *
 * ② 「一透則一用，兼透則兼用，透而又會，則透與會並用」
 *    잡기월의 격은 하나로 고정되지 않는다. 둘이면 둘을 겸용한다.
 *
 * ③ 겸용된 것들이 「合而有情則吉，合而無情則不吉」
 *    有情 = 順而相成 / 無情 = 逆而相背. 11편 순잡의 잡기월 확장이다.
 *    다만 여기서는 한 가지가 더 분명하다 —
 *    **극하는 대상이 기신(겁재·칠살)이면 상극이라도 도리어 유정하다.**
 *      癸生辰月 透戊爲官인데 申子 水局과 상극이나, 극당하는 것이 劫財라 무방
 *      丙生辰月 透戊爲食에 透壬爲煞이라 상극이나, 食神帶煞·煞逢食制는 도리어 貴
 *
 * ④ 「有情而卒成無情」 — 새 규칙 둘
 *    · 甲生辰月 逢壬爲印에 丙이 있으면 火가 土를 생해 辰중 戊를 도우니 印格不淸.
 *      단 壬이 투간하고 지지가 申子로 회국하면 丙이 있어도 무방하다.
 *    · 甲生辰月 透壬爲印인데 지지에 戌이 있으면 **辰戌沖으로 土動**하여
 *      干頭의 壬이 월령에 통하지 못해 印格이 서지 못한다 → 「富而不貴」
 */

const { GAN, JIJANGGAN, jeonggi, sipseong, JAPGI, yakTuchul } = require('./jijanggan');

const 生 = { 木:'火', 火:'土', 土:'金', 金:'水', 水:'木' };
const 剋 = { 木:'土', 土:'水', 水:'火', 火:'金', 金:'木' };
const 墓沖 = { 辰:'戌', 戌:'辰', 丑:'未', 未:'丑' };
const 忌神 = ['겁재', '비견', '편관', '상관', '편인'];
const POS = ['년', '월', '일', '시'];

function analyze(ctx, m) {
  if (!JAPGI.includes(m.wolJi)) {
    return { 잡기: false, 판정: '해당 없음',
      사유: `${m.wolJi}월은 사묘가 아니므로 잡기 취용을 논하지 않는다` };
  }

  const pool = [['년', m.yeonGan], ['월', m.wolGan], ['시', m.siGan]].filter(x => x[1]);
  const jip  = { 년: m.yeonJi, 월: m.wolJi, 일: m.ilJi, 시: m.siJi };

  // ① 透干 — 원문 자체가 弱透를 전제로 쓴다.
  //    「甲生辰月，透壬爲印」에서 辰의 지장간은 乙癸戊라 壬이 없다.
  //    辰중 癸(印)를 같은 오행인 壬으로 투출시킨 것을 透干으로 본 것이다.
  //    「丙生辰月，透戊爲食，而又透壬爲煞」의 壬도 마찬가지다.
  const 투간 = [];
  for (const jg of JIJANGGAN[m.wolJi]) {
    for (const [p, g] of pool) {
      if (g === jg.gan)
        투간.push({ 수단:'투간', 자리:p, 글자:g, 깊이:jg.wi, 십성:sipseong(m.ilGan, g) });
    }
  }
  for (const y of yakTuchul(m)) {
    for (const [p, g] of pool) {
      if (g !== y.gan) continue;
      if (투간.some(x => x.글자 === g && x.자리 === p)) continue;
      투간.push({ 수단:'투간', 자리:p, 글자:g, 깊이:y.wi, 약투:true, 원장간:y.원장간,
        십성: sipseong(m.ilGan, g) });
    }
  }

  // ① 會支 — 월지가 낀 삼합·방합
  const 회지 = [];
  for (const h of [...(ctx.합충?.지지?.삼합 ?? []), ...(ctx.합충?.지지?.방합 ?? [])]) {
    if (h.해소 || !h.지지.includes(m.wolJi) || !h.왕지) continue;
    회지.push({ 수단:'회지', 지지:h.지지.join(''), 화:h.화,
      십성: sipseong(m.ilGan, jeonggi(h.왕지)) });
  }

  const 용 = [...투간, ...회지];

  // ② 一透則一用，兼透則兼用，透而又會，則透與會並用
  const 겸용 = 용.length >= 2;
  const 겸용문 = 용.length === 0 ? '취용할 투간도 회지도 없어 정기로 본다'
    : 용.length === 1 ? `${용[0].수단} 하나뿐이라 하나를 쓴다 (一透則一用)`
    : 투간.length >= 2 && 회지.length >= 1 ? '투간이 둘이고 회지도 있어 함께 쓴다 (透與會並用)'
    : 투간.length >= 2 ? '둘이 함께 투간해 겸용한다 (兼透則兼用)'
    : '투간과 회지를 함께 쓴다 (透而又會)';

  // ③ 유정 / 무정
  const 정 = [];
  for (let i = 0; i < 용.length; i++) {
    for (let j = i + 1; j < 용.length; j++) {
      const A = 용[i], B = 용[j];
      const oa = 오행of(A, m), ob = 오행of(B, m);
      if (!oa || !ob) continue;
      let 관계 = null, from = null, to = null;
      if (生[oa] === ob)      { 관계 = '생'; from = A; to = B; }
      else if (生[ob] === oa) { 관계 = '생'; from = B; to = A; }
      else if (剋[oa] === ob) { 관계 = '극'; from = A; to = B; }
      else if (剋[ob] === oa) { 관계 = '극'; from = B; to = A; }
      if (!관계) { 정.push({ 짝:[라벨(A), 라벨(B)], 판정:'중', 설명:'서로 관여하지 않는다' }); continue; }

      // 극하는 대상이 기신이면 도리어 유정 —— 원문의 「無情而終爲有情」
      const 기신극 = 관계 === '극' && 忌神.includes(to.십성);
      const 유정 = 관계 === '생' ? true : 기신극;
      정.push({
        짝:[라벨(A), 라벨(B)], 관계, 판정: 유정 ? '유정' : '무정',
        설명: 관계 === '생'
            ? `${from.십성}이 ${to.십성}을 생하니 順而相成이다`
          : 기신극
            ? `${from.십성}이 ${to.십성}을 극하나 극당하는 것이 기신이라 도리어 有情이다`
            : `${from.십성}이 ${to.십성}을 극하니 逆而相背다`,
      });
    }
  }

  // ④ 有情而卒成無情 — 묘고가 충당하면 土가 動한다.
  //    다만 그 動함이 이로운지 해로운지는 17편(論墓庫刑沖之說)이 가른다.
  //    여기서는 발생 사실만 표시하고 가감은 17편에 넘긴다.
  const 충한자리 = POS.find(p => p !== '월' && jip[p] && 墓沖[m.wolJi] === jip[p]);
  const 토동 = 충한자리
    ? { 발생:true, 자리:충한자리, 상대:jip[충한자리],
        설명:`월지 ${m.wolJi}이 ${jip[충한자리]}(${충한자리})과 충해 土가 動하니, 천간이 월령에 통근하기 어려울 수 있다`,
        비고:'動한 土가 이로운지는 17편에서 가른다',
        원문:'二者爲朋沖而土動，干頭之壬難通月令，印格不成 … 富而不貴者也' }
    : { 발생:false };

  const 무정수 = 정.filter(x => x.판정 === '무정').length;
  return {
    잡기: true,
    투간, 회지, 겸용, 겸용문,
    정, 토동,
    판정: 용.length === 0 ? '취용 없음'
        : 무정수 ? '합이무정(合而無情)' : 정.some(x => x.판정 === '유정') ? '합이유정(合而有情)' : '중립',
    원문: '透干會支，取其清者用之，雜而不雜也',
  };

  function 오행of(x, m) {
    return x.수단 === '투간' ? GAN[x.글자].ohaeng : x.화;
  }
  function 라벨(x) {
    return x.수단 === '투간'
      ? `${x.십성}(${x.글자}${x.약투 ? `←${x.원장간}` : ''})`
      : `${x.십성}(${x.지지}국)`;
  }
}

module.exports = { analyze };
