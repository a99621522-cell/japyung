/**
 * sangsin.js — 15편 「論相神緊要」
 * 사주팔자집 (2026-08-02)
 *
 * 「月令既得用神，則別位亦必有相，若君之有相，輔我用神者是也。」
 *
 * 이 편에서 얻은 세 가지 — 앞선 편들에는 없던 것이다.
 *
 * ① 상신은 십성이 아니라 '글자'다
 *    「凡全局之格，賴此一字而成者，均謂之相也」
 *    官逢財生이면 財가 상신 …식으로 십성으로 부르는 것은 「一定之法，非通變之妙」라 하고,
 *    격을 이루게 한 바로 그 한 글자를 상신으로 본다.
 *    그래서 **지지도 상신이 된다** — 癸生亥月에 卯未가 와서 化水爲木하면 卯未가 상신이고,
 *    庚生申月에 子辰이 회국해 金水相涵을 이루면 子辰이 상신이다.
 *
 * ② 「傷用甚於傷身，傷相甚於傷用」
 *    격을 다치는 것보다 상신을 다치는 것이 더 심하다. 우선순위가 명시돼 있다.
 *
 * ③ 「相神無破，貴格已成；相神有傷，立敗其格」
 *    상신이 다치면 즉시 격이 깨진다. 원문이 든 두 예가 모두 '합거의 2차 효과'다.
 *      甲用酉官, 透丁逢癸 — 癸가 丁을 제어해 관을 지키니 癸가 상신인데,
 *        戊가 또 있으면 戊癸합에 묶여 丁을 못 제어한다 → 癸水之相傷矣
 *      丁用酉財, 透癸逢己 — 己가 癸를 제어해 재를 생하니 己가 상신인데,
 *        甲이 또 있으면 甲己합에 묶인다 → 己土之相傷矣
 *    「是皆有情而化無情，有用而成無用之格也」
 */

const { GAN, sipseong, jeonggi } = require('./jijanggan');
const 剋 = { 木:'土', 土:'水', 水:'火', 火:'金', 金:'木' };
const CHUNG = { 子:'午', 午:'子', 丑:'未', 未:'丑', 寅:'申', 申:'寅',
                卯:'酉', 酉:'卯', 辰:'戌', 戌:'辰', 巳:'亥', 亥:'巳' };
const POS = ['년', '월', '일', '시'];

/** 상신에 해당하는 실제 '글자'를 특정한다 */
function 상신글자(ctx, 상신십성, m) {
  const out = [];

  // 천간에서
  for (const [p, g] of [['년', m.yeonGan], ['월', m.wolGan], ['시', m.siGan]]) {
    if (!g) continue;
    const ss = sipseong(m.ilGan, g);
    if (ss === 상신십성) out.push({ 종류:'천간', 자리:p, 글자:g, 십성:ss });
    // '식상'·'관살'·'재관' 같은 묶음 표기도 받는다
    else if (상신십성 === '식상' && ['식신','상관'].includes(ss)) out.push({ 종류:'천간', 자리:p, 글자:g, 십성:ss });
    else if (상신십성 === '관살' && ['정관','편관'].includes(ss)) out.push({ 종류:'천간', 자리:p, 글자:g, 십성:ss });
    else if (상신십성 === '재관' && ['정재','편재'].includes(ss)) out.push({ 종류:'천간', 자리:p, 글자:g, 십성:ss });
  }

  // 지지 회국이 격을 이룬 경우 그 회국 지지들이 상신이다
  const 화 = ctx.합충?.월지?.화근거;
  if (out.length === 0 && ctx.변화?.발생 && 화?.지지) {
    const jip = { 년:m.yeonJi, 월:m.wolJi, 일:m.ilJi, 시:m.siJi };
    for (const j of 화.지지) {
      if (j === m.wolJi) continue;                    // 월지는 격이지 상신이 아니다
      const p = POS.find(x => jip[x] === j);
      if (p) out.push({ 종류:'지지(회국)', 자리:p, 글자:j, 십성:sipseong(m.ilGan, jeonggi(j)) });
    }
  }
  return out;
}

/** 상신이 다쳤는가 — 합거 / 인접 극 / 충 */
function 손상판정(ctx, 글자들, m) {
  const 상처 = [];
  const 간 = { 년:m.yeonGan, 월:m.wolGan, 일:m.ilGan, 시:m.siGan };
  const 지 = { 년:m.yeonJi, 월:m.wolJi, 일:m.ilJi, 시:m.siJi };

  for (const s of 글자들) {
    // ① 합거 — 원문이 든 두 예가 모두 이것
    if ((ctx.합거 ?? []).some(x => x.천간 === s.글자)) {
      상처.push({ ...s, 사유:'합', 설명:`상신 ${s.글자}(${s.자리})이 합에 묶여 제 일을 못 한다`,
        원문:'癸合戊而不制丁，癸水之相傷矣' });
      continue;
    }
    if (s.종류 === '천간') {
      // ② 인접한 글자에게 극당함.
      //    단 **일간은 제외한다** — 일간이 재를 극하는 것은 재를 쓰는 것이지 다치는 것이 아니다.
      //    또 원문이 든 傷相의 예는 둘 다 '합'이므로, 극은 참고로만 표시하고 立敗로 세지 않는다.
      const i = POS.indexOf(s.자리);
      for (const p of [POS[i-1], POS[i+1]].filter(Boolean)) {
        if (p === '일') continue;
        const g = 간[p];
        if (!g || g === s.글자) continue;
        if (剋[GAN[g].ohaeng] === GAN[s.글자].ohaeng) {
          상처.push({ ...s, 사유:'극', 참고만:true,
            설명:`상신 ${s.글자}(${s.자리})이 바로 옆 ${g}(${p})에게 극당한다`,
            원문:'相神有傷，立敗其格' });
          break;
        }
      }
    } else {
      // ③ 지지 상신이 충당함
      for (const p of POS) {
        if (지[p] && CHUNG[s.글자] === 지[p]) {
          상처.push({ ...s, 사유:'충', 설명:`상신 ${s.글자}(${s.자리})이 ${지[p]}(${p})에게 충당한다`,
            원문:'相神有傷，立敗其格' });
          break;
        }
      }
    }
  }
  return 상처;
}

/**
 * @param {object} r judge() 결과
 * @param {object} m 명식
 */
function analyze(r, m) {
  const ctx = r.ctx;
  if (!r.상신) {
    // 상신이 아예 잡히지 않은 것은 상신이 될 글자가 합에 묶였기 때문일 수 있다.
    //   「癸合戊而不制丁，癸水之相傷矣 … 是皆有情而化無情，有用而成無用之格也」
    const 합거 = ctx.합거 ?? [];
    const 상신후보 = ['정재','편재','정인','편인','식신','상관','정관','편관'];
    const 묶인후보 = 합거.filter(x => 상신후보.includes(x.십성));
    if (묶인후보.length) {
      return {
        상신:null, 글자:[], 손상:묶인후보.map(x => ({ ...x, 사유:'합' })),
        판정:'상신 유상(相神有傷)', 입패:true,
        설명:`상신이 될 ${묶인후보.map(x => `${x.십성}(${x.천간})`).join('·')}이 합에 묶여 제 일을 못 하니, 격을 떠받칠 글자가 남지 않았다`,
        원문:'是皆有情而化無情，有用而成無用之格也',
        우선순위:'傷相甚於傷用' };
    }
    return { 상신:null, 글자:[], 손상:[], 판정:'상신 없음',
      설명:'격을 이루게 한 글자를 지목할 수 없다', 입패:false, 우선순위:'傷相甚於傷用' };
  }

  const 글자 = 상신글자(ctx, r.상신, m);
  const 손상 = 글자.length ? 손상판정(ctx, 글자, m) : [];
  const 立敗손상 = 손상.filter(x => !x.참고만);
  const 온전 = 글자.length > 0 && 立敗손상.length < 글자.length;

  return {
    상신: r.상신,
    글자,
    손상,
    판정: 글자.length === 0 ? '글자 미특정'
        : 온전 ? '상신 무파(相神無破)' : '상신 유상(相神有傷)',
    설명: 글자.length === 0
        ? `${r.상신}을 상신으로 잡았으나 그에 해당하는 글자가 원국에 드러나지 않는다`
      : 온전
        ? `${글자.map(x => `${x.글자}(${x.자리})`).join('·')}이 격을 떠받치고 있으며 다치지 않았다`
        : `상신이 다쳤다 — ${손상.map(x => x.설명).join('; ')}`,
    입패: !온전 && 글자.length > 0,
    참고손상: 손상.filter(x => x.참고만),
    원문: 온전 ? '相神無破，貴格已成' : '相神有傷，立敗其格',
    우선순위: '傷用甚於傷身，傷相甚於傷用 — 격보다 상신을 먼저 지켜야 한다',
  };
}

module.exports = { analyze, 상신글자, 손상판정 };
