/**
 * unchung.js — 25편 「論行運」의 후반부
 * 사주팔자집 (2026-08-02)
 *
 * 「論運與看命，無二法也 … 運中每運行一字，即必以此一字，配命中八字而統觀之」
 *
 * 앞부분(희기 총론·似喜實忌)은 이미 chwiun.js에 반영했다.
 * 그 **뒤에 여섯 층이 더 있었고 전부 빠져 있었다.**
 *
 * ① 「行干而不行支」 — 丙生子月亥年，逢丙丁則幫身，逢巳午則相沖
 *    운의 천간과 지지가 같은 오행이라도 정반대로 작용한다.
 * ② 「行支而不行干」 — 甲生酉月，辛透而官猶弱，逢申酉則官植根，逢庚辛則混煞重官
 * ③ 「干同一類而不兩行」 — 丁生亥月年透壬官，逢丙則幫身，**逢丁則合官**
 *    같은 火인데 丙은 돕고 丁은 관을 합거해 없앤다.
 * ④ 「支同一類而不兩行」 — 戊生卯月巳年，逢申則自坐長生，**逢酉則會巳以傷官**
 * ⑤ 「同是相沖而分緩急」 — **沖年月則急，沖時日則緩**
 * ⑥ 「同是相沖而分輕重」 — **運本美而逢沖則輕，運既忌而又沖則重**
 * ⑦ 「逢沖而不沖」 — 甲用酉官，行卯則沖，而本命巳酉有相會，則沖無力；
 *    年支亥未，則卯逢年會而不沖月官
 * ⑧ 「一沖而得兩沖」 — 乙用申官，兩申並而不沖一寅，運又逢寅，
 *    則運與本命合成二寅，以沖二申
 */

const { GAN, jeonggi, sipseong } = require('./jijanggan');
const hapchung = require('./hapchung');

const CHUNG = { 子:'午', 午:'子', 丑:'未', 未:'丑', 寅:'申', 申:'寅',
                卯:'酉', 酉:'卯', 辰:'戌', 戌:'辰', 巳:'亥', 亥:'巳' };
const GANHAP = [['甲','己'],['乙','庚'],['丙','辛'],['丁','壬'],['戊','癸']];
const POS = ['년', '월', '일', '시'];

/** 운의 한 간지가 원국과 어떻게 맞물리는지 */
function analyze(un, ctx, m, 기본판정) {
  const 간 = { 년:m.yeonGan, 월:m.wolGan, 일:m.ilGan, 시:m.siGan };
  const 지 = { 년:m.yeonJi, 월:m.wolJi, 일:m.ilJi, 시:m.siJi };
  const 사건 = [];

  // ③ 운 천간이 원국 천간과 합해 그 글자를 묶는다
  for (const p of ['년', '월', '시']) {
    const g = 간[p];
    if (!g) continue;
    if (!GANHAP.some(h => h.includes(un.천간) && h.includes(g) && un.천간 !== g)) continue;
    const 묶인 = sipseong(m.ilGan, g);
    사건.push({
      종류:'운간합', 대상:`${묶인}(${g}·${p}간)`,
      효과: 묶인 === ctx.gyeok ? '격을 묶는다' : (묶인 === (ctx.상신 ?? '') ? '상신을 묶는다' : '해당 글자를 묶는다'),
      설명:`운의 ${un.천간}이 ${g}(${p}간)과 합해 ${묶인}을 묶는다. 같은 오행이라도 어느 글자가 오느냐로 갈리는 자리다`,
      원문:'干同一類而不兩行 — 逢丙則幫身，逢丁則合官',
      가감: (묶인 === ctx.gyeok || 묶인 === ctx.상신) ? -2 : 0,
    });
  }

  // ⑤⑥⑦⑧ 운 지지의 충
  for (const p of POS) {
    const j = 지[p];
    if (!j || CHUNG[un.지지] !== j) continue;

    // ⑦ 逢沖而不沖 — 원국에서 그 지지가 회합에 묶여 있으면 충이 무력하다
    const 회합 = [...(ctx.합충?.지지?.삼합 ?? []), ...(ctx.합충?.지지?.방합 ?? []),
                  ...(ctx.합충?.지지?.반합 ?? []), ...(ctx.합충?.지지?.육합 ?? [])]
      .find(h => !h.해소 && h.지지.includes(j));
    // 운 지지 자신이 원국 지지와 회합해 충으로 가지 않는 경우도 같다
    const 운회합 = POS.map(q => 지[q]).filter(Boolean)
      .some(x => hapchung.SAMHAP.some(s => s.ji.includes(un.지지) && s.ji.includes(x) && x !== j)
              || hapchung.YUKHAP.some(s => s.ji.includes(un.지지) && s.ji.includes(x)));

    if (회합 || 운회합) {
      사건.push({
        종류:'충이 풀림', 대상:`${j}(${p}지)`,
        설명:`운의 ${un.지지}이 ${j}(${p}지)를 충하려 하나, ${회합 ? `${회합.지지.join('')}이 모여 있어` : '운의 글자가 다른 지지와 먼저 회합해'} 충이 힘을 잃는다`,
        원문:'逢沖而不沖 — 本命巳酉有相會，則沖無力', 가감:0,
      });
      continue;
    }

    // ⑤ 緩急 ⑥ 輕重
    const 급 = ['년', '월'].includes(p);
    // 판정어는 바뀔 수 있으므로 이름으로 거르지 않는다 — 「눌림」이 들어가면 흉운이다
    const 흉운 = /눌림/.test(기본판정) || ['흉', '대흉'].includes(기본판정);
    사건.push({
      종류:'충', 대상:`${j}(${p}지)`,
      완급: 급 ? '급(急)' : '완(緩)',
      경중: 흉운 ? '중(重)' : '경(輕)',
      설명:`운의 ${un.지지}이 ${j}(${p}지)를 충한다. ${급 ? '년·월을 충하는 것은 급하게 오고' : '일·시를 충하는 것은 더디게 오고'}, ${흉운 ? '본래 꺼리는 운에 충까지 겹치니 무겁다' : '본래 좋은 운이라 충이 있어도 가볍다'}`,
      원문:'沖年月則急，沖時日則緩 / 運本美而逢沖則輕，運既忌而又沖則重',
      가감: 흉운 ? -1 : 0,
    });
  }

  // ⑧ 一沖而得兩沖 — 원국에 같은 지지가 둘 있어 못 충하던 것이 운에서 하나 더 와 성립.
  //    단 ⑦로 이미 충이 풀린 자리라면 양충도 서지 않는다.
  const 충풀림 = 사건.some(x => x.종류 === '충이 풀림');
  const 원국충대상 = POS.map(p => 지[p]).filter(x => x && CHUNG[x] === un.지지);
  if (!충풀림 && 원국충대상.length >= 2) 사건.push({
    종류:'양충', 대상:`${원국충대상.join('·')}`,
    설명:`원국에 ${원국충대상[0]}이 둘 나란해 한쪽이 다른 하나를 충하지 못하고 있었는데, 운에서 ${un.지지}이 와 둘이 되니 두 자리를 함께 충한다`,
    원문:'一沖而得兩沖 — 運與本命，合成二寅，以沖二申', 가감:-1,
  });

  // ④ 운 지지가 원국 지지와 회국해 없던 십성을 만든다
  for (const s of hapchung.SAMHAP) {
    if (!s.ji.includes(un.지지)) continue;
    const 짝 = POS.filter(p => 지[p] && s.ji.includes(지[p]) && 지[p] !== un.지지);
    if (짝.length < 1) continue;
    const 생긴십성 = sipseong(m.ilGan, jeonggi(s.wang));
    if (생긴십성 === un.지지십성) continue;
    사건.push({
      종류:'운지회국', 대상:`${[un.지지, ...짝.map(p => 지[p])].join('')}`,
      설명:`운의 ${un.지지}이 ${짝.map(p => `${지[p]}(${p}지)`).join('·')}과 모여 ${s.hwa}로 化하니, ${un.지지십성}으로 오던 것이 ${생긴십성}으로 작용한다`,
      원문:'支同一類而不兩行 — 逢申則自坐長生，逢酉則會巳以傷官',
      생긴십성, 가감:0,
    });
  }

  const 가감 = 사건.reduce((s, x) => s + (x.가감 ?? 0), 0);
  return {
    사건, 가감,
    총론: '운의 천간과 지지는 같은 오행이라도 정반대로 작용할 수 있다. 한 글자씩 원국에 대어 보는 것이 원문의 방식이다',
  };
}

module.exports = { analyze };
