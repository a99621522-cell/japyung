/**
 * @param {object} m 명식 {yeonGan..siJi}
 * @returns 조문 판정 (없는 일간·달이면 {해당없음:true})
 */
function analyze(m) {
  const 일 = m.ilGan, 월 = m.wolJi;
  if (!표[일] || !표[일][월]) return { 해당없음: true, 사유: `${일}일간 ${월}월은 아직 조문화되지 않음` };
  const 칸 = 표[일][월];
  const c = ctx만들기(m);
  const 걸린 = [];
  for (const j of 칸.조문) {
    if (j.월 && j.월 !== 월) continue;
    let ok = false; try { ok = !!j.조건(c); } catch (e) {}
    if (ok) 걸린.push(j);
  }
  const 판정들 = 걸린.filter(j => j.종류 === '판정');
  const 주 = 판정들[0] || null;                 // 원문 순서 = 우선순위
  const 방향 = 주 ? 방향찾기(주.판정) : null;
  return {
    해당없음: false, 일간: 일, 월: 월,
    용: 칸.용, 기: 칸.기, 요지: 칸.요지,
    주판정: 주 ? { id: 주.id, 원문: 주.원문, 판정어: 주.판정, 방향, 결: 주.결, 결말: 방향 ? 결말[방향] : null } : null,
    바탕: 걸린.filter(j => j.종류 === '바탕').map(j => ({ id:j.id, 원문:j.원문, 결:j.결 })),
    흠:   걸린.filter(j => j.종류 === '흠').map(j => ({ id:j.id, 원문:j.원문, 결:j.결 })),
    완화: 걸린.filter(j => j.종류 === '완화').map(j => ({ id:j.id, 원문:j.원문, 결:j.결 })),
    그밖의판정: 판정들.slice(1).map(j => ({ id:j.id, 원문:j.원문, 판정어:j.판정, 방향:방향찾기(j.판정), 결:j.결 })),
    걸린수: 걸린.length,
    조문수: 칸.조문.length,
  };
}

