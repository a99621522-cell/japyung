function ctx만들기(m) {
  const 천간 = [m.yeonGan, m.wolGan, m.siGan].filter(Boolean);        // 일간 제외
  const 지지 = [m.yeonJi, m.wolJi, m.ilJi, m.siJi].filter(Boolean);
  const 지장 = [];                                                    // 지지 속 글자 전부
  for (const j of 지지) for (const h of (JIJANGGAN[j] || [])) 지장.push(h.gan);
  const 정기 = 지지.map(j => { const h = (JIJANGGAN[j] || []).find(x => x.wi === '정기'); return h ? h.gan : null; }).filter(Boolean);
  return { m, 일간: m.ilGan, 천간, 지지, 지장, 정기, 월지: m.wolJi };
}
