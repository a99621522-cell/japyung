function 관계of(ilGan, a, b) {
  const oa = GAN[a].ohaeng, ob = GAN[b].ohaeng;
  if (生[oa] === ob) return { 방향:[a,b], 종류:'생' };
  if (生[ob] === oa) return { 방향:[b,a], 종류:'생' };
  if (剋[oa] === ob) return { 방향:[a,b], 종류:'극' };
  if (剋[ob] === oa) return { 방향:[b,a], 종류:'극' };
  return null;
}

function sunjap(ctx, m) {
  if (!m) return { 판정:'해당 없음', 항목:[], 감점:0, 사유:'명식 정보 없음' };

  const pool = [m.yeonGan, m.wolGan, m.siGan].filter(Boolean);   // 일간 제외
  const 투출 = JIJANGGAN[m.wolJi].filter(jg => pool.includes(jg.gan));

  if (투출.length < 2) {
    return { 판정:'해당 없음', 항목:[], 감점:0,
      사유:'월령에서 둘이 함께 투출하지 않아 순잡을 논하지 않는다 (互用이 아님)' };
  }

  const 항목 = [];
  for (let i = 0; i < 투출.length; i++) {
    for (let j = i + 1; j < 투출.length; j++) {
      const A = 투출[i].gan, B = 투출[j].gan;
      const rel = 관계of(ctx.ilGan, A, B);
      const ssA = sipseong(ctx.ilGan, A), ssB = sipseong(ctx.ilGan, B);
      if (!rel) {
        항목.push({ 짝:[A,B], 십성:[ssA,ssB], 종류:'무관', 판정:'중',
          설명:`${ssA}(${A})과 ${ssB}(${B})이 생극 관계가 아니라 서로 관여하지 않는다` });
        continue;
      }
      // 「壬印戊財，以乙隔之，水與土不相碍」 —
      // 서로 극하는 사이라도 다른 글자가 끼어 떨어져 있으면 부딪히지 않는다.
      const 자리of = g => ['년','월','시'][[m.yeonGan, m.wolGan, m.siGan].indexOf(g)];
      const pA = 자리of(A), pB = 자리of(B);
      const 인접 = Math.abs(['년','월','일','시'].indexOf(pA) - ['년','월','일','시'].indexOf(pB)) === 1;

      const [from, to] = rel.방향;
      const key = `${sipseong(ctx.ilGan, from)}>${sipseong(ctx.ilGan, to)}`;
      const ok = 得當[key];
      const 방향설명 = `${sipseong(ctx.ilGan, from)}(${from})이 ${sipseong(ctx.ilGan, to)}(${to})을 ${rel.종류}한다`;
      const 격리 = ok === false && rel.종류 === '극' && !인접;
      항목.push({
        짝:[A,B], 십성:[ssA,ssB], 종류:rel.종류, 자리:[pA,pB], 격리,
        판정: 격리 ? '중' : ok === true ? '순' : ok === false ? '잡' : '중',
        설명: 격리
            ? `${sipseong(ctx.ilGan, from)}(${from})과 ${sipseong(ctx.ilGan, to)}(${to})이 상극이나 사이에 글자가 끼어 서로 방해하지 않는다 — 「以乙隔之，兩不相碍」`
          : ok === true
            ? `${방향설명} — ${rel.종류 === '극' ? '相剋而得其當' : '兩相得'}`
          : ok === false
            ? `${방향설명} — ${rel.종류 === '생' ? '相生而適爲累' : '兩不相謀'}`
            : `${방향설명} — 마땅함을 단정하기 어렵다`,
      });
    }
  }

  const 잡수 = 항목.filter(x => x.판정 === '잡').length;
  const 순수 = 항목.filter(x => x.판정 === '순').length;

  return {
    판정: 잡수 ? '잡(雜)' : 순수 ? '순(純)' : '중립',
    항목, 감점: 잡수 * 0.25,
    원문: '純者吉，雜者凶',
    사유: `월령 ${투출.map(x => x.gan).join('·')}이 함께 투출해 互用한다`,
  };
}

// ─────────────────────────────────────────────
