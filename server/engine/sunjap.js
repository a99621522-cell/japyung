/*
 원문이 세운 축은 딱 둘이다.
   「其理之大綱，亦在有情無情、有力無力之間而已。」

 有情 — 배합이 서로를 풀어주는가
   · 甲透酉官，透丁合壬，是謂合傷存官   → 합으로 기신을 치우면 유정
   · 財忌比肩，而與煞作合，劫反爲用     → 꺼리던 글자가 합으로 쓰임이 되면 유정
   · 正官佩印，不如透財，而四柱帶傷，反推佩印 → 사주가 요구하는 것이 놓였으면 유정
   · 癸尅不如壬合                       → 극으로 치우는 것은 합으로 치우는 것만 못하다

 有力 — 격·상신·일간 세 축이 모두 힘이 있고 고른가
   · 身强煞露而食神又旺，三者皆備，極品之貴
   · 官强財透而身坐祿刃，三者皆均，遂成大貴

 無情 — 넘치는 것을 더 돕는 배합
   · 印用七煞이나 身强印旺이면 도리어 孤貧 (身旺不勞印生，印旺何勞煞助)
   · 傷官佩印이나 身旺·傷淺·印重이면 不貴不秀

 無力 — 한 축이 뿌리를 잃음
   · 煞强食旺而身無根 / 身强比重而財無氣 → 或夭或貧
*/

const 群G = { 재:['정재','편재'], 인:['정인','편인'], 식상:['식신','상관'],
             관살:['정관','편관'], 비겁:['비견','겁재'] };
const 그룹of = { 정재:'재', 편재:'재', 정인:'인', 편인:'인', 식신:'식상', 상관:'식상',
                정관:'관살', 편관:'관살', 관살:'관살', 식상:'식상', 재관:'재',
                비견:'비겁', 겁재:'비겁', 건록:'비겁', 양인:'비겁' };

/** 격 자체의 힘 = 그 십성 그룹의 세력 */
function 힘of(ctx, 십성) {
  const g = 그룹of[십성];
  return g ? (ctx.sery[g] ?? 0) : 0;
}

function godo(ctx, 상신, m, opt = {}) {
  if (!상신 && opt.고관무보) {
    const 합거 = (ctx.합거 ?? []).map(x => `${x.십성}(${x.천간})`);
    return { 판정:'상신 없음', 고관무보:true, 축:{ 유정:null, 유력:null },
      사유: 합거.length
        ? `상신이 될 재·인이 합거되어 孤官無輔 — 합거: ${합거.join(', ')}`
        : '격은 섰으나 도와줄 상신이 없다 (孤官無輔)' };
  }
  if (!상신) return { 판정:'평가 불가', 사유:'상신 미지정 (격이 성립하지 않음)' };

  // ── 有力 : 격 · 상신 · 일간 세 축 ─────────────
  // 다만 일간에게 요구되는 방향은 국마다 다르다.
  //   煞用食制는 「身健」이 조건이지만,
  //   傷官佩印은 「反要傷官旺，身稍弱，始爲秀氣」라 도리어 약해야 한다.
  //   印用煞도 「身旺不勞印生」이니 왕할 이유가 없다.
  // 그래서 일간은 절대값이 아니라 '요구 방향과 맞는가'로 잰다.
  const 일간요구 = {
    '편관|식신':'강', '편관|상관':'강', '편관|양인':'강',
    '정재|식신':'강', '편재|식신':'강', '정재|정관':'강', '편재|정관':'강',
    '정관|정재':'강', '건록|정관':'강', '건록|식상':'강', '양인|관살':'강',
    '상관|정인':'약', '편관|정인':'약', '정인|편관':'약', '편인|편관':'약',
    '정관|정인':'약',
  }[`${ctx.gyeok}|${상신}`] ?? '중';

  const 격힘   = 힘of(ctx, ctx.gyeok);
  const 상신힘 = 힘of(ctx, 상신);
  const 일간실 = (ctx.통근?.score ?? 0) + (ctx.sery.비겁 ?? 0) * 0.3;
  const 일간힘 = 일간요구 === '약'
    ? (일간실 <= 1.2 ? 1.2 : Math.max(0.3, 2.4 - 일간실))   // 약할수록 부합
    : 일간실;

  const 삼자 = [격힘, 상신힘, 일간힘];
  const 최소 = Math.min(...삼자), 최대 = Math.max(...삼자);

  const 皆備 = 최소 >= 1.0;
  const 皆均 = 최대 > 0 && 최소 / 최대 >= 0.5;
  const 무근 = 최소 < 0.3;

  // 원문은 皆備와 皆均을 **각각의 사례**로 든다 —
  //   「身强煞露而食神又旺，**三者皆備**，極品之貴」
  //   「官强財透而身坐祿刃，**三者皆均**，遂成大貴」
  // 둘 다여야 하는 것이 아니므로 어느 한쪽이면 有力으로 본다. 한 축이 무근이면 無力이다.
  const 유력성립 = !무근 && (皆備 || 皆均);
  const 유력사유 = 무근
    ? '격·상신·일간 세 축 가운데 하나가 뿌리를 잃었다'
    : (皆備 && 皆均) ? '격·상신·일간 셋이 모두 갖춰지고 고르다 (三者皆備·皆均)'
    : 皆備 ? '격·상신·일간 셋이 모두 갖춰졌다 (三者皆備)'
    : 皆均 ? '격·상신·일간 셋이 고르다 (三者皆均)'
    : '세 축이 모두 얇다';

  // ── 有情 : 배합이 서로를 풀어주는가 ────────────
  const 유정근거 = [], 무정근거 = [];

  // 합으로 기신을 치웠는가 — 극으로 치우는 것보다 낫다
  for (const h of (ctx.합거 ?? [])) {
    if (['상관', '편관', '편인', '겁재'].includes(h.십성))
      유정근거.push(`${h.십성}(${h.천간})이 합으로 치워졌다 — 「癸尅不如壬合」`);
  }
  // 패격을 구응이 풀었는가
  if ((ctx.구응수 ?? 0) > 0) 유정근거.push('깨질 자리를 다른 글자가 풀어냈다');
  // 사주가 요구하는 상신이 놓였는가 — 상관이 있는데 인수를 상신으로 쓴 경우
  if (상신 === '정인' && (ctx.cheongan['상관']?.length || ctx.합국?.['상관']?.length))
    유정근거.push('상관이 있는 사주에 인수가 놓였다 — 「四柱帶傷，反推佩印」');

  // 無情 : 넘치는 것을 더 돕는 배합
  if (['정인','편인'].includes(ctx.gyeok) && 상신 === '편관' && ctx.신강 && ctx.sery.인 >= 2.5)
    무정근거.push('몸도 인수도 왕한데 칠살로 인수를 더 생한다 — 「身旺不勞印生，印旺何勞煞助」');
  if (ctx.gyeok === '상관' && 상신 === '정인' && ctx.신강 && ctx.sery.식상 < 1.2 && ctx.sery.인 >= 2.5)
    무정근거.push('몸이 왕하고 상관은 얕은데 인수가 너무 무겁다 — 「要此重印何用」');
  if (ctx.상신손상)
    무정근거.push('격을 떠받치는 상신이 다쳤다 — 「相神有傷，立敗其格」');
  // ── 11편 「用神純雜」 ─────────────────────────
  // 「純者吉，雜者凶」 — 둘이 함께 투출했을 때 서로 도모하는가로 갈린다.
  // 잡이면 무정, 순이면 유정을 뚜렷하게 한다. 원문이 대립쌍으로 썼으므로 양쪽 다 반영한다.
  if (ctx.순잡판정 === '잡(雜)')
    무정근거.push('월령에서 함께 투출한 두 글자가 서로 도모하지 않는다 — 「雜者凶」');
  else if (ctx.순잡판정 === '순(純)')
    유정근거.push('월령에서 함께 투출한 둘이 서로 도모한다 — 「純者吉」');
  if ((ctx.패격수 ?? 0) > 0 && (ctx.구응수 ?? 0) === 0)
    무정근거.push('격을 깨뜨리는 글자가 풀리지 않은 채 남아 있다');

  // ── 15편 「相神緊要」의 극 ────────────────────
  // 「相神有傷，立敗其格」 — 원문은 「상한다」고만 했고 든 예 둘이 다 「합」이다.
  //   그래서 성패(9편)는 합만 立敗로 세고 극은 참고로 둔다 (sangsin.js 참조).
  //   다만 극도 상신의 힘을 깎는 것은 사실이고, 5편·11편이 이미 「붙으면 서로 못 쓴다」를
  //   격 판정에 쓰고 있으므로, 고저(12편)에는 낮은 무게로 반영한다.
  //   ※ 원문이 굳이 합 예만 든 데 뜻이 있을 수 있다 — 판단이 바뀌면 이 줄만 지우면 된다.
  if ((ctx.상신참고손상 ?? []).some(x => x.사유 === '극'))
    무정근거.push('격을 떠받치는 글자가 바로 옆에서 극당한다 — 立敗는 아니나 힘이 깎인다');

  // ── 20편 「生尅先後分吉凶」 ─────────────────────
  // 「同此生尅，而先後之間，遂分吉凶」 — 무엇이 있느냐만이 아니라 어디에 있느냐다.
  // 성패(9편)는 조문이 정하므로 건드리지 않고, 고저(12편)에만 반영한다.
  //   병이 시주에 있으면 「돌아가 머무는 자리(歸宿之地)」가 상한 것이라 무정으로 본다.
  //   약이 시주에 있으면 도리어 유정을 더 뚜렷하게 한다.
  if (ctx.선후?.병이시 && !ctx.선후?.약이뒤)
    무정근거.push('격을 해치는 글자가 시주에 놓였다 — 「歸宿之地」가 상했다');
  else if (ctx.선후?.약이시)
    유정근거.push('격을 푸는 글자가 시주에 놓였다 — 말년의 결국이 있다');
  else if (ctx.선후?.약이뒤)
    유정근거.push('병보다 약이 뒤에 놓였다 — 앓다가 낫는 배치');

  // ── 14편 「用神配氣候得失」 ────────────────────
  // 「遭時不順，雖有奇才，成功不易」 — 계절이 어긋나면 격이 서도 힘을 못 쓴다.
  // 조후가 급한데 그것을 푸는 글자가 없으면 무정으로 본다.
  if (ctx.기후?.급함 && !ctx.기후?.해소)
    무정근거.push('계절이 급한데 그것을 푸는 글자가 없다 — 「遭時不順」');
  else if (ctx.기후?.급함 && ctx.기후?.해소)
    유정근거.push('급한 계절을 푸는 글자가 갖춰졌다 — 「生得其時」');

  // ── 17편 「墓庫刑沖之說」 ─────────────────────
  // 「四庫之中…終以土爲主，沖則土靈」 — 사고를 충하면 그 土만 動한다.
  // 動한 것이 재·정관이면 창고가 열리고(庫啟), 겁재·상관이면 도리어 누(累)가 된다.
  //   충 자체가 좋고 나쁜 것이 아니라 **무엇이 動했느냐**로 갈리므로 고저에 반영한다.
  if (ctx.묘고?.누)
    무정근거.push('창고를 충해 겁재·상관이 動했다 — 「沖則反爲累」');
  else if (ctx.묘고?.고계 && !ctx.묘고?.이미투출)
    유정근거.push('창고를 충해 재·정관이 動했다 — 「沖則庫啟」');

  // ── 27편 「喜忌干支有別」 ─────────────────────
  // 「干主天，動而有爲；支主地，靜以待用」
  // 상신이 지지에만 있고 천간에 안 나왔으면 아직 나서지 않은 것이라 힘이 덜하다.
  if (ctx.상신지지only)
    무정근거.push('격을 떠받치는 것이 지지에만 있어 아직 나서지 않았다 — 「靜以待用」');

  // 有情과 無情은 원문에서 대립쌍이다 — 「有情無情、有力無力之間而已」.
  // 특정 사건(합거·구응)이 있어야 有情인 것이 아니라, **無情이 아니면 有情 쪽**이다.
  // 유정근거는 그 有情을 더 뚜렷하게 하는 것일 뿐 성립 요건이 아니다.
  const 유정성립 = 무정근거.length === 0;

  // 원문의 네 상태 — 「有情兼有力」이 가장 높고, 둘 다 아니면 아직 갖춰지지 않은 것이다.
  const 판정 = 유정성립 && 유력성립 ? '유정겸유력(有情兼有力)'
             : 유정성립 ? '유정(有情)'
             : 유력성립 ? '유력(有力)'
             : '아직 갖춰지지 않음';

  return {
    판정,
    축: {
      유정: { 성립:유정성립, 근거:유정근거, 흠:무정근거 },
      유력: { 성립:유력성립, 사유:유력사유,
              세축:{ 격:+격힘.toFixed(2), 상신:+상신힘.toFixed(2), 일간:+일간힘.toFixed(2) },
              일간요구, 일간실측:+일간실.toFixed(2) },
    },
    사유: [유력사유, ...무정근거, ...유정근거].filter(Boolean).join(' / '),
    주의: '「或一字而有千鈞之力，或半字而敗全局之美」 — 고저는 미세한 자리에서 갈리므로 등급을 단정적으로 읽지 말 것',
  };
}

