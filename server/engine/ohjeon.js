/**
 * @param {object} r judge() 결과
 * @param {object} m 명식
 * @param {object} opt { 시주불확실:boolean }
 */
function analyze(r, m, opt = {}) {
  const 불확실 = opt.시주불확실 === true || !m.siGan || !m.siJi;
  if (!불확실) {
    return { 시주불확실:false, 영향:[], 판정:'시주 확정',
      주의:'원문은 「사람의 시주는 확실치 않은 경우가 많고 본인도 모른다」고 했다. 시주가 확실한지 한 번 더 확인할 값어치가 있다',
      원문:'人之八字，時多未確，即彼本身，亦不自知' };
  }

  const 영향 = [...시주의존];
  // 실제로 시주에 걸린 것이 있으면 구체적으로 짚는다
  const 구체 = [];
  if (m.siGan && r.상신) {
    const { sipseong } = require('./jijanggan');
    if (sipseong(m.ilGan, m.siGan) === r.상신)
      구체.push(`상신 ${r.상신}이 시간 ${m.siGan}에 놓여 있다 — 시주가 달라지면 격의 성패 자체가 달라진다`);
    if (sipseong(m.ilGan, m.siGan) === r.ctx.gyeok)
      구체.push(`격과 같은 ${r.ctx.gyeok}이 시간에 있다`);
  }

  return {
    시주불확실:true, 영향, 구체,
    판정:'시주 미확정 — 아래 항목의 신뢰도가 낮다',
    설명:'시주가 확실하지 않으면 자녀·말년에 관한 것과 시주가 끼는 회국·형충 판정은 그대로 믿기 어렵다. 원문 자신이 「사람의 시주는 확실치 않은 경우가 많고 본인도 모른다」고 인정한 부분이다',
    원문:'人之八字，時多未確，即彼本身，亦不自知',
  };
}

