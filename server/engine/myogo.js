/**
 * myogo.js — 17편 「論墓庫刑沖之說」
 * 사주팔자집 (2026-08-02)
 *
 * 이 편은 통설을 반박하는 편이다.
 *
 * 「『辰戌丑未，最喜刑沖。財官入庫，不沖不發。』
 *   此說雖俗書盛稱之，然子平先生造命，無是說也。
 *   夫雜氣透干會支，豈不甚美？又何勞刑沖乎？」
 *
 * — 잡기는 16편대로 透干·會支로 취용하면 그만이지 형충이 필요 없다.
 *   「不沖不發」은 속서의 말이고 자평의 법이 아니다.
 *
 * 그리고 충이 실제로 무엇을 하는지 못박는다.
 *
 * 「況四庫之中，雖五行俱有，而**終以土爲主**。**沖則土靈**，
 *   金木水火，豈能以四庫之沖而動乎？」
 *
 * — 사고를 충하면 **土만 動한다.** 금목수화는 사고의 충으로 動하지 않는다.
 *   그러니 창고 안의 재관이 무엇이냐가 아니라, **그 土가 일간에게 무엇이냐**가 문제다.
 *
 * 「故財官屬土，沖則庫啟。如甲用戊財而辰戌沖，壬用己官而丑未沖之類是也。
 *   然終以戊己干頭爲清，用干之既透，即不沖而亦得也。
 *   至於財官爲水，沖則反爲累。
 *   如己生辰月，壬透爲財，戌沖則**劫動**，何益之有？
 *   丁生辰月，透壬爲官，戌沖則**傷動**，豈能無害？」
 *
 * 16편에서 나는 「辰戌沖으로 土動하면 통근이 어렵다」를 일률로 감점했는데,
 * 17편은 그것을 갈라놓는다 — 動한 土가 재관이면 창고가 열리고,
 * 겁재·상관이면 겁이 動하고 상관이 動해 도리어 누가 된다.
 */

const { GAN, JIJANGGAN, jeonggi, sipseong, JAPGI } = require('./jijanggan');

const 墓沖 = { 辰:'戌', 戌:'辰', 丑:'未', 未:'丑' };
const POS = ['년', '월', '일', '시'];
// 원문이 명시한 것은 둘뿐이다.
//   庫啟 — 動한 土가 재·정관일 때 (甲用戊財而辰戌沖 / 壬用己官而丑未沖)
//   累   — 動한 土가 겁재·상관일 때 (戌沖則劫動 / 戌沖則傷動)
// 나머지(정인·식신·비견 등)는 원문에 없으므로 단정하지 않고 중립으로 둔다.
const 庫啟십성 = ['정재', '편재', '정관'];
const 累십성   = ['겁재', '상관', '편관', '편인'];

function analyze(ctx, m) {
  if (!JAPGI.includes(m.wolJi)) {
    return { 해당:false, 판정:'해당 없음',
      사유:`${m.wolJi}월은 사고가 아니므로 묘고 형충을 논하지 않는다` };
  }

  const jip = { 년:m.yeonJi, 월:m.wolJi, 일:m.ilJi, 시:m.siJi };
  const 충자리 = POS.find(p => p !== '월' && jip[p] && 墓沖[m.wolJi] === jip[p]);

  if (!충자리) {
    return { 해당:true, 충:false, 판정:'충 없음', 가감:0,
      사유:'월지가 충당하지 않는다',
      속설반박:'「재관이 창고에 들면 충하지 않으면 발하지 않는다」는 속서의 말이고 자평의 법이 아니다. 잡기는 투간·회지로 취용하면 그만이라 형충을 빌릴 일이 없다',
      원문:'此說雖俗書盛稱之，然子平先生造命，無是說也' };
  }

  // 사고의 주인은 土다. 충하면 그 土만 動한다.
  const 토 = jeonggi(m.wolJi);
  const 토십성 = sipseong(m.ilGan, 토);
  const 토투출 = [m.yeonGan, m.wolGan, m.siGan].filter(Boolean).includes(토);

  // 창고 안의 금목수화는 충으로 動하지 않는다 — 무엇이 잠자는지 밝혀둔다
  const 안잠긴것 = JIJANGGAN[m.wolJi]
    .filter(x => GAN[x.gan].ohaeng !== '土')
    .map(x => `${sipseong(m.ilGan, x.gan)}(${x.gan})`);

  const 고계 = 庫啟십성.includes(토십성);
  const 누 = 累십성.includes(토십성);

  if (!고계 && !누) {
    return {
      해당:true, 충:true, 충자리, 충지지:jip[충자리],
      동한것:{ 글자:토, 십성:토십성, 투출:토투출 }, 안잠긴것,
      판정:`${토십성}이 動함 — 원문에 없는 경우`,
      설명:`월지 ${m.wolJi}이 ${jip[충자리]}(${충자리})과 충해 ${토십성} ${토}가 動한다. 원문은 재·정관이 動하면 창고가 열리고 겁재·상관이 動하면 누가 된다고만 했을 뿐 이 경우는 다루지 않았으므로, 이롭다 해롭다 단정하지 않는다`,
      주의:`사고를 충하면 土만 動한다. ${안잠긴것.length ? `창고 안의 ${안잠긴것.join('·')}은 충으로 움직이지 않는다` : ''}`,
      원문:'四庫之中…終以土爲主，沖則土靈',
    };
  }

  return {
    해당:true, 충:true, 충자리, 충지지:jip[충자리],
    동한것:{ 글자:토, 십성:토십성, 투출:토투출 },
    안잠긴것,
    // 고저(12편)로 넘길 플래그 — 충이 아니라 動한 것이 무엇이냐가 갈림점이다
    고계, 누, 이미투출:토투출,
    판정: 고계 ? (토투출 ? '고계(庫啟) — 다만 이미 투출해 충이 긴요치 않다' : '고계(庫啟)')
                : `${토십성}이 動함 — 累가 된다`,
    설명: 고계
      ? (토투출
          ? `월지 ${m.wolJi}이 ${jip[충자리]}(${충자리})과 충해 ${토십성} ${토}가 動하나, 이미 천간에 투출해 있으므로 충이 없어도 얻는다`
          : `월지 ${m.wolJi}이 ${jip[충자리]}(${충자리})과 충해 ${토십성} ${토}가 動하니 창고가 열린다`)
      : `월지 ${m.wolJi}이 ${jip[충자리]}(${충자리})과 충해 ${토십성} ${토}가 動하니, 창고가 열리는 것이 아니라 도리어 누가 된다`,
    주의: `사고를 충하면 土만 動한다. ${안잠긴것.length ? `창고 안의 ${안잠긴것.join('·')}은 충으로 움직이지 않는다` : ''}`,
    원문: 고계
      ? '財官屬土，沖則庫啟 … 然終以戊己干頭爲清，用干之既透，即不沖而亦得也'
      : '至於財官爲水，沖則反爲累 … 戌沖則劫動，何益之有',
  };
}

module.exports = { analyze, 墓沖, 庫啟십성 };
