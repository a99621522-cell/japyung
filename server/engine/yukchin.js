/**
 * yukchin.js — 23편 「論宮分用神配六親」
 * 사주팔자집 (2026-08-02)
 *
 * 「人有六親，配之八字，亦存於命。」
 *
 * 육친 배속에는 **두 축**이 있고 원문은 이를 나란히 놓는다.
 *
 * ① 宮分으로 배속 — 「年月日時，自上而下，**祖父妻子**，亦自上而下」
 *    자리 순서가 곧 항렬 순서다. 年=祖, 月=父, 日=妻, 時=子.
 *    (기존 구현은 月을 '부모·형제', 日을 '자신·배우자'로 뭉뚱그렸는데
 *     원문은 月=父, 日=妻로 더 좁게 잡는다. 일간이 나이고 일지가 처다.)
 *
 * ② 用神(십성)으로 배속 — 원문은 외우게 하지 않고 **유도한다**
 *    正印爲母 — 「身所自出，取其生我也」
 *    偏財爲父 — 「若偏財受我克制，何反爲父？**偏財者，母之正夫也**」
 *               정인이 어머니이니, 그 어머니의 정부(正夫)가 곧 편재다
 *    正財爲妻 — 「受我克制，夫爲妻綱，妻則從夫」
 *    官煞爲子女 — 「若官煞則克制乎我，何以反爲子女也？**官煞者，財所生也**」
 *                 재가 처첩이니 처가 낳은 것이 관살이다
 *    比肩爲兄弟 — 「又理之顯然者」
 *
 * ③ **빠져 있던 층** — 육친의 길흉을 어떻게 보는가
 *    「其間有無得力，或吉或凶，則以四柱所存…財官傷刃，係是何物，
 *     然後以六親配之用神。**局中作何喜忌**，參而配之，可以了然矣」
 *    — 육친의 득력 여부는 **그 십성이 격국에서 희신이냐 기신이냐**로 본다.
 *      육친도 격국에 종속된다. 기존 구현은 궁위와 십성을 나열만 했지
 *      이 희기 판정을 하지 않았다.
 *
 * ※ 원문은 여명(女命) 육친을 따로 다루지 않는다. 통설의 여명 매핑은
 *   원문 근거가 없으므로 표시할 때 그 사실을 밝힌다.
 */

const { sipseong, jeonggi } = require('./jijanggan');
const chwiun = require('./chwiun');

const 宮 = {
  년: { 항렬:'조상', 설명:'조상과 물려받은 조건이 놓이는 자리' },
  월: { 항렬:'부친', 설명:'부친과 자라난 환경이 놓이는 자리이며, 격이 여기서 나온다' },
  일: { 항렬:'배우자', 설명:'천간은 나 자신이고 지지가 배우자의 자리' },
  시: { 항렬:'자녀', 설명:'자녀와 말년이 놓이는 자리. 돌아가 머무는 곳(歸宿之地)이라 무겁다' },
};

const 用 = {
  정인: { 육친:'모친', 유도:'나를 낳아 기르는 것이라 어머니다 (身所自出)' },
  편재: { 육친:'부친', 유도:'내가 극하는 것이 어찌 아버지인가 — 정인이 어머니이니 그 어머니의 정부(正夫)가 편재다' },
  정재: { 육친:'배우자', 유도:'내가 극하는 자리이며, 남편이 벼리가 되고 처가 그를 따른다는 옛 관념에서 나온 배속' },
  정관: { 육친:'자녀', 유도:'나를 극하는 것이 어찌 자녀인가 — 관살은 재가 낳은 것이고 재가 처첩이니 그 소생이다' },
  편관: { 육친:'자녀', 유도:'관살은 재가 낳은 것이라 자녀에 배속된다' },
  비견: { 육친:'형제', 유도:'나와 같은 것이니 형제다' },
  겁재: { 육친:'형제', 유도:'나와 같은 것이니 형제다' },
};

/**
 * @param {object} r judge() 결과
 * @param {object} m 명식
 */
function analyze(r, m) {
  const ctx = r.ctx;
  // 격국의 희기를 그대로 쓴다 — 육친도 격국에 종속된다
  const rule = chwiun.lookup(ctx.gyeok, r.상신, ctx);
  const 속함 = (십성, 그룹) => 그룹 === '정관합거' ? false
    : (chwiun.群[그룹] ? chwiun.群[그룹].includes(십성) : 십성 === 그룹);
  const 희기 = (십성) => {
    if (!rule) return '판단 보류';
    if (rule.기.some(g => 속함(십성, g))) return '기신';
    if (rule.희.some(g => 속함(십성, g))) return '희신';
    if (십성 === r.상신) return '상신';
    return '한신';
  };

  // ── 축 ① 宮分
  const 궁분 = [['년', m.yeonGan, m.yeonJi], ['월', m.wolGan, m.wolJi],
                ['일', m.ilGan, m.ilJi], ['시', m.siGan, m.siJi]]
    .filter(([, g, j]) => g || j)
    .map(([p, g, j]) => {
      const 간십성 = p === '일' ? '일간(나)' : (g ? sipseong(m.ilGan, g) : '-');
      const 지십성 = j ? sipseong(m.ilGan, jeonggi(j)) : '-';
      const 대표 = p === '일' ? 지십성 : 간십성;      // 일주는 지지가 배우자 자리
      return { 자리:p, ...宮[p], 천간:g ?? '-', 천간십성:간십성,
               지지:j ?? '-', 지지십성:지십성,
               희기: 대표 === '일간(나)' ? '-' : 희기(대표) };
    });

  // ── 축 ② 用神
  const 용신배속 = [];
  for (const [십성, info] of Object.entries(用)) {
    const 자리 = [['년', m.yeonGan], ['월', m.wolGan], ['시', m.siGan]]
      .filter(([, g]) => g && sipseong(m.ilGan, g) === 십성).map(([p]) => p);
    const 지자리 = [['년', m.yeonJi], ['월', m.wolJi], ['일', m.ilJi], ['시', m.siJi]]
      .filter(([, j]) => j && sipseong(m.ilGan, jeonggi(j)) === 십성).map(([p]) => p + '지');
    if (!자리.length && !지자리.length) continue;
    용신배속.push({ 십성, ...info, 자리:[...자리, ...지자리], 희기:희기(십성) });
  }

  return {
    궁분, 용신배속,
    희기기준: rule ? `${ctx.gyeok}격 用${r.상신 ?? '미정'} 기준` : '격의 희기가 정해지지 않아 육친 길흉은 보류',
    총론: '육친의 득력 여부는 그 십성이 격국에서 희신이냐 기신이냐로 본다 — 「局中作何喜忌，參而配之」',
    주의: [
      '두 축(자리·십성)은 나란히 보는 것이지 하나로 합치는 것이 아니다',
      '원문은 여명(女命) 육친을 따로 다루지 않는다. 흔히 쓰는 여명 배속은 후대 통설이므로 원문 근거로 제시하지 않는다',
      '육친 배속은 옛 가족 관념 위에 세워진 것이라, 오늘의 관계를 그대로 재단하는 데 쓰지 말 것',
    ],
  };
}

module.exports = { 宮, 用, analyze };
