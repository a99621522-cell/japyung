const 금지 = /(질병|병원|수술|사고|사망|죽음|죽는|수명|단명|요절|이혼|파혼|사별|상처|과부|홀아비|상격|하격|귀격|천격|빈천|신살|역마|도화|화개|백호|괴강|겁살|망신|공망|원진|귀문|삼재|천을귀인|문창|홍염|부적|굿|방위|행운의\s*색)/;
const 깨끗 = (s, n) => String(s ?? '').replace(/[\r\n]+/g, ' ').replace(/\s+/g, ' ').trim().slice(0, n);
const 거르기 = (s, n) => { const t = 깨끗(s, n); return 금지.test(t) ? '(금지 표현이 있어 표시하지 않음)' : t; };

const G = '甲乙丙丁戊己庚辛壬癸', Z = '子丑寅卯辰巳午未申酉戌亥';
const 연간지 = y => G[((y - 4) % 10 + 10) % 10] + Z[((y - 4) % 12 + 12) % 12];

/** 입력: { 명식, 성별, 출생연도, 대운:[{간지,시작나이}], 올해, 지난해수 } */
function 해목록(입력) {
  const 올해 = 입력.올해 || new Date().getFullYear(), 출 = Number(입력.출생연도) || null;
  const 첫 = 출 ? Math.max(출 + 15, 올해 - (입력.지난해수 || 12)) : 올해;
  const 해 = []; for (let y = 첫; y < 올해 + 10; y++) 해.push(y);
  return 해;
}
