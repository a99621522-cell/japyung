/**
 * cheoja.js — 24편 「論妻子」
 * 사주팔자집 (2026-08-02)
 *
 * 이 편의 방법론은 23편 「局中作何喜忌」를 배우자 자리에 구체화한 것이다.
 *
 * 「坐下財官，妻當賢貴。**然亦有坐財官而妻不利，逢傷刃而妻反吉者，何也？
 *   此蓋以月令用神，配成喜忌。**
 *   如妻宮坐財，吉也；而**印格逢之，反爲不美**。
 *   妻宮坐官，吉也；而**傷官逢之，豈能順意**？
 *   妻坐傷官，凶也；而**財格逢之，可以生財；煞格逢之，可以制煞，反主妻能內助**。
 *   妻坐陽刃，凶也；而…日干無氣，**全憑日刃幫身，則妻必能相夫**。
 *   **其理不可執一也。**」
 * — 일지에 놓인 십성이 좋으냐 나쁘냐가 아니라, 그것이 **이 격국에서** 희신이냐 기신이냐.
 *   원문이 든 네 사례가 모두 통설을 뒤집는 쪽이라는 점이 중요하다.
 *
 * 「既看妻宮，又看妻星。**妻星者，干頭之財也**」 — 자리(일지)와 글자(천간의 재) 두 축.
 *   23편의 宮分/用神 두 축과 같은 구조다.
 *
 * 부모에 대해서는 「提綱得力，或年干有用，皆主父母雙全得力。
 *   **至於祖宗兄弟，不甚驗矣**」 — 조상·형제 항목은 원문 스스로 잘 맞지 않는다고 인정한다.
 *
 * ── 의도적으로 구현하지 않는 것 ──────────────────────
 * 원문 후반의 **자녀 수 산출**(「長生四子中旬半，沐浴一雙保吉祥…」)은 넣지 않는다.
 *   · 「死中至老沒兒郞」「入墓之時命夭亡」처럼 무자녀·요절을 단정하는 구절을 포함한다.
 *     이 앱은 수명·사망을 다루지 않기로 이미 정했고, 그 원칙에 정면으로 걸린다.
 *   · 난임이나 자녀를 잃은 사용자에게 줄 해가 크고, 검증할 방법도 없다.
 * 같은 이유로 「防刑尅」「難偕老」류의 배우자 관련 흉단(凶斷)도 문장으로 만들지 않는다.
 * 구조가 어떻게 놓였는지만 서술하고 그 이상을 말하지 않는다.
 */

const { sipseong, jeonggi } = require('./jijanggan');
const chwiun = require('./chwiun');

const 재 = ['정재', '편재'];
const CHUNG = { 子:'午', 午:'子', 丑:'未', 未:'丑', 寅:'申', 申:'寅',
                卯:'酉', 酉:'卯', 辰:'戌', 戌:'辰', 巳:'亥', 亥:'巳' };

/** 원문이 든 네 사례 — 모두 통설을 뒤집는 쪽이다 */
const 원문사례 = [
  { 일지십성:재, 격:['정인','편인'],
    설명:'배우자 자리에 재가 놓인 것은 통상 좋게 보나, 인수격에서는 재가 인수를 깨뜨리므로 그렇게 보지 않는다',
    원문:'妻宮坐財，吉也；而印格逢之，反爲不美' },
  { 일지십성:['정관'], 격:['상관'],
    설명:'배우자 자리에 관이 놓인 것은 통상 좋게 보나, 상관격에서는 상관이 관을 치는 자리라 뜻대로 되지 않는다',
    원문:'妻宮坐官，吉也；而傷官逢之，豈能順意？' },
  { 일지십성:['상관'], 격:[...재],
    설명:'배우자 자리의 상관은 통상 꺼리나, 재격에서는 그 상관이 재를 생하므로 도리어 안에서 돕는 자리가 된다',
    원문:'妻坐傷官，凶也；而財格逢之，可以生財…反主妻能內助' },
  { 일지십성:['상관'], 격:['편관'],
    설명:'배우자 자리의 상관은 통상 꺼리나, 칠살격에서는 그 상관이 살을 제복하므로 도리어 돕는 자리가 된다',
    원문:'妻坐傷官，凶也；…煞格逢之，可以制煞，反主妻能內助' },
  { 일지십성:['비견','겁재'], 격:[...재,'정관','편관','상관'],
    조건: c => !c.신강,
    설명:'배우자 자리의 양인·겁재는 통상 꺼리나, 격은 이미 섰는데 일간이 무력한 경우에는 그것에 기대어 몸을 지탱하므로 도리어 돕는 자리가 된다',
    원문:'妻坐陽刃，凶也；而…日干無氣，全憑日刃幫身，則妻必能相夫' },
];

function analyze(r, m) {
  const ctx = r.ctx;
  const rule = chwiun.lookup(ctx.gyeok, r.상신, ctx);
  const 속함 = (십성, g) => g === '정관합거' ? false
    : (chwiun.群[g] ? chwiun.群[g].includes(십성) : 십성 === g);
  const 희기 = (십성) => {
    if (!rule) return '판단 보류';
    if (rule.기.some(g => 속함(십성, g))) return '기신';
    if (rule.희.some(g => 속함(십성, g))) return '희신';
    if (십성 === r.상신) return '상신';
    return '한신';
  };

  // ── 妻宮 : 일지
  const 일지십성 = m.ilJi ? sipseong(m.ilGan, jeonggi(m.ilJi)) : null;
  const 궁희기 = 일지십성 ? 희기(일지십성) : '-';
  const 해당사례 = 일지십성 ? 원문사례.filter(s =>
    s.일지십성.includes(일지십성) && s.격.includes(ctx.gyeok) &&
    (!s.조건 || s.조건(ctx))) : [];

  // 일지가 충당하는가 — 사실만 적고 흉단은 하지 않는다
  const 일지충 = ['년','월','시'].some(p =>
    ({년:m.yeonJi, 월:m.wolJi, 시:m.siJi})[p] && CHUNG[m.ilJi] === ({년:m.yeonJi, 월:m.wolJi, 시:m.siJi})[p]);

  // ── 妻星 : 천간의 재
  const 처성 = [['년', m.yeonGan], ['월', m.wolGan], ['시', m.siGan]]
    .filter(([, g]) => g && 재.includes(sipseong(m.ilGan, g)))
    .map(([p, g]) => ({ 자리:p, 글자:g, 십성:sipseong(m.ilGan, g), 희기:희기(sipseong(m.ilGan, g)) }));
  const 정편잡출 = new Set(처성.map(x => x.십성)).size >= 2;

  // ── 부모 — 「提綱得力，或年干有用」
  const 월령득력 = ['성격', '패중유성', '인패득성'].includes(r.결론);
  const 년간십성 = m.yeonGan ? sipseong(m.ilGan, m.yeonGan) : null;
  const 년간유용 = 년간십성 ? ['희신', '상신'].includes(희기(년간십성)) : false;

  return {
    희기기준: rule ? `${ctx.gyeok}격 用${r.상신 ?? '미정'} 기준` : '격의 희기가 정해지지 않아 보류',
    처궁: {
      자리:'일지', 지지:m.ilJi ?? '-', 십성:일지십성 ?? '-', 희기:궁희기,
      충:일지충,
      원문사례: 해당사례.map(s => ({ 설명:s.설명, 원문:s.원문 })),
    },
    처성: { 목록:처성, 정편잡출 },
    부모: {
      월령득력, 년간유용,
      설명: (월령득력 || 년간유용)
        ? '월령이 힘을 얻었거나 년간이 쓸모 있는 자리라, 원문은 이런 경우 부모가 온전하다고 본다'
        : '월령과 년간 어느 쪽도 뚜렷하게 쓸모 있는 자리로 잡히지 않는다',
      원문:'提綱得力，或年干有用，皆主父母雙全得力',
    },
    조상형제단서: '원문은 「至於祖宗兄弟，不甚驗矣」라 하여 조상·형제 항목은 스스로 잘 맞지 않는다고 인정한다',
    핵심: '「其理不可執一也」 — 배우자 자리에 무엇이 놓였느냐로 좋고 나쁨을 정하지 않는다. 이 격국에서 그것이 어떻게 쓰이는지로 본다',
    배제: {
      자녀수: '원문 후반의 자녀 수 산출(長生沐浴之歌)은 구현하지 않는다. 무자녀·요절을 단정하는 구절을 포함하며, 이 앱은 수명·사망을 다루지 않기로 했다',
      흉단: '「防刑尅」「難偕老」류의 배우자 흉단은 문장으로 만들지 않는다. 구조가 어떻게 놓였는지만 서술한다',
    },
  };
}

module.exports = { 원문사례, analyze };
