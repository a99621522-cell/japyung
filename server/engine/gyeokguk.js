/**
 * cond 지원 연산자
 *   투간:      [십성...]  — 모두 천간에 있어야
 *   투간_or:   [십성...]  — 하나 이상 천간에
 *   유:        [십성...]  — 천간/지지 어디든 모두
 *   유_or:     [십성...]
 *   무:        [십성...]  — 천간/지지 어디에도 없어야
 *   천간무:    [십성...]
 *   충월지:    true|false
 *   fn:        (ctx) => boolean
 */
function evalCond(cond, ctx, 유효만 = false) {
  const map = 유효만 ? (ctx.유효천간 ?? ctx.cheongan) : ctx.cheongan;
  const inGan = s => (map[s]?.length ?? 0) > 0;
  const inAny = s => inGan(s) || (ctx.jiji[s]?.length ?? 0) > 0;

  if (cond.투간     && !cond.투간.every(inGan))          return false;
  if (cond.투간_or  && !cond.투간_or.some(inGan))        return false;
  if (cond.투간_or2 && !cond.투간_or2.some(inGan))       return false;
  if (cond.유       && !cond.유.every(inAny))            return false;
  if (cond.유_or    && !cond.유_or.some(inAny))          return false;
  if (cond.무       && cond.무.some(inAny))              return false;
  if (cond.천간무   && cond.천간무.some(inGan))          return false;
  if (cond.합국    && !cond.합국.some(s => (ctx.합국?.[s]?.length ?? 0) > 0)) return false;
  if (cond.합국무  && cond.합국무.some(s => (ctx.합국?.[s]?.length ?? 0) > 0)) return false;
  if (cond.충월지 !== undefined && cond.충월지 !== ctx.chungWolji) return false;
  if (cond.fn       && !cond.fn(ctx))                     return false;
  return true;
}

