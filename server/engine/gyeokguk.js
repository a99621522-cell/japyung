/**
 * @param {object} m { yeonGan, yeonJi, wolGan, wolJi, ilGan, ilJi, siGan, siJi, daysFromJeolip }
 */
function buildContext(m) {
  const { ilGan } = m;
  const ganPos  = [['년', m.yeonGan], ['월', m.wolGan], ['시', m.siGan]]; // 일간 제외
  const jiPos   = [['년', m.yeonJi], ['월', m.wolJi], ['일', m.ilJi], ['시', m.siJi]];

  // 합거(合去) — 인접한 천간합에 묶인 글자는 제 작용을 잃는다.
  //   李參政 庚寅 乙酉 甲子 戊辰: 乙庚합으로 편관이 합거되어 合煞留官
  //   잡기정관 壬戌 丁未 戊申 乙卯: 丁壬합으로 재·인이 함께 합거되어 孤官無輔
  const hcGan = hapchung.detectCheongan(
    [['년', m.yeonGan], ['월', m.wolGan], ['일', m.ilGan], ['시', m.siGan]]);
  //  ① 일간이 낀 합은 합거가 아니다 — 일간의 합은 有情이지 去가 아니다.
  //     王少師 庚午戊子癸卯丁巳: 戊癸합이지만 정관 戊는 살아 있어 用官이 성립한다.
  //  ② 일간을 사이에 둔 월-시 천간은 인접으로 본다 — 일간은 합의 방해물이 아니다.
  //     王兵 己酉乙亥壬戌庚子: 乙(월)·庚(시)이 합해 去傷存官이 된다.
  const 비일간자리 = ['년', '월', '시'];
  const 자리of = g => [['년',m.yeonGan],['월',m.wolGan],['시',m.siGan]]
                        .filter(([, x]) => x === g).map(([p]) => p);
  const 합거글자 = new Set();
  for (const h of hcGan.합) {
    if (h.쟁합) continue;
    if (h.천간.includes(ilGan)) continue;                 // ①
    const [pa, pb] = h.자리;
    const 실질인접 = Math.abs(비일간자리.indexOf(pa) - 비일간자리.indexOf(pb)) === 1;  // ②
    if (!실질인접) continue;
    for (const g of h.천간) 합거글자.add(g);
  }

  // 합거의 효과는 忌神이냐 喜神이냐에 따라 다르다.
  //   忌神(상관·칠살) 합거 → 패격은 일단 성립하고 救應으로 풀린다 (敗中有成)
  //   喜神(재·인)   합거 → 상신이 될 수 없다 (孤官無輔)
  // 그래서 전체 맵(cheongan)과 유효 맵(유효천간)을 분리한다.
  //   패격·대기 조문은 전체 맵, 성격·구응 조문은 유효 맵으로 평가한다.
  const cheongan = {};   // 합거 포함 — 패격 판정용
  const 유효천간 = {};   // 합거 제외 — 성격·상신 판정용
  const 합거십성 = [];
  for (const [pos, g] of ganPos) {
    if (!g) continue;
    const ss = sipseong(ilGan, g);
    (cheongan[ss] ??= []).push(pos);
    if (합거글자.has(g)) { 합거십성.push({ 천간:g, 자리:pos, 십성:ss }); continue; }
    (유효천간[ss] ??= []).push(pos);
  }

  const jiji = {};
  for (const [pos, j] of jiPos) {
    if (!j) continue;
    (jiji[sipseong(ilGan, jeonggi(j))] ??= []).push(pos);
  }

  // [1단계] 형충회합을 먼저 푼다 — 격 취용보다 앞이다 (論刑衝會合解法)
  const hc = hapchung.analyze(m);
  const chungWolji = hc.월지.충;

  // 회국(會局)이 만들어낸 십성 — 원국 천간에 없어도 실제로 작용한다.
  //   宣參國 己卯辛未壬寅辛亥: 亥卯未 木局이 壬일간의 상관이 되어 관을 친다
  const 합국 = {};
  for (const h of [...hc.지지.삼합, ...hc.지지.방합]) {
    if (h.해소 || !h.왕지) continue;
    const ss = sipseong(ilGan, jeonggi(h.왕지));
    (합국[ss] ??= []).push({ 지지:h.지지.join(''), 화:h.화 });
  }

  let g = chwiyongGyeok(m);

  // ── 10편 「論用神變化」 ─────────────────────────
  // 순서상 격 취용 '직후, 순잡·고저 이전'이다. 격이 확정돼야 다음을 물을 수 있다.
  //   「八字非用神不立，用神非變化不靈」
  // 변화의 경로는 둘 — ①본기가 투출하지 않고 다른 지장간이 투출해 주인이 바뀜
  //                    ②지지가 국을 이뤄 월령이 化함 (丁生亥月 支全卯未則化爲印)
  // 결정적 단서: 「變而不失本格」 — 化해도 본기가 투출해 있으면 본격을 유지하고
  //   化한 쪽은 兼格이 된다. 宣參國 己卯辛未壬寅辛亥가 그 예 —
  //   亥卯未 木局이 서도 未중 己官이 투간했으므로 정관격을 잃지 않는다.
  const 화오행 = hc.월지.화;
  let 변화 = { 발생:false };
  // 왕지가 있는 국(삼합·방합·반합)이거나, 왕지 없이 선 拱合이거나 —
  //   拱合은 hapchung에서 「천간에 그 오행이 투출」을 이미 확인했다 (원문 나장원 대목).
  if (화오행 && (hc.월지.화근거?.왕지 || hc.월지.화근거?.왕지없음)) {
    // 化한 오행을 대표하는 글자는 '천간에 드러난 그 오행'이 우선이다.
    //   「丙生申月，藏庚透壬，會子會辰，則化爲煞」 — 왕지 子의 癸(정관)가 아니라
    //   투출한 壬(칠살)으로 化를 읽는다.
    const 투출동행 = [m.yeonGan, m.wolGan, m.siGan]
      .filter(Boolean).find(x => GAN[x].ohaeng === 화오행);
    const 화천간 = 투출동행 ?? (hc.월지.화근거.왕지 ? jeonggi(hc.월지.화근거.왕지) : null);
    // 비겁으로 化하면 그것은 격이 아니라 월겁(건록)이다
    const 화십성 = 화천간 ? sipseong(ilGan, 화천간) : null;
    const 화격   = !화십성 ? null : ['비견','겁재'].includes(화십성) ? '건록' : 화십성;
    const 본기   = JIJANGGAN[m.wolJi].find(x => x.wi === '정기').gan;
    const 본기투출 = [m.yeonGan, m.wolGan, m.siGan].includes(본기);
    const 길신 = ['정관','정재','편재','정인','편인','식신'];

    // 원문이 든 會局 변화의 예는 예외 없이 吉↔凶 경계를 넘는다.
    //   化傷爲財·月劫化爲食傷(흉→길), 印綬化爲劫·偏財化爲煞(길→흉)
    // 같은 쪽 안에서의 化는 격을 바꾸지 않고 겸격으로 본다.
    //   金狀元 乙卯丁亥丁未庚戌은 「化官爲印」이라 하면서도 정관격으로 논한다.
    const 같은쪽 = 길신.includes(화격) === 길신.includes(g.gyeok);

    // 拱合으로 선 국은 **본격을 바꾸지 않는다**.
    //   원문이 羅狀元을 「化傷爲財」라 하면서도 41편(상관) 장에 싣고,
    //   「化劫爲財」인 명식도 45편(건록) 장에 싣는다.
    //   즉 化는 그 격을 읽는 **결**이지 격 자체를 갈아치우는 것이 아니다.
    //   왕지가 선 삼합·방합만 격을 바꾼다 — 그쪽이 국이 더 뚜렷하기 때문이다.
    const 공합화 = !!hc.월지.화근거?.왕지없음;

    if (공합화) {
      변화 = { 발생:true, 종류:'공합화', 본격:g.gyeok, 겸격:화격,
        원문:'干頭之甲，通根於亥，然又會未成局，化水爲木',
        근거:`${hc.월지.화근거.지지.join('')}이 왕지 ${hc.월지.화근거.빠진왕지} 없이 국을 이뤄 ${화오행}으로 化하나, 본격은 ${g.gyeok}으로 둔다`,
        비고:`${화격}으로 化하는 결이 있다 — 원문도 이런 명식을 본래 격의 장에 싣는다` };
    } else if (화격 === g.gyeok) {
      변화 = { 발생:false, 비고:`${hc.월지.화근거.지지.join('')} 국이 섰으나 化해도 같은 격이다` };
    } else if (같은쪽) {
      변화 = { 발생:true, 종류:'화이불역격', 본격:g.gyeok, 겸격:화격,
        원문:'化官爲印而透財，則又爲甚秀',
        근거:`${hc.월지.화근거.지지.join('')} 국이 ${화오행}으로 化해 ${화격}이 되나 길흉이 같은 쪽이라 본격은 ${g.gyeok}으로 둔다`,
        비고:`${화격}은 겸격으로 본다` };
    } else if (본기투출) {
      변화 = { 발생:true, 종류:'변이불실본격', 본격:g.gyeok, 겸격:화격,
        원문:'變而不失本格', 근거:`${hc.월지.화근거.지지.join('')} 국이 ${화오행}으로 化하나 본기 ${본기}이 투출해 본격을 잃지 않는다`,
        비고:`${화격}은 겸격으로 본다` };
    } else {
      const 선악 = 길신.includes(화격) && !길신.includes(g.gyeok) ? '변지이선'
                 : !길신.includes(화격) && 길신.includes(g.gyeok) ? '변지불선' : '변화';
      변화 = { 발생:true, 종류:선악, 원격:g.gyeok, 화격,
        원문: 선악==='변지이선' ? '變之而善，其格愈美' : 선악==='변지불선' ? '變之不善，其格遂壞' : '用神之變化',
        근거:`본기 ${본기}이 투출하지 않은 채 ${hc.월지.화근거.지지.join('')} 국이 ${화오행}으로 化해 ${g.gyeok}격이 ${화격}격으로 바뀐다` };
      g = { ...g, gyeok: 화격,
            yongbeop: SUNYONG.includes(화격) ? '순용' : YEOKYONG.includes(화격) ? '역용' : '미분류',
            geunGeo: `${g.geunGeo} → ${변화.근거}` };
    }
  }


  // 세력은 글자 개수가 아니라 통근 가중치로 잰다 (tonggeun.js)
  const st = strength(m);

  return {
    // 조문 조건 함수가 원국 글자를 직접 볼 수 있도록 명식을 얹는다
    yeonGan: m.yeonGan, wolGan: m.wolGan, ilGan: m.ilGan, siGan: m.siGan,
    yeonJi: m.yeonJi, wolJi: m.wolJi, ilJi: m.ilJi, siJi: m.siJi,
    ...g, ilGan, wolJi: m.wolJi, cheongan, jiji, chungWolji,
    sery: st.세력,
    합충: hc,
    합거: 합거십성,
    유효천간,
    합국,
    변화,
    신강: st.신강, 신강판정: st.판정, 일간점수: st.일간점수,
    득령: st.득령, 득지: st.득지, 득세: st.득세, 왕상휴수사: st.왕상휴수사,
    통근: st.통근,
    양인보유: [m.yeonJi, m.ilJi, m.siJi].some(j => j && require('./jijanggan').YANGIN[ilGan] === j),
  };
}

