const 합거된 = (ctx, ss) => (ctx.합거 ?? []).some(x => x.십성 === ss);
const 금수상관 = ctx => ['庚','辛'].includes(ctx.ilGan) && ['亥','子','丑'].includes(ctx.wolJi);
const 재 = ['정재','편재'], 인 = ['정인','편인'], 식상 = ['식신','상관'], 비겁 = ['비견','겁재'];

/**
 * 몸의 무게 — 인수를 뺀 제 뿌리로만 잰다.
 * 論印 「必身重印輕，或身輕印重」은 身과 印을 따로 세는 말이므로,
 * 인수가 두터워 '신강'으로 잡히는 것을 身重으로 세면 「身輕印重」이 성립할 수 없다.
 * 茅狀元 己巳癸酉癸未庚申이 그 예 — 통근 0.25에 인수 2.5인데 신강으로 판정됐다.
 */
function 신중(c) { return (c.통근?.score ?? 0) + (c.sery.비겁 ?? 0) * 0.3 >= 1.0; }

/** 월령 지장간에 그 십성이 있으나 천간에 드러나지 않았는가 (暗官·藏煞) */
function 월령암장(c, 십성) {
  return JIJANGGAN[c.wolJi].some(x => sipseong(c.ilGan, x.gan) === 십성)
      && !(c.cheongan[십성]?.length);
}
/** 그 계열이 천간에 드러났는가 */
function 투출됨(c, 십성목록) {
  return 십성목록.some(x => (c.cheongan[x]?.length ?? 0) > 0);
}
/** 두 계열이 천간에서 인접해 있는가 (財印相並) */
function 인접함(c, A목록, B목록) {
  const P = ['년','월','일','시'], 간 = { 년:c.yeonGan, 월:c.wolGan, 일:c.ilGan, 시:c.siGan };
  for (let i = 0; i < P.length - 1; i++) {
    const a = 간[P[i]], b = 간[P[i+1]];
    if (!a || !b) continue;
    const sa = sipseong(c.ilGan, a), sb = sipseong(c.ilGan, b);
    if ((A목록.includes(sa) && B목록.includes(sb)) || (B목록.includes(sa) && A목록.includes(sb))) return true;
  }
  return false;
}
/** 三奇 — 정관이 재와 인 사이에 끼어 둘이 서로 상하지 않는 배치 */
