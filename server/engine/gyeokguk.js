// ─────────────────────────────────────────────
// 4. 판정
// ─────────────────────────────────────────────
function judge(m) {
  const ctx = buildContext(m);
  const pool = JOMUN.filter(j => Array.isArray(j.격) ? j.격.includes(ctx.gyeok) : j.격 === ctx.gyeok);
  const hit  = pool.filter(j => evalCond(j.조건, ctx, j.판정 === '성격' || j.판정 === '구응'));

  const 성격 = hit.filter(j => j.판정 === '성격');
  const 대기 = hit.filter(j => j.판정 === '대기');
  const 패격 = hit.filter(j => j.판정 === '패격');
  const 구응 = hit.filter(j => j.판정 === '구응')
                  .filter(j => {
                    const t = Array.isArray(j.구제대상) ? j.구제대상 : [j.구제대상];
                    return 패격.some(p => t.includes(p.id));
                  });

  let 결론;
  if (패격.length && 구응.length) 결론 = '패중유성';
  else if (성격.length && 대기.length) 결론 = '성중유패';
  else if (패격.length && 성격.length) 결론 = '성중유패';
  else if (패격.length) 결론 = '패격';
  else if (성격.length) 결론 = '성격';
  else 결론 = '상신미현';
  // 「미성립」이라 부르지 않는다 — 격은 월령이 이미 세웠고, 안 나온 것은 **상신**이다.
  //   원문은 격과 상신을 나눠 놓았다 (8편 격 / 15편 상신).
  //   상신이 천간에 없다고 격까지 없는 것이 아니다.
  //   27편 「支主地，靜以待用」 — 지지에 있는 것은 아직 나서지 않았을 뿐이다.
  //   그리고 26·28편이 「운에서 드러나면 그때 격이 선다」고 답을 준다.
  //   그러므로 이것은 「안 된다」가 아니라 **「아직」**이다.

  const 유의미성격 = 성격.filter(j => !j.기본);
  let 상신 = 구응[0]?.상신 ?? 유의미성격[0]?.상신 ?? null;

  // 조문이 상신을 지목하지 못했을 때만, 8편의 「順逆之大略」으로 내려가 고른다.
  // 조문(원문 전사)은 손대지 않는다 — 특별 규정이 침묵할 때 일반 규정을 쓰는 것이다.
  let 상신폴백 = null;
  if (!상신 && 성격.length > 0) {
    상신폴백 = sangsinFallback.pick(ctx.gyeok, ctx, m);
    if (상신폴백) 상신 = 상신폴백.상신;
  }
  // 孤官無輔 — 격은 섰으나 상신이 없다 (합거로 재·인을 잃은 경우 포함)
  const 고관무보 = !상신 && 성격.length > 0;   // 대략으로도 못 고르면 진짜 孤官無輔다
  ctx.패격수 = 패격.length;
  ctx.구응수 = 구응.length;

  return {
    격: ctx.gyeok,
    용법: ctx.yongbeop,
    근거: ctx.geunGeo,
    결론,
    상신,
    고관무보,
    상신폴백,
    조문: { 성격, 패격, 구응, 대기 },
    ctx,
  };
}

