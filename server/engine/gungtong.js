  if (m.반월 === '상' || m.반월 === '하') return '반월 지정';
  if (m.jd != null || m.생시) { const r = 반월계산(m.jd != null ? m.jd : m.생시); if (r) return `${r.절} 뒤 ${r.지난날}일, ${r.중기}${r.반월 === '상' ? `까지 ${r.중기까지일}일 — 중기 기준` : ` 지남 — 중기 기준`}`; }
  return `절입 ${m.daysFromJeolip}일 — 15일 폴백`;
