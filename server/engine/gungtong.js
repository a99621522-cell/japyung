/* ── 반월 — 중기(中氣) 기준 (8차, 2026-10-07) ──
 *   manse.그해절기 는 12절만 두므로, 중기 12개(절 황경 +15°)를 manse.태양황경 으로 같은 이분법(절입시각과 같은 식)으로 구한다.
 *   JD 는 manse 와 같이 **KST 눈금**이다(태양황경은 UT 눈금을 받으므로 9시간을 빼고 넣고 더해서 낸다). */
const KST = 9 / 24;
const 중기이름 = { 315:'우수', 345:'춘분', 15:'곡우', 45:'소만', 75:'하지', 105:'대서', 135:'처서', 165:'추분', 195:'상강', 225:'소설', 255:'동지', 285:'대한' };
function 황경도달(황경, 기준JD) {   // manse.절입시각 과 같은 이분법(그 함수는 내보내지 않음)
  let lo = 기준JD - 20, hi = 기준JD + 20;
  const diff = jd => { let d = manse.태양황경(jd) - 황경; while (d > 180) d -= 360; while (d < -180) d += 360; return d; };
  if (diff(lo) > 0) lo -= 30;
  for (let i = 0; i < 60; i++) { const mid = (lo + hi) / 2; if (diff(mid) < 0) lo = mid; else hi = mid; }
  return (lo + hi) / 2;
}
/** 생시(KST 눈금 JD)가 든 달의 절·중기 — { 절:{이름,월지,jd}, 중기:{이름,jd}, 지난날 } (manse 없으면 null) */
function 절중기(jd) {
  if (!manse || typeof manse.그해절기 !== 'function') return null;
  const y = Math.floor((jd - 2451545.0) / 365.25) + 2000;   // 대략의 해 — 앞뒤 해까지 모아 고르므로 정확할 필요 없다
  const 전체 = [...manse.그해절기(y - 1), ...manse.그해절기(y), ...manse.그해절기(y + 1)].sort((a, b) => a.jd - b.jd);
  let 절 = null; for (const s of 전체) if (s.jd <= jd) 절 = s;
  if (!절) return null;
  const 중기황경 = (절.황경 + 15) % 360;
  const 중기 = { 이름: 중기이름[절.황경], 황경: 중기황경, jd: 황경도달(중기황경, 절.jd - KST + 15) + KST };
  return { 절, 중기, 지난날: jd - 절.jd };
}
/** 생시 → 반월. 생시는 KST 눈금 JD 또는 {y,m,d,h,min}. 절입 ≤ 생시 < 중기 → '상', 중기 ≤ 생시 → '하'. 계산 불가면 null */
function 반월계산(생시) {
  if (!manse) return null;
  const jd = typeof 생시 === 'number' ? 생시
    : (생시 && typeof 생시 === 'object') ? manse.toJD(생시.y ?? 생시.year, 생시.m ?? 생시.month, 생시.d ?? 생시.day, 생시.h ?? 생시.hour ?? 0, 생시.min ?? 생시.minute ?? 0) : NaN;
  if (!Number.isFinite(jd)) return null;
  const r = 절중기(jd);
  if (!r) return null;
  return { 반월: jd < r.중기.jd ? '상' : '하', 절: r.절.이름, 중기: r.중기.이름, 중기까지일: +(r.중기.jd - jd).toFixed(2), 지난날: +r.지난날.toFixed(2), 기준: '중기' };
}
/** 반월 — ① m.반월 ② m.jd/m.생시 → 중기 기준 ③ daysFromJeolip 15일 폴백. 없으면 null */
const 반월of = m => {
  if (m.반월 === '상' || m.반월 === '하') return m.반월;
  if (m.jd != null || m.생시) { const r = 반월계산(m.jd != null ? m.jd : m.생시); if (r) return r.반월; }
  return (m.daysFromJeolip == null || Number.isNaN(+m.daysFromJeolip)) ? null : (+m.daysFromJeolip < 15 ? '상' : '하');
};
