/**
 * @param {object} ctx buildContext 결과
 * @param {string} 상신
 * @param {object} m 명식
 */
function analyze(ctx, 상신, m) {
  const 일간오행 = GAN[m.ilGan].ohaeng;
  const hit = RULES.filter(r =>
    r.일간 === 일간오행 &&
    r.월.includes(m.wolJi) &&
    r.격.includes(ctx.gyeok) &&
    (상신 ? r.상신.includes(상신) : false));

  const 실 = hit.some(r => r.방향 === '실');
  return {
    계절: 계절[m.wolJi] ?? '-',
    판정: hit.length === 0 ? '무관' : 실 ? '실시(失時)' : '득시(得時)',
    항목: hit,
    총론: '「英雄豪傑，生得其時，自然事半功倍；遭時不順，雖有奇才，成功不易」 — 계절은 격을 만들지 않고 격을 돕거나 깎는다',
  };
}

