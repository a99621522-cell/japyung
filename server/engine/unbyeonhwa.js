/**
 * unbyeonhwa.js — 26편 「論行運成格變格」
 * 사주팔자집 (2026-08-02)
 *
 * 「命之格局，成於八字，然配之以運，亦有成格變格之權。
 *  **成格變格，比之喜忌，禍福尤重。**」
 * — 운이 격을 완성시키기도 하고 아예 바꾸기도 한다. 그리고 **이것이 희기보다 무겁다.**
 *   그래서 대운 판정에서 이 층을 희기 앞에 세운다.
 *
 * 成格 — 「本命用神，成而未全，運從而就之者是也」
 *   · 丁生辰月，透壬爲官，而**運逢申子以會之** — 운 지지가 원국과 회국해 격을 온전케 함
 *   · 乙生辰月，或申或子會印成局，而**運逢壬癸以透之** — 운 천간이 원국 회국을 투출시킴
 *
 * 變格 — 격이 아예 바뀐다
 *   · 丁生辰月，透壬爲官，而**運又逢戊，透出辰中傷官** — 운 천간이 월지 지장간을 투출시켜
 *     없던 십성이 드러난다. 10편 用神變化의 '운 버전'이며, 25편에는 없던 층이다.
 *   · 壬生戌月，丁己並透…作財旺生官矣，而**運逢戊土，透出戌中七煞**
 *   · 壬生亥月，透己爲用，作建祿用官矣，而**運逢卯未，會亥成木，又化建祿爲傷**
 */

const { GAN, JIJANGGAN, jeonggi, sipseong } = require('./jijanggan');
const hapchung = require('./hapchung');

const POS = ['년', '월', '일', '시'];

function analyze(un, ctx, r, m) {
  const 지 = { 년:m.yeonJi, 월:m.wolJi, 일:m.ilJi, 시:m.siJi };
  const 사건 = [];

  // ── 變格 ① 운 천간이 월지 지장간을 투출시켜 없던 십성이 드러난다
  // 원문이 든 예는 辰중 戊·戌중 戊로 모두 정기·중기다. 여기(餘氣)까지 변격으로 세지 않는다.
  const 월장간 = JIJANGGAN[m.wolJi].find(x => x.gan === un.천간 && x.wi !== '여기');
  if (월장간) {
    const 새십성 = sipseong(m.ilGan, un.천간);
    const 원래투출 = [m.yeonGan, m.wolGan, m.siGan].filter(Boolean).includes(un.천간);
    if (!원래투출 && 새십성 !== ctx.gyeok) {
      사건.push({
        종류:'변격', 방향:'운이 월령의 다른 글자를 끌어냄',
        설명:`운의 ${un.천간}이 월지 ${m.wolJi} 속의 ${un.천간}(${월장간.wi})을 끌어내니, 원국에 없던 ${새십성}이 드러나 ${ctx.gyeok}격의 배치가 달라진다`,
        새십성,
        원문:'運又逢戊，透出辰中傷官 … 運逢戊土，透出戌中七煞',
        무게:'重', 방향길흉: 방향판정(ctx.gyeok, 새십성),
      });
    }
  }

  // ── 成格 / 變格 ② 운 지지가 원국 지지와 회국
  for (const s of hapchung.SAMHAP) {
    if (!s.ji.includes(un.지지)) continue;
    const 짝 = POS.filter(p => 지[p] && s.ji.includes(지[p]) && 지[p] !== un.지지);
    if (!짝.length) continue;
    const 국십성 = sipseong(m.ilGan, jeonggi(s.wang));
    const 월지포함 = 짝.some(p => p === '월');
    // 회국은 **오행**으로 뭉친다 — 왕지 정기 하나의 음양(정관↔편관, 정인↔편인)으로 격과 견주면
    //   원문 성격 예 「丁生辰月，透壬爲官，運逢申子以會之」가 子 정기 癸=편관 ≠ 정관 이라 '변격·악화'로 뒤집혔다.
    //   같은 묶음(관살·인성·재성·식상·비겁)이면 격·상신을 떠받치는 것이고, 묶음이 다를 때만 변격이다. (2026-10-07)
    const 묶음 = x => ({ 정관:'관살', 편관:'관살', 칠살:'관살', 정인:'인성', 편인:'인성', 정재:'재성', 편재:'재성',
                         식신:'식상', 상관:'식상', 비견:'비겁', 겁재:'비겁', 건록:'비겁', 월겁:'비겁', 양인:'비겁' })[x] ?? x;
    const 같은묶음 = (a, b) => a && b && 묶음(a) === 묶음(b);
    // 왕지(子午卯酉) 없이 두 글자만 모인 것은 반합이 아니다 — 왕지가 운이나 원국에 있어야 국으로 센다
    if (un.지지 !== s.wang && !짝.some(p => 지[p] === s.wang)) continue;
    // 건록·양인격에 비겁 국이 더해지는 것은 「격을 온전케 함」이 아니다 — 45편 「本身不可爲用」, 월령이 나 자신이라
    //   재·관·살·식상을 따로 취해 쓰는 격이니 비겁이 늘면 그냥 비겁 운(불리)이지 成格이 아니다. 성격·변격 사건을 내지 않고
    //   희기 판정(haengun)에 맡긴다. (2026-10-07 — 辛酉월 건록격에 巳 운이 「건록격이 온전해진다」로 나오던 것)
    if (묶음(ctx.gyeok) === '비겁' && 묶음(국십성) === '비겁') continue;

    if (월지포함 && !같은묶음(국십성, ctx.gyeok)) {
      // 월령이 회국에 끌려가면 격이 化한다
      사건.push({
        종류:'변격', 방향:'월령이 회국에 끌려감',
        설명:`운의 ${un.지지}이 ${짝.map(p => `${지[p]}(${p}지)`).join('·')}과 모여 ${s.hwa}로 化하는데 월지가 여기 끼어 있으니, ${ctx.gyeok}격이 ${국십성} 쪽으로 바뀐다`,
        새십성:국십성,
        원문:'運逢卯未，會亥成木，又化建祿爲傷',
        무게:'重', 방향길흉: 방향판정(ctx.gyeok, 국십성),
      });
    } else if (같은묶음(국십성, ctx.gyeok) || 같은묶음(국십성, r.상신)) {
      // 격이나 상신을 회국이 떠받치면 성격이다
      사건.push({
        종류:'성격', 방향:'운이 격을 온전케 함',
        설명:`운의 ${un.지지}이 ${짝.map(p => `${지[p]}(${p}지)`).join('·')}과 모여 ${s.hwa}로 뭉치니, ${같은묶음(국십성, ctx.gyeok) ? `${ctx.gyeok}격` : `상신 ${r.상신}`}이 온전해진다`,
        원문:'本命用神，成而未全，運從而就之 — 運逢申子以會之',
        무게:'重',
      });
    }
  }

  // ── 成格 ③ 운 천간이 원국의 회국을 투출시킨다
  const 원국회국 = [...(ctx.합충?.지지?.삼합 ?? []), ...(ctx.합충?.지지?.방합 ?? [])]
    .filter(h => !h.해소 && h.왕지);
  for (const h of 원국회국) {
    if (GAN[un.천간].ohaeng !== h.화) continue;
    const 국십성 = sipseong(m.ilGan, un.천간);
    if (국십성 !== ctx.gyeok && 국십성 !== r.상신) continue;
    사건.push({
      종류:'성격', 방향:'운이 회국을 천간으로 끌어올림',
      설명:`원국의 ${h.지지.join('')}이 ${h.화}로 뭉쳐 있는데 운의 ${un.천간}이 그것을 천간으로 끌어올리니, ${국십성 === ctx.gyeok ? '격' : '상신'}이 비로소 온전해진다`,
      원문:'或申或子會印成局，而運逢壬癸以透之',
      무게:'重',
    });
  }

  const 성격목록 = 사건.filter(x => x.종류 === '성격');
  const 변격목록 = 사건.filter(x => x.종류 === '변격');
  // 원문은 「禍福尤重」이라 했을 뿐 변격이 곧 흉이라 하지 않았다.
  // 10편에서 變之而善/變之不善을 갈랐듯 여기서도 방향으로 가른다.
  const 변격가감 = 변격목록.reduce((s, x) =>
    s + (x.방향길흉 === '악화' ? -2 : x.방향길흉 === '개선' ? +1 : 0), 0);

  return {
    사건, 성격:성격목록.length, 변격:변격목록.length,
    판정: 변격목록.length ? '변격(變格)' : 성격목록.length ? '성격(成格)' : '없음',
    가감: 성격목록.length * 2 + 변격가감,
    우선: '「成格變格，比之喜忌，禍福尤重」 — 이 층은 희기보다 무겁게 본다',
  };
}

/** 길신 → 흉신이면 악화, 흉신 → 길신이면 개선, 같은 쪽이면 판단 보류 */
const 길신 = ['정관','정재','편재','정인','편인','식신'];
function 방향판정(원격, 새격) {
  const a = 길신.includes(원격), b = 길신.includes(새격);
  return a && !b ? '악화' : !a && b ? '개선' : '중립';
}

module.exports = { analyze, 방향판정 };
