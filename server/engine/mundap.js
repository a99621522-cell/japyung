// 1. 상담 브리프에서 「판정·표·가드」만 남기고 상담 화법을 걷어낸다
// ─────────────────────────────────────────────
// toLLMBrief는 한 덩어리 함수라 안을 뜯지 않고, 출력 문자열을 줄 단위로 걸러 쓴다.
// 남기는 것: 판정(여덟 글자~세운), 용어 풀이, 축 한 줄, 글자의 그림, 묻는 주제 번역,
//            경계 유형 지시(수명·사실확인·선택·신살·궁합·임신·택일·처방·제3자),
//            조후 층, 앞으로 올 해들 표, 달들 표, 십성 실명표·실명제, 육친 두 축, 주제 사전
// 걷어내는 것: 상담가 페르소나, 분야 모범답안과 그 예시문, 이어묻기 지시(우리 이력으로 대체),
//            기간 질문의 모범 꼴, 「오늘의 말로 하세요」 이후의 상담 화법 전부
const 걷어낼_시작 = [
  '**이 분야의 모범 답안',       // + 다음 줄(예시문)까지
  '**[이어 묻기',
  '**기간 질문의 모범 꼴',
  '위 판정을 재료로 해석을 써 주세요',
  '**보는 차례 — 이것은 당신 머릿속의 순서입니다',
  '**다만 이 여덟 단계를 번호대로',
  '짚은 것마다 **왜 그렇게 보는지**',
  '  이 한 줄이 글 전체의 축입니다',
];
const 걷어낼_패턴 = [
  /^「/,                                   // 상담체 장문 예시
  /십성으로 옮기지 않는 종류다/,            // 주제 미분류 시의 상담 지시
];

function 판정재료(r, opt) {
  const 전체 = haeseol.toLLMBrief(r, Object.assign({}, opt, { 주제: opt.질문 }));
  const 줄들 = 전체.split('\n');
  const out = [];
  let 상태 = '페르소나';   // 페르소나 → 판정 → 끝
  let 건너뛰기 = 0;
  for (const ln of 줄들) {
    if (건너뛰기 > 0) { 건너뛰기--; continue; }
    if (상태 === '페르소나') {
      if (ln.startsWith('─── 아래는 이 사람의 판정입니다')) { 상태 = '판정'; out.push(ln); }
      continue;
    }
    if (ln.startsWith('**오늘의 말로 하세요.**')) break;          // 여기서부터 상담 화법
    if (걷어낼_시작.some(s => ln.startsWith(s))) {
      if (ln.startsWith('**이 분야의 모범 답안')) 건너뛰기 = 1;     // 예시문 한 줄도 함께
      continue;
    }
    if (걷어낼_패턴.some(p => p.test(ln))) continue;
    out.push(ln);
  }
  return out;
}

