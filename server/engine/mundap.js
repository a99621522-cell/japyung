// 2. 십성 실명표 — 브리프에 없을 때만 직접 만든다
// ─────────────────────────────────────────────
// haeseol.js의 실명표는 궁통보감 블록(if (jo)) 안에 들어 있어 GT가 없거나
// analyze가 null이면 통째로 빠진다. 문답 모드는 실명제가 생명이라 여기서 보장한다.
function 실명표(m) {
  const 천간들 = ['甲','乙','丙','丁','戊','己','庚','辛','壬','癸'];
  const 자리이름 = { yeonGan:'년간', wolGan:'월간', siGan:'시간', yeonJi:'년지', wolJi:'월지', ilJi:'일지', siJi:'시지' };
  const 표 = {};
  for (const g of 천간들) {
    const 이름 = (g === m.ilGan) ? '비견' : sipseong(m.ilGan, g);
    if (!표[이름]) 표[이름] = { 글자: g, 드러남: [], 본기: [], 숨음: [] };
  }
  for (const k of ['yeonGan','wolGan','siGan']) {
    const g = m[k]; if (!g) continue;
    const 이름 = (g === m.ilGan) ? '비견' : sipseong(m.ilGan, g);
    표[이름].드러남.push(자리이름[k]);
  }
  표['비견'].드러남.unshift('일간 자체');
  for (const k of ['yeonJi','wolJi','ilJi','siJi']) {
    const ji = m[k]; if (!ji || !JIJANGGAN[ji]) continue;
    for (const h of JIJANGGAN[ji]) {
      const 이름 = (h.gan === m.ilGan) ? '비견' : sipseong(m.ilGan, h.gan);
      if (h.wi === '정기') 표[이름].본기.push(`${자리이름[k]} ${ji}`);
      else 표[이름].숨음.push(`${자리이름[k]} ${ji} 속`);
    }
  }
  const 순서 = ['정관','편관','정재','편재','정인','편인','식신','상관','비견','겁재'];
  const 줄 = 순서.map(nm => {
    const t = 표[nm]; if (!t) return null;
    const 곳 = [];
    if (t.드러남.length) 곳.push(t.드러남.join('·') + '에 드러남');
    if (t.본기.length)   곳.push(t.본기.join('·') + '의 본기');
    if (t.숨음.length)   곳.push(t.숨음.join('·') + '에 숨음');
    return `${nm}=${t.글자}` + (곳.length ? `(${곳.join(', ')})` : '(원국에 없음 — 운에서 올 때 크게 움직임)');
  }).filter(Boolean);
  return [
    `[십성 실명표 — 일간 ${m.ilGan} 기준, 천간 글자와 원국 위치] ${줄.join(' / ')}`,
    '**십성 실명제** — 어떤 십성을 말하든 위 표의 글자 이름으로 부르고 원국 위치(드러남/본기/숨음/없음)를 함께 밝힐 것. 표에 없는 글자를 그 십성이라 부르는 것은 지어내기. 정과 편은 다른 글자다(정관과 편관, 정재와 편재, 정인과 편인) — 한쪽 위치에 다른 쪽 이름을 붙이지 말 것.',
  ];
}

