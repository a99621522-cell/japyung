// 4. 대화 이력 — 전체를 싣는다 (직전 하나가 아니라)
// ─────────────────────────────────────────────
function 이력줄(이력) {
  if (!Array.isArray(이력) || !이력.length) return [];
  const L = ['', `─── 지금까지의 문답 (${이력.length}턴) — 이어서 답할 것 ───`];
  이력.forEach((t, i) => {
    L.push(`[${i+1}]${i === 0 ? ' (첫 물음 — 상담글로 답한 자리입니다)' : ''} 물음: ${String(t.질문 || '').slice(0, 400)}`);
    L.push(`[${i+1}] 답: ${String(t.답 || '').slice(0, 2500)}`);
  });
  L.push('**첫 답[1]은 이 명식의 상담글입니다 — 일간·격·상신·글자의 그림·올해의 결이 이미 그 안에 다 나왔습니다.** 그러니 이번 답에서 명식을 처음부터 다시 펼치지 마세요. 필요하면 「앞서 보신 ○○격의 결로 보면」처럼 한 구절로만 되짚고 곧장 이번 물음으로 들어가세요. 첫 답과 모순되면 「앞서 말씀드린 것을 바로잡으면」이라고 밝히고 고치세요.');
  return L;
}

