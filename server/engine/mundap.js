/**
 * @param {object} r      interpret 결과 (r.명식, r.결론 …) — /해설과 같은 것
 * @param {object} opt    { 질문, 이력:[{질문,답}], 년도, 출생연도, 성별 … toLLMBrief에 그대로 넘어가는 것들 }
 * @returns {string}      Gemini에게 보낼 브리프 전문
 */
function toMundapBrief(r, opt = {}) {
  const 질문 = String(opt.질문 || '').trim();
  const L = [];
  L.push(...판정재료(r, opt));
  if (!L.some(l => l.startsWith('[십성 실명표'))) { L.push(''); L.push(...실명표(r.명식)); }
  L.push(...지식창고(r));
  L.push(...이력줄(opt.이력));
  L.push(...문답규칙(질문, opt.이력));
  return L.join('\n');
}

