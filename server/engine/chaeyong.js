/**
 * chaeyong.js — 기업 채용 일정(서류·필기·면접·합격자 발표)을 인터넷에서 찾아 그 날짜·달의 운을 셈한다 (2026-10-10, 49차)
 *
 * 운영자 「어떤 기업을 언급하면 언제 시험과 면접·합격자 발표가 있는지 인터넷에서 검색해서 답변해」.
 *
 * 나눔
 *  · 날짜는 판정이 아니라 사실이다 — 서버가 Gemini 의 Google 검색(grounding)으로 그 기업의 최근 채용 공고 일정을 찾아
 *    JSON 으로 받는다(`검색`). 모델은 날짜를 옮기기만 하고 운을 판정하지 않는다.
 *  · 운의 판정은 지금처럼 코드: 날짜가 날이면 일진(25편 방법을 하루에, 원전에 일진 대목 없음), 달이면 적천수 희기를 그 달에 —
 *    `mureum.물음셈` 을 그 날·그 달 물음으로 불러 같은 셈을 쓴다.
 *  · 검색 결과는 틀릴 수 있고 해마다 바뀐다 — 줄과 답에 「공고 확인」과 출처를 늘 붙인다. 지난해 일정이면 지난해라고 적는다.
 *  · 개인정보·로그인 뒤 자료는 찾지 않는다(공개 채용 공고·보도만).
 */

// 물음에서 기업 이름 — 잘 알려진 이름 + 「○○ 입사/채용/공채/면접/인적성/필기」 꼴
const 알려진 = ['삼성전자', '삼성', 'SK하이닉스', 'SK', '현대자동차', '현대차', '기아', 'LG전자', 'LG', '포스코', '롯데', 'CJ', '한화', 'GS', '두산', '네이버', '카카오', '쿠팡', '배달의민족', '토스', '당근',
  '한국전력', '한전', '코레일', '한국철도', 'LH', '한국토지주택공사', '인천공항', '한국가스공사', '한국수자원공사', '국민건강보험공단', '건강보험공단', '국민연금공단', '한국은행', '산업은행', '기업은행', '국민은행', 'KB국민은행', '신한은행', '하나은행', '우리은행', '농협', 'KT', 'SKT', 'LGU+', '현대모비스', '셀트리온', '삼성바이오로직스', '대한항공', '아시아나'];
const 일반꼴 = /([A-Za-z가-힣0-9+&]{2,15}?)(?:에|의|에서)?\s*(?:입사|취업|지원|채용|공채|신입|면접|인적성|필기|서류)/;
const 아닌말 = /^(?:공무원|경찰|소방|군|교사|임용|공기업|대기업|회사|직장|취업|시험|올해|내년|이번|다음|신입|경력|하반기|상반기|어디|어느|이|그|저|제가|나|내가)$/;
function 기업of(질문) {
  const q = String(질문 || '').replace(/^\[이어묻기\][^⇒]*⇒\s*새 질문:\s*/, '');
  const 앎 = 알려진.filter(n => q.includes(n)).sort((a, b) => b.length - a.length)[0];
  if (앎) return 앎;
  const m = q.match(일반꼴);
  if (m && !아닌말.test(m[1]) && !/(?:공무원|경찰|임용|수능|시험)$/.test(m[1])) return m[1];
  return null;
}

// 검색 요청문 — 모델은 공개 공고에서 날짜만 옮긴다
function 검색프롬프트(기업, 올해) {
  return [
    `「${기업}」의 신입(대졸·고졸 공채 또는 대표 채용) 일정을 Google 검색으로 찾아 아래 JSON 하나만 답하세요. 설명 문장은 쓰지 마세요.`,
    `- ${올해}년 공고가 있으면 그것을, 아직 없으면 가장 최근 공고(${올해 - 1}년)를 쓰고 "기준해"에 그 해를 적으세요.`,
    '- 날짜는 공고·보도에 적힌 것만. 날이 없고 달만 있으면 "YYYY-MM", 모르면 그 단계를 빼세요. 지어내지 마세요.',
    '- 단계 이름은 서류 마감 · 필기·인적성 · 면접 · 합격자 발표 가운데서.',
    '{"기업":"","기준해":0,"채용이름":"","일정":[{"단계":"서류 마감","날짜":"YYYY-MM-DD"}],"출처":["https://..."]}',
  ].join('\n');
}

/** 모델 답에서 JSON 을 꺼내 다듬는다 — 틀이 맞지 않으면 null */
function 정리(글, 기업) {
  try {
    const t = String(글 || ''); const a = t.indexOf('{'), b = t.lastIndexOf('}'); if (a < 0 || b <= a) return null;
    const j = JSON.parse(t.slice(a, b + 1));
    const 단계들 = ['서류 마감', '필기·인적성', '면접', '합격자 발표'];
    const 일정 = (Array.isArray(j.일정) ? j.일정 : []).map(x => ({ 단계: String(x && x.단계 || '').trim(), 날짜: String(x && x.날짜 || '').trim() }))
      .filter(x => /^(19|20)\d{2}-(0[1-9]|1[0-2])(-(0[1-9]|[12]\d|3[01]))?$/.test(x.날짜))
      .map(x => ({ ...x, 단계: 단계들.find(s => x.단계.includes(s.split('·')[0]) || x.단계.includes(s)) || x.단계.slice(0, 12) }))
      .slice(0, 8);
    if (!일정.length) return null;
    const 출처 = (Array.isArray(j.출처) ? j.출처 : []).map(String).filter(u => /^https?:\/\//.test(u)).slice(0, 4);
    return { 기업: String(j.기업 || 기업).slice(0, 30), 기준해: Number(j.기준해) || Number(일정[0].날짜.slice(0, 4)), 채용이름: String(j.채용이름 || '').slice(0, 40), 일정, 출처 };
  } catch (e) { return null; }
}

/** 지난해 일정이면 같은 달·날을 앞날로 옮긴 「예상」 — 한 채용의 단계들은 함께 옮긴다(마지막 단계가 오늘 뒤에 오도록 같은 햇수만큼).
 *  옮긴 뒤에도 이미 지난 단계는 `지남` 으로 적는다(이번 채용에서 이미 끝난 단계). */
function 앞날로(일정, 올해, 오늘) {
  const 끝 = 일정.map(x => x.날짜).sort().slice(-1)[0];
  let k = 0; while (`${+끝.slice(0, 4) + k}${끝.slice(4)}` < 오늘.slice(0, 끝.length) && k < 5) k++;
  return 일정.map(x => { const 새 = k ? `${+x.날짜.slice(0, 4) + k}${x.날짜.slice(4)}` : x.날짜;
    return { ...x, 날짜: 새, 예상: k > 0, 원날짜: k ? x.날짜 : undefined, 지남: 새 < 오늘.slice(0, 새.length) }; });
}

/** 엔진 셈 줄 — 날은 일진, 달은 적천수 희기(mureum.물음셈 을 그 때로) */
function 일정줄(r, 결과, opt = {}) {
  try {
    if (!결과 || !결과.일정 || !결과.일정.length) return '';
    const U = require('./mureum');
    const 오 = new Date(Date.now() + 9 * 3600e3), 오늘 = 오.toISOString().slice(0, 10), 올해 = 오.getUTCFullYear();
    const 일정 = 앞날로(결과.일정, 올해, 오늘);
    const 줄 = 일정.map(x => {
      const [y, m, d] = x.날짜.split('-').map(Number);
      const 물음 = d ? `${y}년 ${m}월 ${d}일` : `${y}년 ${m}월`;
      let 셈 = null; try { 셈 = U.물음셈(r, 물음, { 성별: opt.성별, 출생연도: opt.출생연도 }); } catch (e) {}
      const 첫 = 셈 && 셈.줄 && 셈.줄[0] ? 셈.줄[0].replace(/^[^:]*:\s*/, '') : '셈 범위 밖';
      return `${x.단계} ${x.날짜}${x.예상 ? `(지난 공고 ${x.원날짜} 기준 예상)` : ''}${x.지남 ? '(이미 지남)' : ''} → ${d ? '그날 일진' : '그 달'}: ${첫.slice(0, 120)}`;
    });
    return `[채용 일정 — 인터넷 검색(${결과.기업}${결과.채용이름 ? ' ' + 결과.채용이름 : ''}, ${결과.기준해}년 공고 기준${결과.출처.length ? ' · 출처 ' + 결과.출처.join(' ') : ''}). 날짜는 검색 결과라 틀릴 수 있고 해마다 바뀜 — 반드시 공고 확인] ` + 줄.join(' ‖ ') +
      ` — **물으신 ${결과.기업}의 다가오는 단계(가장 가까운 날짜)를 「▶ 한 줄로 말하면」에 날짜와 함께 쓰고, 그날·그 달의 판정(위 엔진 셈)을 붙일 것.** 단계마다 「○월 ○일 면접 — 그날은 ○○ 날」처럼 「▶ 해마다 보면」 표 위나 「▶ 쉽게 풀어 보면」에 차례로. 지난 공고 기준 예상이면 「작년 일정을 바탕으로 한 예상」이라고 밝히고, 날짜는 공고로 확인하라고 한 번. 합격·불합격을 못박지 말 것(「그날은 열리는 날이라 준비한 것이 잘 드러나기 쉬운 날」까지). 날의 판정은 원전에 일진 대목이 없어 가볍게 보라고 한 번.`;
  } catch (e) { return ''; }
}

/** 답 끝에 붙일 출처 한 줄(서버) */
function 출처줄(결과) {
  if (!결과 || !결과.출처 || !결과.출처.length) return '';
  return `\n\n(채용 일정 출처 — 인터넷 검색, ${결과.기준해}년 공고 기준: ${결과.출처.join(' · ')} · 날짜는 해마다 바뀌니 공고를 확인하세요)`;
}

module.exports = { 기업of, 검색프롬프트, 정리, 앞날로, 일정줄, 출처줄, 알려진 };
