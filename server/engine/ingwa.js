/**
 * ingwa.js — 13편 「論用神因成得敗因敗得成」
 * 사주팔자집 (2026-08-02)
 *
 * 「成敗之中，又變化不測，遂有因成得敗，因敗得成之奇。」
 *
 * 9편의 帶忌·救應과는 층이 다르다.
 *   9편  — 격 안에 흠이 있느냐, 그 흠을 푸는 글자가 있느냐
 *   13편 — 成을 이룬 바로 그 요소가 원인이 되어 敗가 되고,
 *          敗의 요소가 원인이 되어 成이 되는 '인과의 역전'
 *
 * 원문이 든 네 예:
 *  因成得敗
 *   ① 化傷爲財로 격이 섰으나(辛生亥月 透丁爲用 卯未會財) 그 재가 도리어 煞을 돕는다
 *   ② 印用七煞로 격이 섰으나(癸生申月 秋金重重) 태과를 덜려 쓴 財를 煞印이 꺼린다
 *  因敗得成
 *   ③ 官印逢傷은 패격이나(辛生戊戌月 年丙時壬) 壬이 戊를 넘어 丙을 극하지 못하고
 *      도리어 洩身爲秀가 된다 —— 「壬不能越戊尅丙」
 *   ④ 煞刃逢食은 패격이나(庚生酉月 年月丙丁 時上逢壬) 壬이 丁과 합해
 *      合官留煞이 되어 관살이 섞이지 않고 煞刃局이 맑아진다
 *
 * ③이 이 편의 실질이다. 천간은 자리를 건너뛰어 극하지 못한다.
 */

const { GAN, sipseong } = require('./jijanggan');
const 剋 = { 木:'土', 土:'水', 水:'火', 火:'金', 金:'木' };
const POS = ['년', '월', '일', '시'];

/**
 * 「越尅」 판정 — A가 B를 극하려는데 사이에 A를 막는 글자가 있는가.
 * 막는 글자 = A를 극하는 오행. 일간도 자리를 차지하므로 포함해 본다.
 */
function 극차단(m, A자리, B자리, A천간) {
  const 간 = { 년:m.yeonGan, 월:m.wolGan, 일:m.ilGan, 시:m.siGan };
  const i = POS.indexOf(A자리), j = POS.indexOf(B자리);
  if (i < 0 || j < 0 || Math.abs(i - j) <= 1) return null;      // 인접하면 막을 자리가 없다
  const 사이 = POS.slice(Math.min(i, j) + 1, Math.max(i, j));
  for (const p of 사이) {
    const g = 간[p];
    if (!g) continue;
    if (剋[GAN[g].ohaeng] === GAN[A천간].ohaeng)
      return { 막은자리: p, 막은글자: g, 사이 };
  }
  return null;
}

/** 십성명으로 그 글자와 자리를 찾는다 (일간 제외) */
function 찾기(m, ilGan, 십성) {
  const out = [];
  for (const [p, g] of [['년', m.yeonGan], ['월', m.wolGan], ['시', m.siGan]]) {
    if (g && sipseong(ilGan, g) === 십성) out.push({ 자리: p, 천간: g });
  }
  return out;
}

/**
 * @param {object} r  judge() 결과
 * @param {object} m  명식
 * @returns {object}  { 인과역전:[], 최종결론 }
 */
function analyze(r, m) {
  const ctx = r.ctx, ilGan = m.ilGan;
  const 역전 = [];

  // ── 因敗得成 ③ : 패격의 파괴자가 격 또는 상신을 越尅하지 못하는 경우 ──
  //   원문 ③에서 壬이 치려 한 것은 격(印)이 아니라 상신(官)이다.
  const 대상 = [...찾기(m, ilGan, ctx.gyeok), ...(r.상신 ? 찾기(m, ilGan, r.상신) : [])];
  const 격글자 = 대상;
  for (const p of r.조문.패격) {
    const 파 = p.파괴자;
    if (!파 || 격글자.length === 0) continue;
    const 파글자 = 찾기(m, ilGan, 파);
    for (const a of 파글자) {
      for (const b of 격글자) {
        const blk = 극차단(m, a.자리, b.자리, a.천간);
        if (!blk) continue;
        역전.push({
          방향: '인패득성', 조문: p.id,
          설명: `${파}(${a.천간}·${a.자리}간)이 ${sipseong(ilGan, b.천간)}(${b.천간}·${b.자리}간)을 치려 하나 사이의 ${blk.막은글자}(${blk.막은자리}간)을 넘지 못한다`,
          원문: '壬不能越戊尅丙，而反能洩身爲秀，是因敗得成矣',
        });
      }
    }
  }

  // ── 因敗得成 ④ : 관살혼잡이 합거로 맑아진 경우 ──
  const 합거관 = (ctx.합거 ?? []).find(x => x.십성 === '정관');
  const 합거살 = (ctx.합거 ?? []).find(x => x.십성 === '편관');
  if ((합거관 || 합거살) && r.조문.패격.some(p => /혼잡|관살/.test(p.파괴자 ?? ''))) {
    역전.push({
      방향: '인패득성', 조문: '관살혼잡',
      설명: 합거관
        ? `정관 ${합거관.천간}이 합으로 묶여 살만 남으니 관살이 섞이지 않는다 (合官留煞)`
        : `칠살 ${합거살.천간}이 합으로 묶여 관만 남으니 관살이 섞이지 않는다 (合煞留官)`,
      원문: '食神合官留煞，而官煞不雜，煞刃局清，是因敗得成矣',
    });
  }

  // ── 因成得敗 ① : 化해서 재가 됐는데 그 재가 칠살을 돕는 경우 ──
  const v = ctx.변화;
  const 재격류 = ['정재', '편재'];
  if (v?.발생 && (재격류.includes(v.화격) || 재격류.includes(ctx.gyeok))
      && (ctx.cheongan['편관']?.length ?? 0) > 0
      && !(ctx.유효천간?.['식신']?.length || ctx.유효천간?.['상관']?.length)) {
    역전.push({
      방향: '인성득패', 조문: v.종류 ?? '변화',
      설명: '化하여 재가 되어 격이 섰으나, 그 재가 도리어 칠살을 돕는다 (乃以黨煞)',
      원문: '化傷爲財，格之成也，然…卯未會財，乃以黨煞，因成得敗矣',
    });
  }

  // ── 因成得敗 ② : 인수격에 살을 쓰는데 태과를 덜려 든 재가 煞印의 기신이 되는 경우 ──
  if (['정인', '편인'].includes(ctx.gyeok)
      && (ctx.유효천간?.['편관']?.length ?? 0) > 0
      && (ctx.cheongan['정재']?.length || ctx.cheongan['편재']?.length)
      && ctx.sery.인 >= 2.5) {
    역전.push({
      방향: '인성득패', 조문: 'ZPJZ-인수-成-01',
      설명: '인수가 무거워 재로 덜어냈으나, 칠살을 함께 쓰는 국이라 煞印이 재를 꺼린다',
      원문: '印用七煞，格之成也，然…逢煞則煞印忌財，因成得敗也',
    });
  }

  const 패득성 = 역전.filter(x => x.방향 === '인패득성').length;
  const 성득패 = 역전.filter(x => x.방향 === '인성득패').length;

  let 최종 = r.결론;
  if (패득성 && ['패격', '성중유패'].includes(r.결론))        최종 = '인패득성';
  else if (성득패 && ['성격', '패중유성'].includes(r.결론))   최종 = '인성득패';

  return {
    인과역전: 역전,
    최종결론: 최종,
    변동: 최종 !== r.결론 ? `${r.결론} → ${최종}` : null,
    주의: '13편은 9편의 帶忌·救應과 다른 층이다 — 成을 이룬 요소가 敗의 원인이 되고 敗의 요소가 成의 원인이 되는 인과의 역전을 본다',
  };
}

module.exports = { analyze, 극차단 };
