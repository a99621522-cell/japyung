/** 십성이 원국 어디 있는지를 우리말 자리 이름으로. 없으면 「운에서 오는 글자」 */
function 원국위치문(m, 십) {
  if (!m) return '';
  try {
    const { JIJANGGAN, sipseong } = require('./jijanggan');
    const 곳 = [];
    for (const [자리, 간, 지] of [['년', m.yeonGan, m.yeonJi], ['월', m.wolGan, m.wolJi], ['일', m.ilGan, m.ilJi], ['시', m.siGan, m.siJi]]) {
      if (간 && (십 === '비견' ? (간 === m.ilGan && 자리 !== '일') : (간 !== m.ilGan && sipseong(m.ilGan, 간) === 십))) 곳.push(`${자리말[자리]}의 위 글자 ${간}`);
      if (지) for (const jg of (JIJANGGAN[지] || [])) if (sipseong(m.ilGan, jg.gan) === 십 || (십 === '비견' && jg.gan === m.ilGan)) 곳.push(`${자리말[자리]}의 아래 글자 ${지} 속에 숨은 ${jg.gan}`);
    }
    if (!곳.length) return '이 명식에는 없고, 운에서 오는 글자입니다.';
    return `이 명식에서는 ${곳.slice(0, 2).join(', ')}${곳.length > 2 ? ' 등' : ''}입니다.`;
  } catch (e) { return ''; }
}

/**
 * @param {string} 본문  모델이 쓴 답
 * @param {object} r     interpret 결과(r.명식) — 없으면 뜻만 붙인다
 * @returns {{본문:string, 보강:string[]}}
 */
function 용어보강(본문, r) {
  const 글 = String(본문 || '');
  const { 본, 용어 } = 용어단락나누기(글);
  const 쓴 = 쓴전문어(본);
  // 확신 못 하는 낱말은 넣지 않는다 — 오탐 삽입이 미탐보다 나쁘다(사용자 답에 엉뚱한 풀이 줄이 들어간다)
  const 보강제외 = new Set(['년간', '월간', '오행', '물상', '간지', '성격', '통근', '투출', '본기', '월령']);
  const 안풀린 = 쓴.filter(w => !풀이있나(용어항목(용어), w) && !보강제외.has(w));
  if (!안풀린.length) return { 본문: 글, 보강: [] };
  let Y = null; try { Y = require('./yongeo'); } catch (e) {}
  const m = r && (r.명식 || r.ctx && r.ctx.명식) || null;
  const 줄 = [];
  for (const w of 안풀린) {
    let 뜻 = null;
    if (Y && Y.십성말[w]) 뜻 = Y.십성말[w].쉬운말;
    else if (추가사전[w]) 뜻 = 추가사전[w];
    else if (Y && Y.구조말[w]) 뜻 = Y.구조말[w].쉬운말 + (Y.구조말[w].풀이 ? `. ${Y.구조말[w].풀이}` : '');
    if (!뜻) continue;
    let 위치 = '';
    if (십성이름.includes(w)) 위치 = 원국위치문(m, w);
    else if (w === '일간' && m) 위치 = `이 명식에서는 ${m.ilGan}입니다.`;
    else if (w === '칠살') 위치 = 원국위치문(m, '편관');
    else if (w === '인수') 위치 = 원국위치문(m, '정인');
    줄.push(`- ${w}: ${뜻.replace(/\.$/, '')}.${위치 ? ' ' + 위치 : ''}`);
  }
  if (!줄.length) return { 본문: 글, 보강: [] };
  const 새 = 용어 ? (글.replace(/\s+$/, '') + '\n' + 줄.join('\n')) : (글.replace(/\s+$/, '') + '\n\n' + 머리.용어 + '\n' + 줄.join('\n'));
  return { 본문: 새, 보강: 줄.map(l => l.slice(2).split(':')[0]) };
}

