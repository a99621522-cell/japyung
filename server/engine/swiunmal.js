function 용어단락나누기(본문) {
  const 글 = String(본문 || '');
  const i = 글.indexOf(머리.용어);
  if (i < 0) return { 본: 글, 용어: '' };
  return { 본: 글.slice(0, i), 용어: 글.slice(i) };
}

function 단락(글, 머리말) {
  const i = 글.indexOf(머리말);
  if (i < 0) return '';
  const 다음 = 글.indexOf('▶', i + 2);
  return 글.slice(i + 머리말.length, 다음 > 0 ? 다음 : undefined);
}

function 문장들(글) {
  return String(글)
    .replace(/^▶.*$/gm, '')
    .split(/(?<=[.!?。])\s+|\n+/)
    .map(s => s.replace(/\*\*/g, '').trim())
    .filter(s => s.length >= 6 && !/^[-•]\s/.test(s));
}

function 한자수(글) { return (String(글).match(/[一-鿿]/g) || []).length; }

/** 「이 답에 나온 말」 단락에서 「- 낱말: 풀이」 줄 머리의 낱말들 — 풀이 유무는 includes 가 아니라 이것으로(「힘입니다」의 합, 「충분」의 충이 걸리던 것) */
function 용어항목(용어) {
  const 머리들 = [];
  for (const l of String(용어 || '').split('\n')) { const m = l.match(/^\s*[-•*]\s*([^:：]{1,24})[:：]/); if (m) 머리들.push(m[1].replace(/\*\*/g, '').trim()); }
  return 머리들;
}
function 풀이있나(용어항목들, w) {
  if (w === '합' || w === '충') return 용어항목들.some(h => new RegExp(`(?<![가-힣])${w}(?![가-힣])`).test(h));
  return 용어항목들.some(h => h.includes(w));
}
/** 본문에 쓰고 풀이에 없는 전문어 */
function 안풀린목록(본문) {
  const { 본, 용어 } = 용어단락나누기(본문);
  const 항목 = 용어항목(용어);
  return 쓴전문어(본).filter(w => !풀이있나(항목, w));
}

// 전문어 찾기 — 앞에 한글이 붙은 꼴(기본기·인수인계)은 세지 않고, 뒤는 조사·기호·끝만 허용한다(「10년간」「지지해」「인성이 좋다」는 아님).
//   「성격」은 격국 문맥에서만, 「년간·월간」은 간지 문맥(년간의 X·월간 丙)에서만, 「인성」은 괄호·간지가 따르거나 다른 인성 용어가 함께 있을 때만.
const 조사 = '(?:이라는|이라고|이라서|이라면|입니다|이에요|에서는|으로는|이란|이라|이며|이면|이고|이다|으로|에서|에게|께서|보다|밖에|조차|마저|부터|까지|처럼|마다|이나|이든|이지|이야|이기|인|이|가|을|를|은|는|의|에|도|과|와|로|만)';
const 뒤경계 = `(?=$|[^가-힣]|${조사}(?:$|[^가-힣]|${조사}(?:$|[^가-힣])))`;
const 특수전문어 = {
  성격: /(?<![가-힣])성격(?=\(|이 되|을 이루|이라|으로 섰|인 명식|과 패격)/,
  년간: /(?<![0-9가-힣])년간(?=의|에|\s*[甲乙丙丁戊己庚辛壬癸])/,
  월간: /(?<![가-힣])월간(?=의|에|\s*[甲乙丙丁戊己庚辛壬癸])/,
};
function 전문어있나(글, w) {
  글 = String(글 || '');
  if (특수전문어[w]) return 특수전문어[w].test(글);
  if (w === '인성') return /(?<![가-힣])인성(?=\s*[(（]|\s*[甲乙丙丁戊己庚辛壬癸])/.test(글) || (/(?<![가-힣])인성(?=이|을|은|의|과|\()/.test(글) && /정인|편인|인수/.test(글));
  return new RegExp(`(?<![가-힣])${w}${뒤경계}`).test(글);
}
function 전문어목록(글) { return 전문어.filter(w => 전문어있나(글, w)); }

/**
 * @param {string} 본문
 * @param {string} 모드 상담 | 궁통 | 문답 | 설명
 * @param {object} ctx { 질문 } — 갈래 검사에 쓴다
 * @returns {{오류:Array, 경고:Array, 통계:object}}
 */
function 검사(본문, 모드 = '상담', ctx = {}) {
  const 오류 = [], 경고 = [];
  const 글 = String(본문 || '');
  const { 본, 용어 } = 용어단락나누기(글);
  const 상담류 = 모드 === '상담' || 모드 === '궁통';
  const 넣기 = (심각, 항목) => (심각 ? 오류 : 경고).push(항목);

  // ① 첫머리 「한 줄로 말하면」
  const 첫줄있음 = 글.trimStart().startsWith(머리.한줄) || 글.slice(0, 60).includes('한 줄로 말하면');
  if (!첫줄있음) {
    넣기(상담류, { 규칙: '한 줄 답', 내용: `첫머리에 「${머리.한줄}」이 없음 — 결론을 전문어 없이 두 문장으로 먼저` });
  } else {
    const 한줄단락 = 단락(글, 머리.한줄);
    const 섞인 = 전문어목록(한줄단락);
    const 한자 = 한자수(한줄단락);
    // 2026-10-07: 경고 → 오류(상담·궁통). 첫 줄은 캡처의 첫 줄이다
    if (섞인.length || 한자) 넣기(상담류, { 규칙: '한 줄 답 말 높이', 내용: `한 줄 답에 ${[...섞인, 한자 ? `한자 ${한자}자` : ''].filter(Boolean).join('·')} — 이 단락은 전문어·한자 없이` });
    const 사 = 한줄단락.match(사투리);
    if (사) 넣기(상담류, { 규칙: '한 줄 답 사투리', 내용: `한 줄 답에 「${사[0].trim()}」 — 매듭·결·기운·흐름 대신 실제로 무슨 일이 되는지로` });
    const 한줄문 = 문장들(한줄단락);
    const 갈래수 = Math.max(2, 갈래들(ctx.질문).length);
    if (한줄문.length > 갈래수) 경고.push({ 규칙: '한 줄 답 길이', 내용: `한 줄 답이 ${한줄문.length}문장 — 두 문장(갈래마다 하나)까지` });
    const 긴한줄 = 한줄문.filter(s => s.replace(/\s/g, '').length > 50);
    if (긴한줄.length) 경고.push({ 규칙: '한 줄 답 길이', 내용: `한 줄 답에 50자 넘는 문장: 「${긴한줄[0].slice(0, 30)}…」` });
  }

  // ①-1 「정리하면」에 사투리
  {
    const m = 본.match(/정리하면[^\n]*/);
    if (m) { const 사 = m[0].match(사투리); if (사) 경고.push({ 규칙: '정리하면 사투리', 내용: `「정리하면」에 「${사[0].trim()}」 — 실제 일로 바꿀 것` }); }
  }

  // ② 머리말 차례 (상담·궁통)
  if (상담류) {
    const 빠짐 = [머리.풀이, 머리.근거, 머리.노력, 머리.용어].filter(h => !글.includes(h));
    if (빠짐.length >= 2) 오류.push({ 규칙: '답의 모양', 내용: `머리말이 빠짐: ${빠짐.join(', ')} — 다섯 머리말을 차례로` });
    else if (빠짐.length) 경고.push({ 규칙: '답의 모양', 내용: `머리말이 빠짐: ${빠짐.join(', ')}` });
  }

  // ③ 쓴 전문어가 용어 풀이에 있는가 (서버가 용어보강()으로 먼저 메운 뒤 남은 것만 여기 걸린다)
  const 쓴말 = 쓴전문어(본);
  const 안풀린 = 쓴말.filter(w => !풀이있나(용어항목(용어), w));
  const 용어필요 = 상담류 || 모드 === '설명' || 쓴말.length >= 2;
  if (용어필요 && 쓴말.length && !용어) {
    넣기(상담류, { 규칙: '용어 풀이', 내용: `전문어 ${쓴말.length}개(${쓴말.slice(0, 5).join('·')}…)를 썼는데 「${머리.용어}」가 없음` });
  } else if (용어 && 안풀린.length >= 1) {
    경고.push({ 규칙: '용어 풀이', 내용: `본문에 쓰고 풀이에 없는 말: ${안풀린.slice(0, 6).join('·')}` });
  }
  // ③-1 풀이 안에 자리 이름
  if (용어) {
    const 걸린줄 = 용어.split('\n').filter(l => /^\s*-\s/.test(l) && 자리이름꼴.test(l.replace(/^\s*-\s*[^:：]+[:：]/, '')));
    if (걸린줄.length) 경고.push({ 규칙: '풀이 안 자리 이름', 내용: `용어 풀이 안에 월간·년지·천간 같은 자리 이름 ${걸린줄.length}줄 — 「태어난 달의 위 글자」처럼 풀어 쓸 것: 「${걸린줄[0].trim().slice(0, 30)}…」` });
  }

  // ④ 문장 길이·한 문장 전문어 밀도
  const 문 = 문장들(본);
  const 길이 = 문.map(s => s.replace(/\s/g, '').length);
  const 평균 = 길이.length ? Math.round(길이.reduce((a, b) => a + b, 0) / 길이.length) : 0;
  const 긴문장 = 길이.filter(n => n > 60).length;
  const 넘는비율 = 길이.length ? 길이.filter(n => n > 40).length / 길이.length : 0;
  // 2026-10-07: 60자 넘는 문장 셋 이상 → 오류. 40자 넘는 문장이 절반 이상 → 경고
  // 2026-10-07 재점검: 재시도율 자료 없이 오류로 두면 비용 2배 위험 → 경고. 오류는 한 줄 답 전문어·사투리·갈래 빠짐만
  if (긴문장 >= 3) 경고.push({ 규칙: '긴 문장', 내용: `60자 넘는 문장 ${긴문장}개(평균 ${평균}자) — 「~인데, ~지만」을 끊어 40자 안팎으로` });
  else if (넘는비율 >= 0.5) 경고.push({ 규칙: '문장 길이', 내용: `40자 넘는 문장이 ${Math.round(넘는비율 * 100)}%(평균 ${평균}자) — 40자 안팎으로 끊을 것` });
  const 밀도 = s => 전문어목록(s).length + (s.match(간지글자) || []).length;
  const 빽빽4 = 문.filter(s => 밀도(s) >= 4);
  const 빽빽3 = 문.filter(s => 밀도(s) >= 3);
  if (빽빽4.length >= 1) 경고.push({ 규칙: '빽빽한 문장', 내용: `한 문장에 전문어·간지가 넷 이상: 「${빽빽4[0].slice(0, 36)}…」 등 ${빽빽4.length}곳 — 나눠 쓸 것` });
  else if (빽빽3.length >= 3) 경고.push({ 규칙: '빽빽한 문장', 내용: `한 문장에 전문어·간지가 셋인 문장 ${빽빽3.length}곳 — 「${빽빽3[0].slice(0, 36)}…」` });

  // ⑤ 한자음 표기 「미토(未)」 ⑥ 오행 낱말
  {
    const 음 = [...본.matchAll(한자음꼴)].map(m => m[0]).filter(x => !/^(년|월|일|시|해|달|날|글자|자리|운|지|간)\(/.test(x));
    if (음.length) 경고.push({ 규칙: '한자음 표기', 내용: `${음.slice(0, 3).join('·')} — 한자음으로 읽어 쓰지 말고 「2027년의 아래 글자(未)」처럼` });
    const 오 = [...본.matchAll(오행꼴)].map(m => m[0].trim());
    if (오.length) 경고.push({ 규칙: '오행 말', 내용: `${오.slice(0, 3).join('·')} — 오행 말 대신 글자가 하는 일로` });
  }

  // ⑦ 문단 한자 수 — 「왜 그렇게 보나요」 밖에서. 근거 단락은 글자 실명을 모으는 자리라 더 봐준다
  {
    const 근거 = 단락(글, 머리.근거);
    const 바깥 = 근거 ? 본.replace(근거, '') : 본;
    const 문단 = 바깥.split(/\n{2,}/).map(p => p.replace(/^▶.*$/gm, '').trim()).filter(p => p.length > 20);
    const 셈 = 문단.map(p => 한자수(p));
    const 많은 = 셈.filter(n => n > 5).length, 넘는 = 셈.filter(n => n > 2).length;
    if (많은) 경고.push({ 규칙: '문단 한자', 내용: `「왜 그렇게 보나요」 밖 문단에 한자 5자 초과 ${많은}곳 — 쉽게 풀어 보면·해 볼 만한 일에서는 한자를 괄호에 둘까지` });
    else if (넘는) 경고.push({ 규칙: '문단 한자', 내용: `「왜 그렇게 보나요」 밖 문단에 한자 3자 이상 ${넘는}곳` });
    if (근거 && 한자수(근거) > 12) 경고.push({ 규칙: '근거 한자', 내용: `「왜 그렇게 보나요」에 한자 ${한자수(근거)}자 — 간지는 처음 한 번만, 그 뒤는 연도로` });
  }

  // ⑧ 충 아닌 부딪힘 · 합 아닌 붙듦 (2026-10-07) — 짝 목록에 없는 두 글자를 충/합으로 묶은 문장은 오류(파·해·원진을 돌려 말한 것)
  {
    const 틀린 = 충합짝검사(본);
    for (const [a, b, 구절] of 틀린.충) 오류.push({ 규칙: '충 아닌 부딪힘', 내용: `${a}·${b}는 충 짝이 아님(충은 子午·丑未·寅申·卯酉·辰戌·巳亥뿐) — 「${구절}」. 파·해·원진은 말하지 않고, 부딪힘·흔들림으로 돌려 말하지도 않을 것` });
    for (const [a, b, 구절] of 틀린.합) 오류.push({ 규칙: '합 아닌 붙듦', 내용: `${a}·${b}는 합 짝이 아님(육합·천간 합·삼합 묶음만) — 「${구절}」` });
  }

  // ⑩ 물은 갈래가 답에 있는가 (갈래가 둘 이상일 때만)
  //   브리프가 있으면 브리프가 실제로 지시한 갈래(haeseol 의 「이 물음은 N갈래(…)」 줄)만 본다 — 모델이 약속받지 않은 갈래를 요구하지 않게
  const 갈래 = ctx.브리프 ? 브리프갈래(ctx.브리프) : 갈래들(ctx.질문);
  let 빠진갈래 = [];
  if (갈래.length >= 2) {
    const 풀이단락 = 단락(글, 머리.풀이) || 본;
    빠진갈래 = 갈래사전.filter(g => 갈래.includes(g.이름) && !g.답.test(풀이단락)).map(g => g.이름);
    if (빠진갈래.length) 넣기(상담류, { 규칙: '갈래 빠짐', 내용: `물으신 ${갈래.length}갈래 중 답에 없는 갈래: ${빠진갈래.join('·')} — 「쉽게 풀어 보면」에 갈래마다 한 문단` });
  }

  return { 오류, 경고, 통계: { 평균문장: 평균, 긴문장, 넘는비율: Math.round(넘는비율 * 100), 쓴전문어: 쓴말.length, 풀이없음: 안풀린.length, 갈래: 갈래.length, 빠진갈래 } };
}

/** 본문(용어 단락 제외)에 실제로 쓴 전문어 — 합·충은 조사가 붙은 꼴로만 */
function 쓴전문어(본) {
  const 글 = String(본 || '');
  const 목록 = 전문어목록(글);
  const hc = 글.match(합충꼴);
  if (hc) { for (const w of ['합', '충']) if (new RegExp(합충식(w)).test(글)) 목록.push(w); }
  return [...new Set(목록)];
}

