/**
 * seun.js — 세운(歲運)
 * 사주팔자집 (2026-08-02)
 *
 * 자평진전에는 세운을 따로 다룬 편이 없다. 論行運이 말하는 것은 대운이다.
 * 그래서 **다른 책에서 太歲 규칙을 끌어오지 않는다.** 30편이 경계한
 * 「以俗書無知妄作，誤依其說而深入迷途」가 그 위험이다.
 *
 * 대신 이 책이 이미 세워둔 규칙을 한 해 단위에 그대로 적용한다.
 * 원문이 운을 보는 방법 자체를 「運中每運行一字，即必以此一字，配命中八字而統觀之」라고
 * 했으므로, 대운이든 한 해든 **한 글자씩 원국에 대어 보는 것**은 같다.
 *
 *   25편 論行運        — 희기 총론, 似喜實忌, 운간합, 충의 완급·경중, 逢沖而不沖, 一沖而得兩沖
 *   26편 行運成格變格   — 「成格變格，比之喜忌，禍福尤重」
 *   27편 喜忌干支有別   — 천간과 지지가 같은 오행이라도 달리 작용한다
 *   28편 支中喜忌逢運透清 — 지지에 잠자던 것이 운 천간으로 나오면 맑아진다.
 *                        그리고 「**此五年中**，亦能爲其禍福」
 *
 * 28편의 「此五年中」이 대운 열 해를 **천간 다섯 해·지지 다섯 해**로 나눠 보는 근거다.
 * 세운이 그 대운의 어느 쪽 다섯 해에 놓였는지를 함께 표시한다.
 *
 * ── 만들지 않은 것 ──────────────────────────
 * 세운과 대운이 서로 합·충하는 것을 따로 **판정하지 않는다**. 원문에 근거가 없다.
 * 「歲運並臨」「太歲沖合」류는 전부 淵海子平·三命通會 쪽 규칙이다.
 * 원문이 말한 것은 어디까지나 **운의 글자를 원국에 대어 보는 것**이다.
 *   (2026-10-07, 9차) 다만 그 **사실**(세운 글자가 대운 글자와 간합·충·육합·삼합 묶음인가)은 `대운관계` 에 점수·길흉 없이 적는다.
 *   근거 없는 층임을 결과(비고)와 브리프에 함께 명시한다.
 *
 * ── 26편 成格變格은 세운에 적용하지 않는다 (2026-10-07, 9차) ──
 *   26편은 「命之格局，成於八字，然配之以運，亦有成格變格之權」이라 하고 예를 모두 「運逢申子以會之」「運逢壬癸以透之」
 *   「運又逢戊」「運逢卯未」로 든다 — 이 「運」은 편 이름(論行運·論行運成格變格)대로 대운이다. 28편은 그것을 다시
 *   「若月令之物，而運中透清，則與命中原有者，不甚相懸，即前篇所謂行運成格變格也」라 하여 「此五年中」(운 한 글자 다섯 해)에
 *   묶는다. 한 해 단위의 운(세운)은 책 어디에도 나오지 않으므로(歲·太歲·流年 낱말이 본문에 없다), 「禍福尤重」이라 한 층을
 *   한 해에 얹으면 원문보다 무겁게 읽는 것이 된다. 그래서 세운에서는 성격·변격을 **참고로 기록만** 하고 점수에 넣지 않는다.
 */

const { 판정어로: __pj } = require('./chwiun');
const { GAN, JI, sipseong } = require('./jijanggan');
const chwiun = require('./chwiun');
const unchung = require('./unchung');
const unbyeonhwa = require('./unbyeonhwa');
const tuchong = require('./tuchong');
const jeokcheonsu = require('./jeokcheonsu');   // 셋째 층 「흐름」 — 歲運論 戰·衝·和 (2026-10-07 사용자 결정 「세운도 적천수대로」)

const 天干 = ['甲', '乙', '丙', '丁', '戊', '己', '庚', '辛', '壬', '癸'];
const 地支 = ['子', '丑', '寅', '卯', '辰', '巳', '午', '未', '申', '酉', '戌', '亥'];

/**
 * 그 해의 간지. 1984년이 甲子다.
 * ※ 해가 바뀌는 기준은 입춘이므로, 1월~2월 초 생일은 앞 해로 봐야 한다.
 *   이 함수는 연도만 받으므로 그 보정은 호출부에서 한다.
 */
function 연간지(year) {
  const n = ((year - 1984) % 60 + 60) % 60;
  return { 천간: 天干[n % 10], 지지: 地支[n % 12], 간지: 天干[n % 10] + 地支[n % 12] };
}

/** 이 해가 대운의 어느 쪽 다섯 해인가 — 28편 「此五年中」(운 한 글자가 다섯 해). 앞·뒤 차례는 원문에 없는 관행이다 */
function 오년구간(year, 대운) {
  if (!대운) return null;
  const 경과 = year - 대운.시작연도;
  if (경과 < 0 || 경과 >= 10) return null;
  const 앞 = 경과 < 5;
  const 분할 = 대운.읽기?.분할 ?? null;
  const 이쪽 = 분할 ? (앞 ? 분할.천간5 : 분할.지지5) : null;
  return {
    구간: 앞 ? '천간 쪽 다섯 해' : '지지 쪽 다섯 해',
    글자: 앞 ? 대운.천간 : 대운.지지, 십성: 앞 ? 대운.천간십성 : 대운.지지십성,
    설명: 앞
      ? `이 대운 ${대운.간지}의 앞 다섯 해라 천간 ${대운.천간}이 앞서 작용하는 구간입니다`
      : `이 대운 ${대운.간지}의 뒤 다섯 해라 지지 ${대운.지지}가 앞서 작용하는 구간입니다`,
    // 대운 두 읽기 — 이 구간의 글자 하나로 본 판정(분할)과 간지 합친 판정(통합)을 나란히 (9차)
    대운읽기: 분할 ? { 분할: 이쪽.판정, 통합: 대운.읽기.통합.판정, 갈림: !!대운.읽기.갈림 } : null,
    차례비고: '천간이 앞 다섯 해·지지가 뒤 다섯 해라는 차례는 원문에 없다(관행). 원문은 운 한 글자가 다섯 해를 맡는다고만 한다',
  };
}

/**
 * 세운 글자 ↔ 대운 글자의 합·충 — **사실만** (2026-10-07, 9차)
 *   자평진전에는 세운이 대운을 합충한다는 편이 없다(歲·太歲·流年 낱말이 본문에 없다). 그래서 점수·길흉을 붙이지 않고
 *   간합(천간)·충·육합·삼합 묶음(지지)인지만 적는다. 읽는 쪽은 「묶임/풀림(사실만)」으로 쓴다.
 */
const 간합짝 = { 甲:'己', 己:'甲', 乙:'庚', 庚:'乙', 丙:'辛', 辛:'丙', 丁:'壬', 壬:'丁', 戊:'癸', 癸:'戊' };
const 충짝 = { 子:'午', 午:'子', 丑:'未', 未:'丑', 寅:'申', 申:'寅', 卯:'酉', 酉:'卯', 辰:'戌', 戌:'辰', 巳:'亥', 亥:'巳' };
const 육합짝 = { 子:'丑', 丑:'子', 寅:'亥', 亥:'寅', 卯:'戌', 戌:'卯', 辰:'酉', 酉:'辰', 巳:'申', 申:'巳', 午:'未', 未:'午' };
const 삼합묶음 = [{ 화:'木', 지:['亥','卯','未'], 왕:'卯' }, { 화:'火', 지:['寅','午','戌'], 왕:'午' },
                 { 화:'金', 지:['巳','酉','丑'], 왕:'酉' }, { 화:'水', 지:['申','子','辰'], 왕:'子' }];
function 대운관계(un, 대운) {
  const 없음 = { 합:null, 충:null, 육합:null, 회국:null,
    근거:'원문 없음 — 자평진전에 세운이 대운을 합충한다는 편이 없다. 점수·길흉 없이 사실만 적는다' };
  if (!대운 || !대운.천간 || !대운.지지) return 없음;
  const out = { ...없음 };
  if (간합짝[un.천간] === 대운.천간)
    out.합 = { 종류:'간합', 세운:un.천간, 대운:대운.천간, 설명:`세운 ${un.천간}이 대운 천간 ${대운.천간}(${대운.천간십성 ?? ''})과 ${un.천간}${대운.천간}합 — 대운 글자가 세운에 묶임(사실만)` };
  if (충짝[un.지지] === 대운.지지)
    out.충 = { 종류:'충', 세운:un.지지, 대운:대운.지지, 설명:`세운 ${un.지지}이 대운 지지 ${대운.지지}(${대운.지지십성 ?? ''})를 충 — 대운 글자가 세운에 흔들림(사실만)` };
  if (육합짝[un.지지] === 대운.지지)
    out.육합 = { 종류:'육합', 세운:un.지지, 대운:대운.지지, 설명:`세운 ${un.지지}이 대운 지지 ${대운.지지}(${대운.지지십성 ?? ''})와 ${un.지지}${대운.지지}합 — 대운 글자가 세운에 묶임(사실만)` };
  const 묶 = 삼합묶음.find(x => x.지.includes(un.지지) && x.지.includes(대운.지지) && un.지지 !== 대운.지지);
  if (묶) {
    const 왕있 = un.지지 === 묶.왕 || 대운.지지 === 묶.왕;
    out.회국 = { 종류: 왕있 ? '반합' : '같은 삼합 묶음(왕지 없음 — 국 아님)', 세운:un.지지, 대운:대운.지지, 화:묶.화,
      설명:`세운 ${un.지지}과 대운 지지 ${대운.지지}는 ${묶.화} 삼합의 글자${왕있 ? ' — 두 글자가 모여 반합(사실만)' : ' — 왕지가 없어 국으로 세지 않음(사실만)'}` };
  }
  return out;
}

/**
 * @param {number} year 서기 연도
 * @param {object} ctx  buildContext 결과
 * @param {object} r    judge() 결과
 * @param {object} m    명식
 * @param {object} 대운 그 해가 속한 대운 (없으면 null)
 */
function analyze(year, ctx, r, m, 대운 = null) {
  const gz = 연간지(year);
  const un = {
    간지: gz.간지, 천간: gz.천간, 지지: gz.지지,
    천간십성: sipseong(m.ilGan, gz.천간),
    지지십성: sipseong(m.ilGan, require('./jijanggan').jeonggi(gz.지지)),
  };

  // 25편 앞부분 — 격이 이룬 국의 희기로 이 해를 잰다(자평 읽기 — 참고로 남긴다)
  const rule = chwiun.lookup(ctx.gyeok, r.상신, ctx);
  const 자평읽기 = rule ? chwiun.judgeByRule(un, rule, ctx) : { 판정: '판단 보류', 비고: ['격의 희기가 정해지지 않았다'] };
  // ── 2026-10-07 사용자 결정 「층을 두고 세운도 적천수대로 해」 ──
  //   세운의 머리 판정은 滴天髓 歲運論(143~)으로 낸다: 「休咎係乎運，尤係乎歲」「太歲…重天干」 — 세운 천간 희기 ×2 + 지지 ×1 에
  //   대운과의 戰(천간 상극)·衝(지지 충)·和(간합·육합)를 더한다. 희기는 자평 취운 조문(격이 이룬 국)의 희·기를 빌린다(판정은 섞지 않음).
  //   자평 읽기(25편을 한 해에 적용한 것)는 `자평읽기` 로 함께 둔다. 9차의 「세운은 사실만」 결정은 이로써 사용자 결정으로 바뀌었다.
  const 속함 = (십성, 그룹) => 그룹 === '정관합거' ? false : (chwiun.群[그룹] ? chwiun.群[그룹].includes(십성) : 십성 === 그룹);
  const 희기of = rule ? (십성 => rule.기.some(g => 속함(십성, g)) ? -1 : rule.희.some(g => 속함(십성, g)) ? 1 : 0) : (() => 0);
  const 적천수 = jeokcheonsu.세운전충화(un, 대운, 희기of, ctx, m);
  const 길흉 = rule
    ? { 판정: __pj(Math.max(-2, Math.min(2, 적천수.점수))), 점수: 적천수.점수, 읽기: '적천수 歲運論', 비고: [...적천수.근거, ...적천수.사건.map(x => `${x.종류}(${x.꼴}${x.화 ? '→' + x.화 : ''}) ${x.가감 > 0 ? '+' : ''}${x.가감}: ${x.설명}`)], 전충화: 적천수.사건, 조문: 적천수.조문, 자평읽기: { 판정: 자평읽기.판정, 점수: 자평읽기.점수 } }
    : { ...자평읽기, 읽기: '보류' };

  // 26편 — 세운에는 **적용하지 않는다**(머리 주석). 성격·변격으로 읽힐 사건은 참고로만 적고 점수·판정에 넣지 않는다 (9차)
  const ub = unbyeonhwa.analyze(un, ctx, r, m);
  const 성격변격비고 = '26편 성격변격은 대운(「配之以運」「此五年中」)의 층이라 한 해에는 점수로 얹지 않았다 — 아래 참고 사건은 기록일 뿐이다';

  // 25편 뒷부분 — 운 간지가 원국과 맞물리는 자리
  const uc = unchung.analyze(un, ctx, m, 길흉.판정);
  if (uc.가감) {
    const 점 = (길흉.점수 ?? 0) + uc.가감;
    길흉.점수 = 점;
    길흉.판정 = __pj(Math.max(-2, Math.min(2, 점)));
  }

  // 28편 — 지지에 잠자던 것이 맑아지는가
  const tc = tuchong.analyze(un, ctx, m);

  길흉.비고 = [
    ...(길흉.비고 ?? []),
    ...uc.사건.map(x => x.설명),
    ...tc.사건.map(x => x.설명),
    ...ub.사건.map(x => `(참고, 점수 없음) ${x.설명}`),
  ];

  const 관계 = 대운관계(un, 대운);
  const 관계사실 = [관계.합, 관계.충, 관계.육합, 관계.회국].filter(Boolean);
  관계.근거 = '滴天髓 歲運論(143~) 戰·衝·和 — 2026-10-07 사용자 결정으로 세운↔대운 관계는 적천수 규칙으로 점수에 넣는다(자평진전에는 이 층이 없다)';

  return {
    연도: year, ...un,
    길흉,
    오년구간: 오년구간(year, 대운),
    대운: 대운 ? { 간지: 대운.간지, 시작나이: 대운.시작나이 } : null,
    // 26편은 적용하지 않는다 — 사건은 참고 기록, 점수 0
    성격변격: { 적용: false, 사유: 성격변격비고, 참고사건: ub.사건, 판정: ub.판정 },
    // 세운↔대운 합·충 — 사실만, 점수·길흉 없음, 원문 근거 없는 층
    대운관계: 관계,
    상호작용: uc, 투청: tc,
    비고: [
      성격변격비고,
      관계사실.length
        ? `세운↔대운 관계(적천수 歲運論 戰·衝·和로 읽음): ${관계사실.map(x => x.설명.replace(/\(사실만\)/g, '')).join(' / ')}`
        : '세운↔대운 합·충 없음',
      `세운 머리 판정은 滴天髓 歲運論(「休咎係乎運，尤係乎歲」「太歲…重天干」)으로 냈고, 자평진전 25편을 한 해에 적용한 읽기는 ${자평읽기.판정} — 둘이 갈리면 갈린다고만 말한다`,
    ],
    한계: '자평진전에는 세운을 따로 논한 편이 없어 머리 판정은 滴天髓 歲運論(세 번째 층)으로 낸다(2026-10-07 사용자 결정). 자평진전 25·27·28편을 한 해에 적용한 읽기는 자평읽기 로 함께 둔다. 26편 성격변격은 대운의 층이라 한 해에는 점수로 얹지 않았고(참고 기록만), 세운과 대운이 서로 합충하는 것은 원문에 근거가 없어 점수 없이 사실만 적었다',
  };
}

/**
 * 여러 해를 한 번에.
 * @param {object} opt { 시작연도, 개수, 대운목록, 출생연도 }
 */
function range(ctx, r, m, opt = {}) {
  const 시작 = opt.시작연도 ?? new Date().getFullYear();
  const 개수 = opt.개수 ?? 10;
  const 대운목록 = opt.대운목록 ?? [];
  const 출생 = opt.출생연도;

  const out = [];
  for (let y = 시작; y < 시작 + 개수; y++) {
    let 대운 = null;
    if (출생 && 대운목록.length) {
      const 나이 = y - 출생 + 1;                       // 세는 나이
      대운 = 대운목록.find(d => 나이 >= d.시작나이 && 나이 < d.시작나이 + 10) ?? null;
      if (대운 && 대운.시작연도 == null) 대운 = { ...대운, 시작연도: 출생 + 대운.시작나이 - 1 };
    }
    out.push(analyze(y, ctx, r, m, 대운));
  }
  return out;
}

