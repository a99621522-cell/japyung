const 일수 = (y,m,d) => Date.UTC(y, m-1, d) / 86400000;
const 날짜 = jd => { const o = new Date(jd*86400000);
  return { 년:o.getUTCFullYear(), 월:o.getUTCMonth()+1, 일:o.getUTCDate() }; };

/** 그 해의 달 목록 — [{월, 윤달, 시작JD, 길이}] */
function 달목록(y) {
  const r = 해[y - 시작해];
  if (!r) return null;
  const [윤, 비트, 개수, 정월] = r;
  const out = []; let jd = 정월, i = 0;
  for (let m = 1; m <= 12; m++) {
    for (const L of (m === 윤 ? [false, true] : [false])) {
      const 길이 = (비트 >> i) & 1 ? 30 : 29;
      out.push({ 월: m, 윤달: L, 시작JD: jd, 길이 });
      jd += 길이; i++;
      if (i >= 개수) return out;
    }
  }
  return out;
}

/** 음력 → 양력. 없는 날짜면 null */
function 양력으로(년, 월, 일, 윤달 = false) {
  const ms = 달목록(년);
  if (!ms) return null;
  const t = ms.find(x => x.월 === 월 && x.윤달 === !!윤달);
  if (!t) return null;
  if (일 < 1 || 일 > t.길이) return null;
  return 날짜(t.시작JD + 일 - 1);
}

