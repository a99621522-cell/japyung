/**
 * tuchong.js — 28편 「論支中喜忌逢運透清」
 * 사주팔자집 (2026-08-02)
 *
 * 27편과 짝을 이루는 편이다.
 *   27편: 「支主地，**靜以待用**」 — 지지는 쓰이기를 기다린다
 *   28편: 「逢運透清，則**靜而待用者，正得其用**，而喜忌之驗，於此乃見」
 *         — 운에서 그 글자가 천간으로 나오면, 기다리던 것이 비로소 제 쓰임을 얻는다
 *   기다리던 것이 언제 깨어나는가를 답하는 편이다.
 *
 * 「何謂透清？如甲用酉官，**逢辰未即爲財，而運透戊**；
 *   **逢午未即爲傷，而運透丁**之類是也。」
 *   — 원국 지지 속에 잠자던 십성이, 운의 천간으로 나오면 맑아져 작용한다.
 *
 * 「若**命與運二支會局，亦作清論**。如甲用酉官，本命有午，而運逢寅戌之類。」
 *   — 원국 지지와 운 지지가 회국해도 투청으로 본다.
 *
 * 「然**在年則重，在日次之，至於時生於午…則緩而不急矣**。」
 *   — 그 지지가 년에 있으면 무겁고, 일이면 그다음, 시면 더디고 급하지 않다.
 *   (25편의 충 완급은 「沖年月則急，沖時日則緩」으로 축이 다르다. 여기는 월이 빠져 있는데,
 *    월령의 것이 운에서 투청하는 경우는 26편 行運成格變格으로 따로 가기 때문이다 —
 *    원문이 마지막에 「即前篇所謂行運成格變格也」로 직접 연결한다.)
 *
 * 「雖格之成敗高低，八字已有定論 … 而**此五年中，亦能爲其禍福**。」
 *   — 격의 성패·고저는 원국에서 이미 정해졌으니 투청이 그것을 뒤집지는 않는다.
 *     다만 그 **5년 동안** 화복을 만들 수는 있다.
 *     대운 10년을 천간 5년·지지 5년으로 나눠 보는 근거가 여기 있다.
 */

const { JIJANGGAN, jeonggi, sipseong } = require('./jijanggan');
const hapchung = require('./hapchung');

const 경중 = { 년:'중(重)', 일:'차(次)', 시:'완(緩)' };

function analyze(un, ctx, m) {
  const 지 = { 년:m.yeonJi, 일:m.ilJi, 시:m.siJi };   // 월지는 26편 소관
  const 간 = [m.yeonGan, m.wolGan, m.siGan].filter(Boolean);
  const 사건 = [];

  // ① 운 천간이 원국 지지 속의 글자를 끌어내 맑힌다
  for (const p of ['년', '일', '시']) {
    const j = 지[p];
    if (!j) continue;
    const jg = JIJANGGAN[j].find(x => x.gan === un.천간);
    if (!jg) continue;
    if (간.includes(un.천간)) continue;          // 이미 원국 천간에 있으면 새로 맑아질 것이 없다
    사건.push({
      종류:'투청', 경로:'운간',
      자리:p, 지지:j, 글자:un.천간, 깊이:jg.wi,
      십성: sipseong(m.ilGan, un.천간),
      경중: 경중[p],
      설명:`${j}(${p}지) 속에 잠자던 ${sipseong(m.ilGan, un.천간)} ${un.천간}이 운의 천간으로 나와 맑아진다. ${p === '년' ? '년에 있는 것이라 무겁게 작용한다' : p === '일' ? '일에 있는 것이라 그다음으로 본다' : '시에 있는 것이라 더디고 급하지 않다'}`,
      원문:'逢辰未即爲財，而運透戊；逢午未即爲傷，而運透丁',
    });
  }

  // ② 원국 지지와 운 지지가 회국해도 투청으로 본다
  for (const s of hapchung.SAMHAP) {
    if (!s.ji.includes(un.지지)) continue;
    const 짝 = ['년', '일', '시'].filter(p => 지[p] && s.ji.includes(지[p]) && 지[p] !== un.지지);
    if (!짝.length) continue;
    const 십성 = sipseong(m.ilGan, jeonggi(s.wang));
    const 대표 = 짝[0];
    사건.push({
      종류:'투청', 경로:'회국',
      자리:대표, 지지:짝.map(p => 지[p]).join('·'), 십성, 경중:경중[대표],
      설명:`원국의 ${짝.map(p => `${지[p]}(${p}지)`).join('·')}과 운의 ${un.지지}이 모여 ${s.hwa}로 국을 이루니, 이 또한 맑아진 것으로 본다`,
      원문:'若命與運二支會局，亦作清論',
    });
  }

  return {
    사건,
    한계: '격의 성패와 고저는 원국에서 이미 정해졌다. 투청이 그것을 뒤집지는 않는다',
    범위: '다만 그 5년 동안은 화복을 만들 수 있다 — 대운 열 해를 천간 다섯 해·지지 다섯 해로 나눠 보는 근거가 여기 있다',
    원문: '雖格之成敗高低，八字已有定論 … 而此五年中，亦能爲其禍福',
  };
}

module.exports = { analyze, 경중 };
