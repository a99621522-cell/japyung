/**
 * oegyeok.js — 22편 「論外格用舍」
 * 사주팔자집 (2026-08-02)
 *
 * 「外格者，蓋因**月令無用**，權而用之，故曰外格也。」
 * — 외격은 월령에 쓸 것이 없을 때 임시로 빌려 쓰는 것이지 정식 취용이 아니다.
 *
 * 쓸 수 있는 경우:
 *   「如春木、冬水、土生四季之類，**日與月同**，難以作用」
 *   — 일간과 월령이 같은 오행이라 월령을 격으로 세울 수 없는 자리.
 *
 * 쓰지 말아야 할 경우 셋:
 *   ① 「若月令自有用神，豈可別尋外格？」 — 월령에 용신이 있으면 찾지 말 것
 *   ② 「干頭已有財官七煞，而棄之以就外格，亦大謬矣。
 *      **干頭有財，何用沖財？干頭有官，奚用合祿？**」
 *      「提綱有用提綱重」「有官莫尋格局」
 *   ③ **이 편의 핵심 경고** —
 *      「然所謂月令無用者，**原是月令本無用神**，而今人不知，
 *       往往以**財被劫、官被傷之類，用神已破，皆以爲月令無用**，
 *       而棄之以尋外格，則**謬之又謬**矣。」
 *      — 「월령무용」은 처음부터 쓸 것이 없다는 뜻이지,
 *        재가 겁탈당하고 관이 상해서 **격이 깨진 것**을 말하는 게 아니다.
 *        패격을 외격으로 도피시키는 것이 이 편이 가장 경계하는 잘못이다.
 *
 * 그래서 이 모듈의 주된 일은 외격을 잡아주는 것이 아니라 **막는 것**이다.
 */

const { GAN, jeonggi, sipseong } = require('./jijanggan');

// 22편은 「如春木、冬水、土生四季**之類**」라 하여 日與月同을 **예시로** 들 뿐이다.
// 실질 관문은 47편 論雜格이 준다 —
//   「大約要**干頭無官無煞**，方成外格。如有官煞，則自有官煞爲用，無勞外格矣。
//    **若透財尚可取格**，然財根深，或財透兩位，則亦以財爲重，不取外格也」
// 즉 필수는 '천간에 관살이 없을 것'이고, 재는 조건부로 허용된다.
const 관살 = ['정관', '편관'];
const 재 = ['정재', '편재'];

/**
 * @param {object} r judge() 결과
 * @param {object} m 명식
 */
function analyze(r, m) {
  const ctx = r.ctx;
  const 일월동 = GAN[jeonggi(m.wolJi)].ohaeng === GAN[m.ilGan].ohaeng;

  const 간 = [['년', m.yeonGan], ['월', m.wolGan], ['시', m.siGan]].filter(x => x[1]);
  const 간관살 = 간.filter(([, g]) => 관살.includes(sipseong(m.ilGan, g)))
                  .map(([p, g]) => `${sipseong(m.ilGan, g)}(${g}·${p})`);
  const 간재   = 간.filter(([, g]) => 재.includes(sipseong(m.ilGan, g)))
                  .map(([p, g]) => `${sipseong(m.ilGan, g)}(${g}·${p})`);
  const 재중   = 간재.length >= 2 || (ctx.sery?.재 ?? 0) >= 2.5;

  const 막는이유 = [];

  // ⓪ 「月令無用」 — 22편의 관문. 東里山人 按도 「沈氏所謂之月令無用者…刃祿不可爲用也」라 한다.
  //    월령에서 격을 세울 수 있으면 애초에 외격을 찾을 자리가 아니다.
  // 「일월동」은 원문이 든 **예시**일 뿐이고, 실질 기준은 「월령에서 격이 서는가」다.
  //   잡기월(辰戌丑未)에서 중기·여기가 투출해 취용하면 일간과 정기가 같은 오행이어도
  //   월령이 쓰인 것이다. 예: 戊土가 丑월인데 중기 辛이 투출하면 상관격이 선다.
  //   원문 16편 「雜氣透干會支」가 그 자리이므로, 이 경우도 외격을 막는다.
  // 2026-09-02 수정: 東里山人 按이 「沈氏所謂之月令無用者，即無財官印食傷梟煞也，
  //   **刃祿不可爲用也**」라 한다. 즉 월령무용은 인(양인)과 록(건록·월겁)을 함께 이른다.
  //   양인을 빼면 47편이 든 도충 예시(戊午 넉 기둥, 양인격)가 통째로 걸러진다.
  const 건록월겁 = ['건록', '월겁', '양인'].includes(ctx.gyeok);
  const 월령무용 = 일월동 && 건록월겁;   // 격이 실제로 비겁으로 떨어진 경우만

  if (!월령무용) 막는이유.push({
    사유:'월령에 용신이 있음',
    설명: 일월동
      ? `월령 ${m.wolJi}이 일간과 같은 오행이나, 속에 든 다른 글자가 투출해 ${ctx.gyeok}을 세웠다. 월령에 쓸 것이 있으면 외격을 따로 찾지 않는다`
      : `월령 ${m.wolJi}이 일간과 다른 오행이라 ${ctx.gyeok}을 세울 수 있다. 월령에 쓸 것이 있으면 외격을 따로 찾지 않는다`,
    원문:'若月令自有用神，豈可別尋外格？ / 提綱有用提綱重',
  });

  // ① 「如有官煞，則自有官煞爲用，無勞外格矣」 — 이것이 절대 관문이다
  if (간관살.length) 막는이유.push({
    사유:'천간에 관살이 있음',
    설명:`천간에 ${간관살.join('·')}이 드러나 있다. 관살이 있으면 그것으로 쓰면 되지 외격을 수고롭게 찾을 일이 없다. 천간에 관이 있는데 무엇하러 녹을 합하겠는가`,
    원문:'如有官煞，則自有官煞爲用，無勞外格矣 / 干頭有官，奚用合祿？',
  });

  // ② 재는 투출해도 무방하나, 뿌리가 깊거나 두 자리면 재를 중히 본다
  if (!간관살.length && 재중) 막는이유.push({
    사유:'재가 무겁다',
    설명:`천간의 재(${간재.join('·') || '지지'})가 뿌리 깊거나 두 자리에 걸쳐 있다. 이런 경우는 재를 중히 보아 외격을 취하지 않는다`,
    원문:'若透財尚可取格，然財根深，或財透兩位，則亦以財爲重，不取外格也',
  });

  // ③ 이 편이 가장 경계하는 잘못 — 패격을 월령무용으로 착각
  const 패격류 = ['패격', '성중유패', '상신미현', '미성립'].includes(r.결론);
  if (!월령무용 && 패격류) 막는이유.push({
    사유:'패격을 월령무용으로 착각',
    설명:`월령에 ${ctx.gyeok}이 서 있는데 성패가 ${r.결론}이라는 이유로 외격을 찾는 것은 원문이 「謬之又謬」라 한 잘못이다. 「월령무용」은 처음부터 쓸 것이 없다는 뜻이지 격이 깨졌다는 뜻이 아니다`,
    원문:'往往以財被劫、官被傷之類，用神已破，皆以爲月令無用，而棄之以尋外格，則謬之又謬矣',
  });

  const 가능 = 막는이유.length === 0;
  return {
    외격검토가능: 가능,
    일월동, 월령무용, 간관살, 간재, 재중,
    막는이유,
    판정: 가능 ? '외격 검토 가능 (月令無用)' : '외격 불가 — 정격으로 본다',
    설명: 가능
      ? `천간에 관살이 드러나지 않았고${재중 ? '' : ' 재도 무겁지 않아'} 원문이 말한 「월령무용」에 해당한다${월령무용 ? '. 일간과 월령이 같은 오행이라 월령을 격으로 세우기도 어렵다' : ''}. 외격을 빌려 볼 수 있다`
      : 막는이유.map(x => x.설명).join(' / '),
    // 從格(棄命從財·棄命從煞)은 이 편이 말하는 「月令無用」과 범주가 다르다.
    //   從格은 월령에 용신이 있어도 일간이 무력해 따라가는 것이므로,
    //   자평진전 안에서는 외격이 아니라 적천수 계열(jeokcheonsu.js)의 전왕으로 다룬다.
    종격여부: '從格은 이 판정의 대상이 아니다 — 적천수 계열의 전왕으로 본다',
    주의: '외격은 權而用之 — 임시로 빌려 쓰는 것이지 정식 취용이 아니다. 격이 깨졌다는 이유로 외격을 찾는 것은 원문이 「謬之又謬」라 한 잘못이다',
  };
}

module.exports = { analyze };
