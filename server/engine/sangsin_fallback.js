/**
 * sangsin_fallback.js — 8편 「論用神」의 順逆之大略을 상신 폴백으로
 * 사주팔자집 (2026-08-02)
 *
 * 조문은 원문을 옮긴 것이라 손대지 않는다.
 * 다만 조문이 모두 빗나가 상신을 지목하지 못할 때, **원문이 스스로 밝혀둔
 * 상위 원칙**으로 내려가 고른다. 8편이 그것을 「順逆之大略」이라 부른다.
 *
 * 「是以善而順用之，則
 *    **財喜食神以相生，生官以護財**；
 *    **官喜透財以相生，生印以護官**；
 *    **印喜官煞以相生，劫財以護印**；
 *    **食喜身旺以相生，生財以護食**。
 *  不善而逆用之，則
 *    **七煞喜食傷以制伏**，忌財印以資扶；
 *    **傷官喜配印以制伏，生財以化傷**；
 *    **陽刃喜官煞以制伏**，忌官煞之俱無；
 *    **月劫透官以制伏，用財而透食以化劫**。
 *  此順逆之大略也。」
 *
 * 조문이 개별 사례라면 이것은 대략이다. 특별한 규정이 없을 때 일반 규정으로
 * 내려가는 것이지, 부록 명식에 맞추려고 조건을 넓히는 것이 아니다.
 * 30편이 「論命取運，偶然湊合，而遂以己見爲不易」라 경계한 것을 피하는 길이기도 하다.
 *
 * 고르는 순서는 원문이 적어둔 순서를 그대로 따른다.
 * 그리고 15편 「凡全局之格，賴此一字而成者，均謂之相也」에 따라
 * **실제로 그 글자가 원국에 드러나 있어야** 상신으로 삼는다. 천간을 먼저 본다.
 */

const { sipseong, jeonggi, JIJANGGAN } = require('./jijanggan');

/** 격 → 상신 후보 (원문에 적힌 순서 그대로) */
const 大略 = {
  // 「食神」은 계열로 읽는다. 원문 자신이 다른 곳에서 「七煞喜食傷以制伏」처럼 食傷을 묶어 부르고,
  // 부록의 汪學士는 「財用傷以化劫」으로 상관을 상신으로 든다.
  정재: { 용법:'순용', 후보:['식신', '상관', '정관'], 원문:'財喜食神以相生，生官以護財' },
  편재: { 용법:'순용', 후보:['식신', '상관', '정관'], 원문:'財喜食神以相生，生官以護財' },
  정관: { 용법:'순용', 후보:['정재', '편재', '정인', '편인'], 원문:'官喜透財以相生，生印以護官' },
  정인: { 용법:'순용', 후보:['정관', '편관', '겁재'], 원문:'印喜官煞以相生，劫財以護印' },
  편인: { 용법:'순용', 후보:['정관', '편관', '겁재'], 원문:'印喜官煞以相生，劫財以護印' },
  식신: { 용법:'순용', 후보:['비견', '겁재', '정재', '편재'], 원문:'食喜身旺以相生，生財以護食' },

  편관: { 용법:'역용', 후보:['식신', '상관'], 기:['정재','편재','정인','편인'],
          원문:'七煞喜食傷以制伏，忌財印以資扶' },
  상관: { 용법:'역용', 후보:['정인', '편인', '정재', '편재'],
          원문:'傷官喜配印以制伏，生財以化傷' },
  양인: { 용법:'역용', 후보:['정관', '편관'],
          원문:'陽刃喜官煞以制伏，忌官煞之俱無' },
  건록: { 용법:'역용', 후보:['정관', '정재', '편재', '식신', '상관'],
          원문:'月劫透官以制伏，用財而透食以化劫' },
};

/**
 * 그 십성이 상신이 될 만큼 드러나 있는가.
 *
 * 세 갈래로 나뉜다.
 *   ① 천간에 있고 합거되지 않았다 → 그대로 상신
 *   ② 천간에 있었는데 합에 묶였다 → **그 십성은 자격을 잃는다.** 지지도 보지 않는다.
 *      15편 「相神有傷，立敗其格」 — 상신이 될 글자가 묶이면 격을 떠받칠 것이 없어진 것이지,
 *      지지에 같은 십성이 숨어 있다고 대신 세울 수 있는 것이 아니다.
 *      잡기정관 壬戌丁未戊申乙卯의 부록평이 「財印相合」인 것이 이 경우다 — 孤官無輔가 답이다.
 *   ③ 천간에 아예 없다 → 지지에서 찾되, 27편 「支主地，靜以待用」에 따라
 *      천간에 드러난 것보다 약한 것으로 표시한다.
 */
function 드러남(m, ctx, 십성) {
  const 천간 = [['월', m.wolGan], ['시', m.siGan], ['년', m.yeonGan]].filter(x => x[1]);
  const 해당 = 천간.filter(([, g]) => sipseong(m.ilGan, g) === 십성);

  if (해당.length) {
    const 성한것 = 해당.find(([, g]) => !(ctx.합거 ?? []).some(x => x.천간 === g));
    if (성한것) return { 자리: 성한것[0] + '간', 글자: 성한것[1], 종류: '천간' };
    return { 자격상실: true };          // 천간에 있었으나 전부 합에 묶임
  }

  for (const [p, j] of [['월', m.wolJi], ['일', m.ilJi], ['시', m.siJi], ['년', m.yeonJi]]) {
    if (!j) continue;
    if (JIJANGGAN[j].some(x => sipseong(m.ilGan, x.gan) === 십성))
      return { 자리: p + '지', 글자: j, 종류: '지지', 약함: true };
  }
  return null;
}

/**
 * @param {string} 격
 * @param {object} ctx
 * @param {object} m
 * @returns {object|null} { 상신, 근거, 원문, 자리 } 또는 null
 */
function pick(격, ctx, m) {
  const 표 = 大略[격];
  if (!표) return null;

  // 후보 순서보다 먼저 걸리는 것이 있다 — **천간에 드러난 것이 지지에 숨은 것보다 앞선다.**
  //   27편 「干主天，動而有爲；支主地，靜以待用」
  //   汪學士 甲子辛未辛酉壬辰의 부록평이 「財用傷以化劫」인 것이 그 예다 —
  //   식신은 子 속에 숨어 있고 상관 壬은 천간에 나와 있으니, 순서상 뒤인 상관을 쓴다.
  const 후보목록 = 표.후보
    .map(x => ({ 십성: x, 있음: 드러남(m, ctx, x) }))
    .filter(x => x.있음 && !x.있음.자격상실 && !표.기?.includes(x.십성));
  const 천간것 = 후보목록.filter(x => x.있음.종류 === '천간');
  const 정렬 = [...천간것, ...후보목록.filter(x => x.있음.종류 !== '천간')];

  for (const { 십성: 후보, 있음 } of 정렬) {
    return {
      상신: 후보,
      자리: 있음,
      근거: `조문이 지목하지 않아 8편의 「順逆之大略」으로 골랐다 — ${격}격은 ${표.용법}이므로 ${표.후보.join('·')} 순으로 보고, 그중 ${후보}(${있음.글자}·${있음.자리})이 드러나 있다${있음.약함 ? '. 다만 천간이 아니라 지지에 있으니 그만큼 약하게 본다' : ''}`,
      원문: 표.원문,
      폴백: true,
    };
  }
  return null;
}

module.exports = { 大略, pick, 드러남 };
