/** 브리프에 붙일 용어 안내 — 나온 용어만 골라 넘긴다 */
function 용어안내(쓰인용어 = []) {
  const 표 = { ...십성말, ...구조말 };
  const 목록 = [...new Set(쓰인용어)].filter(k => 표[k]);
  if (!목록.length) return '';
  return ['[용어를 이렇게 풀어 쓰세요]',
    ...목록.map(k => `  ${k} → ${표[k].쉬운말}${표[k].풀이 ? ` (${표[k].풀이})` : ''}`),
  ].join('\n');
}

/** 글에서 쓰인 용어 뽑기 */
function 용어추출(text) {
  const 표 = { ...십성말, ...구조말 };
  return Object.keys(표).filter(k => text.includes(k));
}

// ── 한자 검사 ────────────────────────────────────
const 한자 = /[\u4E00-\u9FFF]/g;

/**
 * 답에 한자가 얼마나 섞였는지.
 * 간지(甲子 등)와 괄호 병기 한둘은 봐줄 만하지만, 원문 인용이 통째로 들어오면 막는다.
 * @param {number} 허용 몇 자까지 봐줄 것인가
 */
function lintHanja(text, 허용 = 12) {
  const 전부 = text.match(한자) ?? [];
  // 간지 60개는 어차피 명식 표기에 필요하니 세지 않는다
  const 간지자 = new Set('甲乙丙丁戊己庚辛壬癸子丑寅卯辰巳午未申酉戌亥'.split(''));
  const 간지빼고 = 전부.filter(c => !간지자.has(c));
  // 이어진 한문 덩어리(4자 이상)는 원문을 통째로 옮긴 것으로 본다
  const 덩어리 = (text.match(/[\u4E00-\u9FFF]{4,}/g) ?? [])
    .filter(s => ![...s].every(c => 간지자.has(c)));
  const 통과 = 간지빼고.length <= 허용 && 덩어리.length === 0;
  return {
    통과,
    한자수: 간지빼고.length, 덩어리,
    사유: 통과 ? '한자 과다 없음'
      : 덩어리.length
        ? `원문을 그대로 옮긴 대목이 있다: ${덩어리.slice(0,3).join(' / ')}`
        : `한자가 ${간지빼고.length}자로 많다 (허용 ${허용})`,
  };
}

