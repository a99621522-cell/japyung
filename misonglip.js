/**
 * misonglip.js — 격이 미성립일 때 어디를 더 봐야 하는가
 * 사주팔자집
 *
 * 문제: 「미성립」에서 멈추면 원문이 시키는 일을 절반만 한 것이다.
 *   원문은 격이 안 섰다고 거기서 끝내지 않는다. 네 갈래를 더 묻는다.
 *
 *   ① 살려낼 것이 있나          ← 13편 「因敗得成」
 *   ② 외격으로 갈 자리인가       ← 22편 (대개 아니다)
 *   ③ 지지에 숨어 있나           ← 27편 「支主地，靜以待用」
 *   ④ 운에서 서는가              ← 26편 성격 · 28편 투청
 *
 * 특히 ③④가 중요하다. 「원국에 없다」와 「원국에 안 드러났다」는 다르다.
 *   卯 속에 乙이 둘 있는데 천간에 안 나온 것은 「없는 것」이 아니라
 *   「아직 안 나선 것」이다. 운에서 투청하면 그때 격이 선다.
 *
 * 그러므로 이 모듈의 결론은 「안 된다」가 아니라 **「언제 되는가」**다.
 */

const { JIJANGGAN, GAN, sipseong, jeonggi } = require('./jijanggan');

/** 격을 다스리거나 살려 쓸 후보 십성 — 8편의 순용·역용 */
const 필요십성 = {
  정관: ['정재', '편재', '정인', '편인'],
  편관: ['식신', '상관', '정인', '편인', '양인', '비견', '겁재'],
  정재: ['식신', '상관', '정관', '정인', '편인'],
  편재: ['식신', '상관', '정관', '정인', '편인'],
  정인: ['정관', '편관', '식신', '상관'],
  편인: ['정관', '편관', '식신', '상관'],
  식신: ['정재', '편재', '편관', '정인', '편인'],
  상관: ['정재', '편재', '정인', '편인', '편관'],
  양인: ['정관', '편관', '식신', '상관'],
  건록: ['정관', '편관', '정재', '편재', '식신', '상관'],
};

function analyze(결과, m) {
  const 격 = 결과.결론?.격 ?? 결과.격;
  const 성패 = 결과.결론?.성패 ?? 결과.성패;
  if (성패 !== '상신미현' && 성패 !== '미성립') {
    return { 해당없음: true, 사유: `성패가 ${성패}이므로 이 검토는 필요 없다` };
  }

  const ilGan = m.ilGan;
  const 후보 = 필요십성[격] ?? [];
  const 천간 = [m.yeonGan, m.wolGan, m.siGan].filter(Boolean);
  const 지지 = [m.yeonJi, m.wolJi, m.ilJi, m.siJi].filter(Boolean);

  // ── ③ 지지에 숨어 있는가 ──────────────────────
  const 숨은것 = [];
  const 자리이름 = { [m.yeonJi]: '년', [m.wolJi]: '월', [m.ilJi]: '일', [m.siJi]: '시' };
  for (const p of ['yeonJi', 'wolJi', 'ilJi', 'siJi']) {
    const j = m[p];
    if (!j) continue;
    const 자리 = { yeonJi: '년', wolJi: '월', ilJi: '일', siJi: '시' }[p];
    for (const jg of JIJANGGAN[j]) {
      const ss = sipseong(ilGan, jg.gan);
      if (!후보.includes(ss)) continue;
      if (천간.includes(jg.gan)) continue;      // 이미 드러난 것은 제외
      숨은것.push({ 자리, 지지: j, 글자: jg.gan, 위: jg.wi, 십성: ss });
    }
  }

  // ── ④ 운에서 무엇이 오면 서는가 ───────────────
  // 숨은 것을 끌어낼 천간 + 아예 없는 후보를 데려올 천간
  const 대기천간 = new Set();
  for (const x of 숨은것) 대기천간.add(x.글자);
  for (const ss of 후보) {
    for (const g of Object.keys(GAN)) {
      if (sipseong(ilGan, g) === ss) 대기천간.add(g);
    }
  }
  const 열쇠 = [...대기천간].map(g => ({
    글자: g, 십성: sipseong(ilGan, g),
    경로: 숨은것.some(x => x.글자 === g)
      ? '원국 지지에 있는 것이 운에서 드러난다 (투청)'
      : '원국에 없던 것이 운에서 온다',
  }));

  // ── 결론 ─────────────────────────────────────
  const 있음 = 숨은것.length > 0;
  return {
    격, 성패,
    검토: [
      { 갈래: '① 살려낼 것이 있나', 편: '13편',
        답: '성패 판정에서 이미 확인했다. 구응 조문이 걸리지 않았다',
        원문: '因敗得成' },
      { 갈래: '② 외격으로 갈 자리인가', 편: '22편',
        답: '단계22_외격 결과를 보라. 대개 아니다',
        원문: '格之敗者，非月令無用也。以此爲月令無用而尋外格，謬之又謬矣' },
      { 갈래: '③ 지지에 숨어 있나', 편: '27편',
        답: 있음
          ? `있다 — ${숨은것.map(x => `${x.지지}(${x.자리}) 속 ${x.글자}(${x.십성})`).join(', ')}`
          : '없다 — 지지에도 쓸 것이 없다',
        원문: '支主地，靜以待用' },
      { 갈래: '④ 운에서 서는가', 편: '26·28편',
        답: 열쇠.length
          ? `${열쇠.map(x => x.글자 + '(' + x.십성 + ')').join(' · ')}이 오면 격이 설 수 있다`
          : '기다릴 것이 없다',
        원문: '運中透清，則與命中原有者，不甚相懸，即前篇所謂行運成格變格是也' },
    ],
    숨은것, 열쇠,
    판정: 있음
      ? '아직 안 선 것 — 지지에 재료가 있으니 운에서 드러나기를 기다린다'
      : '기다리는 것 — 원국에 재료가 없으니 운에서 오기를 기다린다',
    상담문구: 있음
      ? '지금은 다스릴 방도가 드러나 있지 않습니다. 다만 없는 게 아니라 숨어 있습니다. 그것이 운에서 끌려 나오면 격이 섭니다.'
      : '지금은 다스릴 방도가 원국에 없습니다. 운에서 오기를 기다리는 구조입니다.',
    경계: '「안 된다」가 아니라 「아직」이다. 그리고 언제 서는지까지 말한 뒤에 멈춘다 — 그 뒤의 일은 명식이 답하지 않는다',
  };
}

module.exports = { analyze, 필요십성 };
