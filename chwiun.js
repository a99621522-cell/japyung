/**
 * 점수를 판정어로 옮긴다 — 「대길·대흉」을 쓰지 않는 까닭
 *
 * 18·19편: 「財官印食…用之不當，亦能破格」「煞傷劫刃…用之得宜，亦能成格」
 * 서락오: 「官煞財印食傷은 오행 생극의 대명사일 뿐 길흉이랄 것이 없다」
 *
 * 운은 들어오는 기운이고, 판정은 그것이 명의 짜임과 어떻게 만나는가다.
 * 「대길」이라 적으면 읽는 사람이 곧바로 「성공」으로 옮긴다 — 그것이 잘못이다.
 * 높이 오르내림이 아니라 **결이 살아나는가 눌리는가**를 적는다.
 */
const jeoul = require('./jeoul');

function 판정어로(점수) {
  const 표 = ['결이 크게 눌림', '결이 눌림', '뒤섞임', '결이 살아남', '결이 크게 살아남'];
  return 표[Math.max(0, Math.min(4, Math.round(점수) + 2))];
}

function lookup(격, 상신, ctx) {
  const 표 = CHWIUN[표키[격] ?? 격];
  if (!표) return null;

  const 별 = 상신별칭[표키[격] ?? 격]?.[상신];
  const 항 = 표[상신] ?? (별 ? 표[별] : null) ?? 표._기본;
  if (!항) return null;

  const 조정 = 항.조건 ? 항.조건(ctx) : null;
  const 공통 = 표._공통기 ?? null;

  // 조문이 「저울 문장」인데 희가 비어 있으면 — 원문이 시킨 저울을 실제로 잰다.
  //   「煞重食輕則助食…」 같은 조문은 무엇이 얇은지 봐야 비로소 희가 정해진다.
  //   숫자로 재지 않고 드러남·뿌리·자릿수만 본다 (jeoul.js 주석 참조).
  let 희 = 조정?.희 ?? 항.희;
  let 저울 = null;
  if ((희 ?? []).length === 0 && ctx?.m) {
    저울 = jeoul.저울로희기(격, 상신, ctx.m);
    if (저울 && !저울.보류) {
      // 조문이 명시적으로 꺼린 것은 저울이 뒤집지 못한다.
      //   식신제살은 「畏印綬之奪食」이라 인수를 꺼리는데, 저울이 「몸을 돕는다」며
      //   인수를 넣으면 조문과 어긋난다. 조문이 먼저다.
      const 기목록 = [...(조정?.기 ?? 항.기), ...(공통?.기 ?? [])];
      희 = 저울.희.filter(x => !기목록.includes(x));
      if (희.length === 0) { 희 = []; 저울 = { ...저울, 보류: true,
        사유: 저울.사유 + ' — 다만 조문이 그것을 꺼리므로 채우지 않는다' }; }
    }
  }

  return {
    격, 상신: 상신 ?? '(기본)',
    희,
    저울,
    기: [...(조정?.기 ?? 항.기), ...(공통?.기 ?? [])],
    비고: 조정?.비고 ?? null,
    원문: [항.원문, 공통?.원문].filter(Boolean),
    대조: 대조상태[격] ?? '미확보',
  };
}

/**
 * 대운 하나를 격국 취운 조문으로 판정한다.
 * @param {object} un   haengun.daeun()이 만든 대운 항목
 * @param {object} rule lookup() 결과
 */
function judgeByRule(un, rule, ctx) {
  const 속함 = (십성, 그룹) => 그룹 === '정관합거' ? false
    : (群[그룹] ? 群[그룹].includes(십성) : 십성 === 그룹);

  const 평가 = (십성) => {
    if (rule.기.some(g => 속함(십성, g))) return -1;
    if (rule.희.some(g => 속함(십성, g))) return  1;
    return 0;
  };

  let g = 평가(un.천간십성);
  let j = 평가(un.지지십성);

  // 「論行運」 반전층 — 似喜而實忌 / 似忌而實喜
  const 반전기록 = [];
  if (ctx) {
    for (const [십성, 자리] of [[un.천간십성,'천간'], [un.지지십성,'지지']]) {
      const b = applyBanjeon(rule.격, 십성, ctx);
      if (!b) continue;
      if (b.방향 === '희→기') { if (자리==='천간') g = -1; else j = -1; }
      else                    { if (자리==='천간') g =  1; else j =  1; }
      반전기록.push(`${자리} ${십성}운 — ${b.방향} (${b.원문})`);
    }
  }
  const 합 = g + j;

  // ── 판정어 ────────────────────────────────────
  // 「대길·대흉」 같은 말은 읽는 사람이 곧바로 **성공·실패**로 옮긴다.
  // 그런데 18·19편이 말한 것은 그 반대다 —
  //   「財官印食，四吉神也，然用之不當，亦能破格」
  //   「煞傷劫刃，四凶神也，然用之得宜，亦能成格」
  // 서락오도 「官煞財印食傷은 오행 생극의 대명사일 뿐 길흉이랄 것이 없다.
  //   내 필요에 맞으면 길이라 하고 안 맞으면 흉이라 한다」고 못박는다.
  //
  // 즉 운은 **들어오는 기운**이고, 판정은 그것이 **명의 짜임과 어떻게 만나는가**다.
  // 그래서 「결이 살아난다 / 눌린다」로 적는다. 높이 오르내림을 말하는 것이 아니다.
  const 판정어 = ['결이 크게 눌림', '결이 눌림', '뒤섞임', '결이 살아남', '결이 크게 살아남'];
  const 판정 = 판정어[Math.max(0, Math.min(4, 합 + 2))];

  return {
    판정,
    // ※ 「판정_옛(대길·대흉)」은 두지 않는다.
    //   뒤에서 점수를 다시 조정하는 층(unbyeonhwa·unchung·tuchong)이 있어
    //   그 값만 낡은 채로 남으면 화면에 어긋난 판정이 나간다.
    //   점수 하나만 남기고 판정어는 언제나 점수에서 다시 뽑는다.
    점수: 합,
    천간: `${un.천간십성}운 — ${g > 0 ? '희' : g < 0 ? '기' : '한신'}`,
    지지: `${un.지지십성}운 — ${j > 0 ? '희' : j < 0 ? '기' : '한신'}`,
    간지불일치: g * j < 0,
    근거: rule.원문[0],
    비고: [
      rule.비고,
      g * j < 0 ? '천간과 지지의 희기가 엇갈린다 — 10년을 통으로 보지 말 것' : null,
      ...반전기록,
      rule.대조 !== '전문' ? `※ 이 격의 취운 조문은 원문 ${rule.대조} 대조 상태` : null,
    ].filter(Boolean),
  };
}

/**
 * 반전층 — 「論行運」
 *   「其有似喜而實忌者 … 有似忌而實喜者」
 *   겉으로는 희신인데 실제로는 기신이고, 그 반대도 있다.
 *   앞의 희기 판정을 뒤집는 마지막 관문이다.
 */
const 반전 = [
  { 방향:'희→기', 격:['정관'], 운:'인',
    조건: c => (c.합거 ?? []).length > 0,
    원문:'官逢印運，而本命有合。' },
  { 방향:'희→기', 격:['정인','편인'], 운:'정관',
    조건: c => (c.cheongan?.['편관']?.length ?? 0) > 0,
    원문:'印逢官運，而本命用煞。' },
  { 방향:'기→희', 격:['정관'], 운:'상관',
    조건: c => (c.유효천간?.['정인']?.length || c.유효천간?.['편인']?.length) > 0,
    원문:'官逢傷運，而命透印。' },
  { 방향:'기→희', 격:['정재','편재'], 운:'편관',
    조건: c => (c.유효천간?.['식신']?.length ?? 0) > 0,
    원문:'財行煞運，而命透食。' },
];

function applyBanjeon(격, 십성, ctx) {
  for (const r of 반전) {
    if (!r.격.includes(격)) continue;
    const 매치 = 群[r.운] ? 群[r.운].includes(십성) : 십성 === r.운;
    if (!매치) continue;
    if (!r.조건(ctx)) continue;
    return r;
  }
  return null;
}

