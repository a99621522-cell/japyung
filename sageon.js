/**
 * sageon.js — 해마다 들기 쉬운 일 (2026-10-10, 40차, 사용자 「사람들이 구체적 사건이 없어 이현령비현령하고 추상적인 답변이 많아 재미없다던데」)
 *
 * 답이 「흐름이 열린다」「결이 살아난다」로만 흘러 무슨 일이 있다는 건지 알 수 없었다. 엔진이 그해 글자로 **들기 쉬운 일의 이름**을 셈해 준다.
 *   ① 그해 위 글자(드러나는 일)·아래 글자 본기(속에서 진행되는 일)의 십성 → 일의 이름 (통변 관례 표 — 원전 조문이 아니라 시중 통변을 옮긴 것, 아래 `일표`)
 *   ② 그 글자 오행이 적천수 자체 희기에서 반기는 쪽이면 「득」 말, 꺼리는 쪽이면 「실」 말 — 같은 재(財)라도 반기면 「목돈·계약」, 꺼리면 「지출·돈 다툼」
 *   ③ 그해 아래 글자가 원국 아래 글자와 충하는 자리(seun.흔들자리) → 자리의 사건 이름(이사·부서 이동…), 대운 글자와 충이면 「열 해 흐름이 바뀌는 해」
 * 사건을 못박지 않는다 — 「~가 들기 쉬운 해」로만 쓰게 하고(dapgeomsa 사건 단정은 그대로), 병·사고·사망·이별·사람 흉단은 표에 없다.
 * 세 책과 섞지 않는다: 희기는 적천수 층 것만 쓴다(세운 머리 판정이 적천수이므로 같은 눈).
 */
const { GAN, jeonggi } = require('./jijanggan');

// 십성 → [득(반기는 기운일 때), 실(꺼리는 기운일 때)] — 통변 관례
const 일표 = {
  정관: ['승진·자리 제안·인정받는 일', '책임이 무거워지는 일·윗사람과의 마찰'],
  편관: ['큰 과업·새 직책을 맡는 일', '압박·평가·감사가 몰리는 일'],
  정재: ['수입이 늘고 저축·계약이 성사되는 일', '고정 지출이 늘거나 돈이 묶이는 일'],
  편재: ['목돈·사업·투자 제안이 드는 일', '큰돈이 나가거나 투자에서 손해 보는 일'],
  정인: ['합격·자격증·문서(계약서·집 문서) 정리', '서류·계약이 늦어지는 일'],
  편인: ['새 공부·기술을 익히는 일·도와주는 윗사람', '계획이 자꾸 바뀌고 일이 더디는 일'],
  식신: ['새 일·일거리가 늘고 결과물을 내는 일', '일만 늘고 남는 게 적은 일'],
  상관: ['재주가 드러나는 일·독립·창업 준비', '말 때문에 생기는 마찰·그만두고 싶은 마음'],
  비견: ['동료·동업 제안·모임이 늘어나는 일', '경쟁이 붙거나 몫을 나누는 일'],
  겁재: ['함께 벌이는 일·사람을 통한 기회', '돈이 새거나 동업·형제 일로 다투는 일'],
};
// 인연 — 남명 재·여명 관(「女以官爲夫」)이 올 때 덧붙인다
const 인연 = ['인연·결혼 이야기가 드는 일', '관계에서 서운함이 생기기 쉬운 일'];
// 원국 아래 글자와 충 — 자리의 사건
const 자리일 = {
  년: '바깥 모임·집안 어른 쪽 일정이 바뀌는 일',
  월: '직장·부서 이동이나 부모님 쪽 일정이 바뀌는 일',
  일: '이사·집 고침·생활 리듬이 바뀌는 일',
  시: '자녀·후배 쪽 일이나 길게 잡은 계획이 바뀌는 일',
};
const 오행 = g => GAN[g] && GAN[g].ohaeng;

/** 한 해(세운 하나) → { 연도, 득[], 실[], 자리[], 말 } */
function 그해(s, m, opt = {}) {
  let H = null; try { H = require('./jeokcheonsu').희기(m); } catch (e) {}
  const 여 = opt.성별 === '여';
  const 득 = [], 실 = [];
  const 넣기 = (십, 글자, 곳) => {
    const 표 = 일표[십]; if (!표) return;
    const v = H ? H.값(오행(글자)) : 0;
    const 쪽 = v > 0 ? 득 : v < 0 ? 실 : null; if (!쪽) return;
    쪽.push({ 일: 표[v > 0 ? 0 : 1], 십성: 십, 곳 });
    if ((여 ? ['정관', '편관'] : ['정재', '편재']).includes(십)) 쪽.push({ 일: 인연[v > 0 ? 0 : 1], 십성: 십, 곳 });
  };
  넣기(s.천간십성, s.천간, '위');
  if (s.지지십성 !== s.천간십성) 넣기(s.지지십성, jeonggi(s.지지), '아래');
  let 자리 = [];
  try { 자리 = require('./seun').흔들자리(s, m).map(z => ({ 일: 자리일[z.자리], 자리: z.자리 })).filter(z => z.일); } catch (e) {}
  if (s.대운관계 && s.대운관계.충) 자리.push({ 일: '열 해의 큰 흐름이 바뀌는 고비(대운 글자와 부딪힘)', 자리: '대운' });
  const 이름 = a => [...new Set(a.map(x => x.일))];
  return { 연도: s.연도, 간지: s.간지, 득: 이름(득), 실: 이름(실), 자리: 이름(자리) };
}

/** 여러 해 → 브리프 한 줄 */
function 브리프줄(se, m, opt = {}) {
  try {
    const 해 = (se || []).filter(s => s && s.길흉).slice(0, opt.해수 || 7).map(s => 그해(s, m, opt));
    if (!해.length) return '';
    const 줄 = 해.map(h => `${h.연도}: ${[h.득.length ? '좋은 쪽 ' + h.득.join('·') : '', h.실.length ? '조심할 쪽 ' + h.실.join('·') : '', h.자리.length ? '바뀌기 쉬운 것 ' + h.자리.join('·') : ''].filter(Boolean).join(' / ') || '두드러진 일 없음(평이한 해)'}`).join(' ‖ ');
    return `[해마다 들기 쉬운 일 — 엔진 셈(그해 글자의 십성 + 적천수 희기 + 원국과 부딪히는 자리; 일의 이름은 통변 관례 표)] ${줄} — **「▶ 해마다 보면」 읽기 칸과 「▶ 한 줄로 말하면」에는 이 가운데 물으신 일에 닿는 것을 이름 그대로 한두 개 쓸 것**(「승진·자리 제안이 들기 쉬운 해」「이사·생활 리듬이 바뀌기 쉬운 해」). 「흐름이 열린다」「결이 살아난다」만으로 끝내지 말 것. 「좋을 수도 나쁠 수도」「상황에 따라 다르다」 같은 양다리 말 금지 — 표의 첫말 한쪽으로. 일이 반드시 일어난다고 못박지는 말 것(「~가 들기 쉬운」「~를 챙길」).`;
  } catch (e) { return ''; }
}

module.exports = { 그해, 브리프줄, 일표, 자리일 };
