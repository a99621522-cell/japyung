const 쪽 = 첫 => /열리는/.test(첫 || '') ? 1 : /조심|지키는/.test(첫 || '') ? -1 : 0;
function 갈림말(s) {
  const 적 = 첫말표[s && s.길흉 && s.길흉.판정], 자 = 첫말표[s && s.길흉 && s.길흉.자평읽기 && s.길흉.자평읽기.판정];
  return 적 && 자 && 쪽(적) * 쪽(자) < 0 ? `자평진전으로는 「${자}」 — 책마다 갈림` : '';
}
function 지나온(r, 출생연도, opt = {}) {
  let se = []; try { se = require('./seun').지나온해(r, Number(출생연도), { 최대: opt.최대 || 12 }); } catch (e) { return []; }
  return se.slice().reverse().map(s => { const 첫 = 첫말표[s.길흉.판정] || s.길흉.판정; const g = 그해(s, r.명식, opt); return { 연도: s.연도, 간지: s.간지, 나이: s.나이, 첫말: 첫, 일: 고른일(g, 첫), 할일: 할일(g, 첫), 갈림: 갈림말(s) }; });
}
