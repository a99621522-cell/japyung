/**
 * wolun.js — 월운(月運, 흔히 流月)
 * 사주팔자집 (2026-08-02)
 *
 * 세운과 같은 사정이다. **자평진전에는 월운을 논한 편이 없다.**
 * 論行運이 말하는 것은 대운이고, 세운조차 따로 다루지 않는다.
 * 그러니 여기서도 다른 책의 流月 규칙을 끌어오지 않고,
 * 이 책이 세워둔 방법을 달 단위에 그대로 적용한다.
 *   25편 「運中每運行一字，即必以此一字，配命中八字而統觀之」
 *
 * ── 다만 경중을 반드시 표시한다 ──────────────
 * 원문은 30편에서 「今人**不知輕重**，拘泥格局，執假失真」이라 하고,
 * 22편에서도 「月令，本也；外格，末也。今人不知輕重」이라 한다.
 * 경중을 모르는 것을 거듭 경계하는 책이다.
 *
 * 근거의 무게는 이렇게 다르다.
 *   대운 — 論行運이 직접 다룬다.                         **본(本)**
 *   세운 — 편이 없으나 28편이 「此五年中」으로 한 해 단위를 인정한다.  중간
 *   월운 — 편도 없고 달 단위를 인정한 대목도 없다.        **말(末)**
 * 그래서 월운은 판정을 내되 **격의 성패나 대운의 흐름을 뒤집는 것으로 읽지 않는다.**
 * 26편의 成格變格도 월운에는 적용하지 않는다 — 한 달이 격을 바꾼다는 말은 원문에 없다.
 */

const { 판정어로: __pj } = require('./chwiun');
const { sipseong, jeonggi } = require('./jijanggan');

/** 받침 여부로 조사를 고른다 — "춘분이" / "우수가" */
function 이가(w) {
  const c = w.charCodeAt(w.length - 1);
  const 받침 = c >= 0xAC00 && c <= 0xD7A3 && (c - 0xAC00) % 28 !== 0;
  return w + (받침 ? '이' : '가');
}
const chwiun = require('./chwiun');
const unchung = require('./unchung');
const tuchong = require('./tuchong');

const 天干 = ['甲', '乙', '丙', '丁', '戊', '己', '庚', '辛', '壬', '癸'];
// 월지는 寅월(입춘)부터 시작한다
const 月支 = ['寅', '卯', '辰', '巳', '午', '未', '申', '酉', '戌', '亥', '子', '丑'];

/** 五虎遁 — 그 해 천간에 따라 寅월의 천간이 정해진다 */
const 寅월천간 = { 甲:'丙', 己:'丙', 乙:'戊', 庚:'戊', 丙:'庚', 辛:'庚',
                 丁:'壬', 壬:'壬', 戊:'甲', 癸:'甲' };

/**
 * 24절기 가운데 **월을 가르는 것은 12절(節)**이고,
 * 나머지 12중기(中氣)는 그 달 안에 든다. 달의 경계는 節로만 잡는다.
 *   節  — 입춘 경칩 청명 입하 망종 소서 입추 백로 한로 입동 대설 소한
 *   中氣 — 우수 춘분 곡우 소만 하지 대서 처서 추분 상강 소설 동지 대한
 * 날짜는 대략이며 해마다 하루 이틀 움직인다.
 */
const 절기명 = { 寅:'입춘', 卯:'경칩', 辰:'청명', 巳:'입하', 午:'망종', 未:'소서',
                申:'입추', 酉:'백로', 戌:'한로', 亥:'입동', 子:'대설', 丑:'소한' };
const 절입일 = { 寅:4, 卯:6, 辰:5, 巳:6, 午:6, 未:7, 申:8, 酉:8, 戌:8, 亥:7, 子:7, 丑:6 };
const 중기명 = { 寅:'우수', 卯:'춘분', 辰:'곡우', 巳:'소만', 午:'하지', 未:'대서',
                申:'처서', 酉:'추분', 戌:'상강', 亥:'소설', 子:'동지', 丑:'대한' };
const 중기일 = { 寅:19, 卯:21, 辰:20, 巳:21, 午:21, 未:23, 申:23, 酉:23, 戌:23, 亥:22, 子:22, 丑:20 };

/**
 * 그 해 그 달의 간지.
 * @param {string} 세운천간 그 해의 천간
 * @param {number} idx 寅월을 0으로 한 순번 (0~11)
 */
function 월간지(세운천간, idx) {
  const 시작 = 天干.indexOf(寅월천간[세운천간]);
  const 지지 = 月支[idx];
  return { 천간: 天干[(시작 + idx) % 10], 지지, 간지: 天干[(시작 + idx) % 10] + 지지,
           절기: 절기명[지지], 절입일: 절입일[지지],
           중기: 중기명[지지], 중기일: 중기일[지지],
           // 寅월은 양력 2월 입춘부터다. 子월(idx 10)이 12월, 丑월(idx 11)은 다음 해 1월이 된다.
           양력월: ((idx + 1) % 12) + 1, 다음해: idx === 11 };
}

/**
 * @param {object} 세 seun.analyze 결과 (그 해)
 */
function analyze(세, ctx, r, m, opt = {}) {
  const rule = chwiun.lookup(ctx.gyeok, r.상신, ctx);
  const out = [];

  for (let i = 0; i < 12; i++) {
    const g = 월간지(세.천간, i);
    const un = {
      간지: g.간지, 천간: g.천간, 지지: g.지지,
      천간십성: sipseong(m.ilGan, g.천간),
      지지십성: sipseong(m.ilGan, jeonggi(g.지지)),
    };

    const 길흉 = rule ? chwiun.judgeByRule(un, rule, ctx)
                      : { 판정: '판단 보류', 비고: ['격의 희기가 정해지지 않았다'] };

    // 25편 — 운 간지가 원국과 맞물리는 자리. 달에도 그대로 적용한다.
    const uc = unchung.analyze(un, ctx, m, 길흉.판정);
    if (uc.가감) {
      const 점 = (길흉.점수 ?? 0) + uc.가감;
      길흉.점수 = 점;
      길흉.판정 = __pj(Math.max(-2, Math.min(2, 점)));
    }
    // 28편 — 지지에 잠자던 것이 맑아지는가
    const tc = tuchong.analyze(un, ctx, m);

    // 26편 成格變格은 적용하지 않는다 — 한 달이 격을 바꾼다는 말은 원문에 없다
    길흉.비고 = [...(길흉.비고 ?? []), ...uc.사건.map(x => x.설명), ...tc.사건.map(x => x.설명)];

    out.push({
      연도: 세.연도, 순번: i + 1, 양력월: g.양력월,
      간지: g.간지, 천간: g.천간, 지지: g.지지,
      천간십성: un.천간십성, 지지십성: un.지지십성,
      절기: g.절기, 절입일: g.절입일, 중기: g.중기, 중기일: g.중기일,
      다음해: g.다음해,
      기간설명: `${g.다음해 ? (세.연도 + 1) + '년 ' : ''}${g.양력월}월 ${g.절입일}일 무렵 ${g.절기}부터`,
      중기설명: `${g.양력월}월 ${g.중기일}일 무렵 ${이가(g.중기)} 이 달의 한가운데`,
      길흉, 상호작용: uc, 투청: tc,
    });
  }

  return {
    연도: 세.연도, 세운간지: 세.간지, 달: out,
    경중: '월운은 말단이다. 대운은 원문이 直接 다루고(論行運), 세운은 28편이 「此五年中」으로 한 해 단위를 인정하나, 달 단위를 인정한 대목은 원문에 없다',
    한계: [
      '자평진전에는 월운을 논한 편이 없다. 이 판정은 25편의 방법(운의 한 글자를 원국에 대어 본다)을 달에 적용한 것이다',
      '26편의 成格變格은 적용하지 않았다 — 한 달이 격을 바꾼다는 말은 원문에 없다',
      '월운은 격의 성패나 대운의 흐름을 뒤집는 것으로 읽지 않는다',
      '달의 경계는 24절기 가운데 12절(節)로 잡는다. 12중기(中氣)는 달을 가르지 않고 그 달 한가운데 든다',
      '절입일은 해마다 하루 이틀 움직이므로 경계에 걸린 날은 정확한 절입 시각을 확인해야 한다',
    ],
  };
}

module.exports = { 월간지, analyze, 절기명, 절입일, 중기명, 중기일 };

