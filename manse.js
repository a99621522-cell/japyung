// ─────────────────────────────────────────────
const 월두 = { 甲:2, 己:2, 乙:4, 庚:4, 丙:6, 辛:6, 丁:8, 壬:8, 戊:0, 癸:0 };
const 시두 = { 甲:0, 己:0, 乙:2, 庚:2, 丙:4, 辛:4, 丁:6, 壬:6, 戊:8, 癸:8 };

/**
 * @param {number} y,m,d,h,min  양력 생년월일시 (한국 표준시)
 * @param {object} opt  { 진태양시보정: true }  기본 true (-32분)
 */
function 사주(y, m, d, h = 12, min = 0, opt = {}) {
  // 진태양시 보정(-32분)은 **시주에만** 쓴다.
  //   절입은 천문 사건이고 그 순간은 경도로 달라지지 않는다. 천문연구원이
  //   내는 절입시각도 한국 표준시라, 표준시끼리 견주는 것이 맞다.
  //   여기에 -32분을 섞으면 경계에 선 사람의 월주가 통째로 어긋난다.
  const 보정 = opt.진태양시보정 === false ? 0 : -32;   // 동경 135도 표준시 → 한국 실제 경도
  // 표준시 이력 — 시계가 가리킨 시각(시민시)을 KST(UTC+9) 눈금으로 옮긴다. 절입 시각은 KST 눈금이므로
  //   1908~1911·1954~1961(UTC+8:30)과 서머타임 해(1948~51·1955~60·1987~88, +1시간)에 난 사람은
  //   이 보정이 없으면 월주·년주 경계와 대운 날수가 30~60분 어긋난다. 표는 manseryeok 와 같다. (2026-10-07)
  // 세계 만세력(2026-10-07): 출생지가 한국 밖이면 그 지역 시간대 이력으로 UTC 를 구해 KST 눈금에 놓는다 — 절입과는 UTC 순간끼리 견주는 셈이다.
  const 출생지 = opt.출생지 && opt.출생지.tz && opt.출생지.tz !== 'Asia/Seoul' ? opt.출생지 : null;
  const 야자시 = opt.야자시 === '자정' ? '자정' : '밤11시';
  let 오프셋근거 = '한국 표준시 이력';
  let 시민시오프셋 = 시민시오프셋분(y, m, d, h);
  if (출생지) {
    const off = 시간대오프셋분(출생지.tz, y, m, d, h, min);
    if (off == null) {
      시민시오프셋 = Math.round(((출생지.경도 ?? 135) / 15) * 60);
      오프셋근거 = '경도 근사(시간대 자료 없음)';
    } else { 시민시오프셋 = off; 오프셋근거 = `IANA 시간대 ${출생지.tz}`; }
  }
  const jd = toJD(y, m, d, h, min) - (시민시오프셋 - 540) / 1440;   // KST 눈금 — 년주·월주 경계용

  // ── 년주: 입춘 전이면 전년 ──
  const 절 = 그해절기(y);
  const 전해절 = 그해절기(y - 1);
  const 입춘 = 절.find(x => x.이름 === '입춘');
  const 년 = jd < 입춘.jd ? y - 1 : y;
  const yi = (년 - 4) % 60;
  const 년주 = 천간[yi % 10] + 지지[yi % 12];

  // ── 월주: 절기로 가른다 ──
  const 전체 = [...전해절, ...절, ...그해절기(y + 1)].sort((a, b) => a.jd - b.jd);
  let 직전 = null, 다음 = null;
  for (let i = 0; i < 전체.length; i++) {
    if (전체[i].jd <= jd) { 직전 = 전체[i]; 다음 = 전체[i + 1] ?? null; }
  }
  const 년간 = 천간[yi % 10];
  const 寅부터 = 지지.indexOf(직전.월지) - 2;
  const 월순번 = ((寅부터 % 12) + 12) % 12;
  const 월주 = 천간[(월두[년간] + 월순번) % 10] + 직전.월지;

  // ── 일주 ──
  let 일JD = Math.floor(toJD(y, m, d, 12, 0) + 0.5);
  // ── 시주: 야자시(23시 이후)는 다음 날 일간으로 보는 설이 있으나
  //    자평진전은 그 논의가 없다. 여기서는 일간 그대로 쓰고 경고만 낸다. (한국 자체 폴백)
  let 실시 = h + (min + 보정) / 60;
  let 보정표시 = `진태양시 ${보정}분`;
  let 진태양시정보 = null;
  if (출생지) {
    // 한국 밖: 일주·시주는 출생지 진태양시(UTC + 경도×4분 [+ 균시차])로. 경도가 없으면 그 시계 오프셋을 쓴다(경고).
    const jdUTC = jd - KST;
    const 진분 = 출생지.경도 != null ? 출생지.경도 * 4 : 시민시오프셋;
    const 균 = opt.균시차 ? 균시차분(jdUTC) : 0;
    const jd진 = jdUTC + (진분 + 균) / 1440;
    const t = fromJD(jd진);
    일JD = Math.floor(jd진 + 0.5);
    if (야자시 === '밤11시' && t.h >= 23) 일JD += 1;
    실시 = t.h + t.min / 60;
    진태양시정보 = { ...t, 진분: Math.round(진분), 균시차: +균.toFixed(1), 시계와차이: Math.round(진분 + 균 - 시민시오프셋) };
    보정표시 = `출생지 진태양시 (경도 ${출생지.경도 != null ? 출생지.경도 : '미상'} · 시계보다 ${진태양시정보.시계와차이 >= 0 ? '+' : ''}${진태양시정보.시계와차이}분${opt.균시차 ? ' · 균시차 포함' : ''} · ${야자시 === '밤11시' ? '밤 11시부터 다음 날' : '자정에 날짜 바뀜'})`;
  }
  const di = (일JD + 49) % 60;
  let 일주 = 천간[di % 10] + 지지[di % 12];
  const 시지idx = Math.floor(((실시 + 1) % 24) / 2);
  let 시주 = 천간[(시두[일주[0]] + 시지idx) % 10] + 지지[시지idx];

  // ── 절기 날수 (대운수용) ──
  const 지난날 = jd - 직전.jd;
  const 남은날 = 다음 ? 다음.jd - jd : null;

  // ── 경고 ──
  //   근사식은 최대 10분쯤 어긋난다. 그래서 경계를 두 단계로 나눈다.
  //   30분 안이면 우리 값으로는 가릴 수 없다고 분명히 말하고,
  //   하루 안이면 알아 두시라고만 한다. 한 단계로 두면 하루짜리 경고가
  //   3%에게 뜨는데, 늘 뜨는 경고는 아무도 안 읽는다.
  const 경고 = [];
  const 근사 = 직전.근거 !== '역서';
  const 가까움 = Math.min(지난날, 남은날 ?? Infinity);
  if (근사 && 가까움 < 30 / 1440) {
    경고.push(`절입(${가까움 === 지난날 ? 직전.이름 : 다음.이름})까지 ${(가까움 * 1440).toFixed(0)}분 — `
      + '우리 계산은 이 폭에서 어긋날 수 있어 월주를 확정하지 못한다. '
      + '천문연구원 역서의 절입시각으로 확인할 것');
  } else if (지난날 < 1) {
    경고.push(`절입(${직전.이름}) 직후 ${(지난날 * 24).toFixed(1)}시간 — 월주가 경계에 있다`);
  } else if (남은날 != null && 남은날 < 1) {
    경고.push(`다음 절입(${다음.이름})까지 ${(남은날 * 24).toFixed(1)}시간 — 월주가 경계에 있다`);
  }
  const 시경계 = Math.abs(((실시 + 1) % 2) - 1);
  if (시경계 > 0.83) 경고.push('시주가 경계에 가깝다 — 태어난 시각을 한 번 더 확인할 것');
  if (h >= 23 || h < 1) 경고.push('자시(子時)에 났다 — 야자시·조자시를 가르는 설이 있으나 자평진전에는 그 논의가 없다');
  if (출생지) {
    const 부호 = v => (v >= 0 ? '+' : '−') + String(Math.floor(Math.abs(v) / 60)).padStart(2, '0') + ':' + String(Math.abs(v) % 60).padStart(2, '0');
    const 일월초 = 시간대오프셋분(출생지.tz, y, 1, 1, 12, 0);
    const 서머 = 일월초 != null && 오프셋근거.startsWith('IANA') && 시민시오프셋 !== 일월초 && 시민시오프셋 > 일월초;
    경고.push(`출생지 ${출생지.이름 || 출생지.tz}: 시계는 UTC${부호(시민시오프셋)}${서머 ? '(서머타임 중)' : ''}(${오프셋근거}) — 년주·월주는 절입과 UTC 순간으로 견주었고, 일주·시주는 출생지 진태양시(시계보다 ${진태양시정보.시계와차이 >= 0 ? '+' : ''}${진태양시정보.시계와차이}분)로 세웠다. 출생 기록이 그 지역 시계 시각인지 확인할 것`);
    if (오프셋근거.startsWith('경도')) 경고.push('그 시간대 자료가 없어 경도로 시계 오프셋을 어림했다 — 서머타임·표준시 이력은 반영되지 않았다');
    if (출생지.경도 == null) 경고.push('출생지 경도가 없어 시주를 시계 시각 그대로 세웠다 — 진태양시 차이(최대 ±1시간)가 반영되지 않았다');
    if (진태양시정보.h >= 23 || 진태양시정보.h < 1) 경고.push(`진태양시로 자시(子時)에 났다 — ${야자시 === '밤11시' ? '밤 11시부터 다음 날로 보았다(시중 관행). 자정 기준으로 보면' : '자정 기준으로 보았다. 밤 11시부터 다음 날로 보면'} 일주가 갈릴 수 있다`);
  } else if (시민시오프셋 !== 540) 경고.push(`태어난 때의 한국 시계는 ${시민시오프셋 === 510 ? 'UTC+8:30 표준시' : 시민시오프셋 === 570 ? 'UTC+8:30 표준시에 서머타임' : '서머타임'}이었다 — 시계 시각을 ${시민시오프셋 - 540 > 0 ? '' : '+'}${540 - 시민시오프셋}분 옮겨 절기·시주를 계산했다. 출생 기록이 그 시계 시각인지 확인할 것`);

  // ── 2026-09-03 외부 만세력(manseryeok, KASI 절입표)으로 일주·시주를 갈아 끼운다 ──
  //   시중 만세력 관행: -30분·균시차 없음·표준시 이력(1954~61 UTC+8:30, 1955~60·1987~88 서머타임) 반영·
  //   자시는 밤 11시부터 다음 날(정자시, 원광·천을 관행 — 2026-09-04 조윤선 지적). 외부 엔진이 없으면 자체(-32분) 폴백.
  const MS = (typeof globalThis !== 'undefined' && globalThis.manseryeok) || null;
  if (MS && typeof MS.calculateFourPillars === 'function' && opt.진태양시보정 !== false) {
    try {
      const 한자 = k => {
        const g = {갑:'甲',을:'乙',병:'丙',정:'丁',무:'戊',기:'己',경:'庚',신:'辛',임:'壬',계:'癸'}[k[0]];
        const j = {자:'子',축:'丑',인:'寅',묘:'卯',진:'辰',사:'巳',오:'午',미:'未',신:'申',유:'酉',술:'戌',해:'亥'}[k[1]];
        return (g && j) ? g + j : null;
      };
      const 경계 = 야자시 === '자정' ? 'midnight' : 'jasi';
      let ext, 민;
      if (!출생지) {
        const 기준 = { longitude: 127.5, applyEquationOfTime: false, applyHistoricalDst: true };
        ext = MS.calculateFourPillars({ year: y, month: m, day: d, hour: h, minute: min, dayBoundary: 경계, trueSolarTime: 기준 });
        민 = MS.calculateFourPillars({ year: y, month: m, day: d, hour: h, minute: min, dayBoundary: 경계 });
      } else if (출생지.경도 != null) {
        // 같은 UTC 순간을 KST(UTC+9 고정) 시계로 옮겨 넣고 경도만 출생지로 — 라이브러리의 진태양시 = UTC + 경도×4분 이라 출생지 진태양시가 된다
        const k = fromJD(jd);
        ext = MS.calculateFourPillars({ year: k.y, month: k.m, day: k.d, hour: k.h, minute: k.min, dayBoundary: 경계,
          trueSolarTime: { longitude: 출생지.경도, applyEquationOfTime: !!opt.균시차, applyHistoricalDst: false } });
        민 = null;
      }
      const o = ext ? ext.toObject() : null;
      const 일주2 = o ? 한자(o.day) : null, 시주2 = o && o.hour ? 한자(o.hour) : null;
      if (일주2 && 시주2 && !출생지) {
        일주 = 일주2; 시주 = 시주2;
        보정표시 = `진태양시 -30분 (시중 관행 · ${야자시 === '밤11시' ? '밤 11시부터 다음 날' : '자정에 날짜 바뀜'} · 표준시 이력·서머타임 반영)`;
        for (let i = 경고.length - 1; i >= 0; i--) if (경고[i].startsWith('자시(子時)에 났다')) 경고.splice(i, 1);
        if (h >= 23 || h < 1) 경고.push(야자시 === '밤11시' ? '자시(子時)에 났다 — 시중 만세력(원광·천을)과 같이 밤 11시부터 다음 날로 보았다. 자정 기준으로 보는 설도 있어 일주가 갈릴 수 있다' : '자시(子時)에 났다 — 설정대로 자정에 날짜가 바뀌는 것으로 보았다. 시중 만세력(밤 11시부터 다음 날)과 일주가 갈릴 수 있다');
        for (let i = 경고.length - 1; i >= 0; i--) if (경고[i].startsWith('시주가 경계에 가깝다')) 경고.splice(i, 1);
      } else if (일주2 && 시주2 && 출생지) {
        // 한국 밖: 자체 진태양시 계산과 라이브러리가 다르면(균시차 근사 차이 등) 라이브러리를 따르고 알린다
        if (일주2 !== 일주 || 시주2 !== 시주) { 경고.push(`출생지 진태양시 계산이 경계에 있다 — 자체 ${일주}·${시주}, 만세력 라이브러리 ${일주2}·${시주2}. 라이브러리 값을 썼다`); 일주 = 일주2; 시주 = 시주2; }
      }
      if (민) {
        const 민시 = 민.toObject().hour ? 한자(민.toObject().hour) : null;
        if (민시 && 시주2 && 민시 !== 시주2)
          경고.push(`시주가 경계에 있다 — 진태양시 보정(-30분)을 하면 ${시주2}, 하지 않으면 ${민시}. 태어난 시각과 출생지를 한 번 더 확인할 것`);
      }
    } catch (e) { /* 외부 엔진이 실패하면 자체 계산 그대로 */ }
  }

  // ── 대운에 쓸 날수 ──
  //   순행이면 다음 절입까지, 역행이면 지난 절입 이후다. 둘은 다른 값이고
  //   지난날을 순행인 사람에게 쓰면 대운 나이가 통째로 어긋난다.
  //   성별을 주면 여기서 바로 갈라 준다. 안 주면 null이니 호출부가 정해야 한다.
  let 대운날수 = null, 순행 = null;
  if (opt.성별 === '남' || opt.성별 === '여') {
    const 양간 = '甲丙戊庚壬'.includes(년주[0]);
    순행 = (양간 && opt.성별 === '남') || (!양간 && opt.성별 === '여');
    대운날수 = 순행 ? 남은날 : 지난날;
  }

  return {
    명식: {
      yeonGan: 년주[0], yeonJi: 년주[1],
      wolGan: 월주[0], wolJi: 월주[1],
      ilGan: 일주[0], ilJi: 일주[1],
      siGan: 시주[0], siJi: 시주[1],
      daysFromJeolip: Math.round(지난날),   // 조후 심천용 — 늘 '지난 절입 이후'
    },
    대운: 대운날수 == null ? null : {
      순행, 방향: 순행 ? '순행' : '역행',
      날수: +대운날수.toFixed(2),
      대운수: Math.max(1, Math.round(대운날수 / 3)),
    },
    사주: `${년주} ${월주} ${일주} ${시주}`,
    절기: { 직전: 직전.이름, 다음: 다음?.이름 ?? null,
            지난날: +지난날.toFixed(2), 남은날: 남은날 != null ? +남은날.toFixed(2) : null },
    보정: 보정표시,
    경고,
    // 세계 만세력(2026-10-07): 시계·UTC·KST·진태양시 — 화면 표시와 반월(중기) 계산용
    시각: {
      시계: { y, m, d, h, min }, 오프셋분: 시민시오프셋, 근거: 오프셋근거,
      KST: fromJD(jd), UTC: fromJD(jd - KST),
      진태양시: 진태양시정보 ? { y: 진태양시정보.y, m: 진태양시정보.m, d: 진태양시정보.d, h: 진태양시정보.h, min: 진태양시정보.min, 시계와차이: 진태양시정보.시계와차이, 균시차: 진태양시정보.균시차 } : null,
      야자시, 균시차: !!opt.균시차,
      출생지: 출생지 ? { tz: 출생지.tz, 경도: 출생지.경도 ?? null, 이름: 출생지.이름 || null } : { tz: 'Asia/Seoul', 경도: 127.5, 이름: '한국' },
    },
  };
}

/** 대운수 — 순행이면 다음 절입까지, 역행이면 지난 절입 이후, ÷3 */
function 대운수(결과, 성별) {
  const { GAN } = require('./jijanggan');
  const 년간음양 = GAN[결과.명식.yeonGan].eumyang;
  const 순행 = (년간음양 === '양' && 성별 === '남') || (년간음양 === '음' && 성별 === '여');
  const 날 = 순행 ? 결과.절기.남은날 : 결과.절기.지난날;
  return { 순행, 방향: 순행 ? '순행' : '역행', 날수: 날, 대운수: Math.max(1, Math.round(날 / 3)) };
}

