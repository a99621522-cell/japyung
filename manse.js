/**
 * manse.js — 만세력: 생년월일시 → 사주 여덟 글자 + 절기 날수
 *
 * 이 모듈이 하는 일은 셋이다.
 *   ① 년월일시를 간지로 옮긴다
 *   ② 절기를 계산해 **월주**를 정한다 (달력의 월이 아니라 절기가 월을 가른다)
 *   ③ 대운수에 쓸 **절기까지 날수**를 낸다
 *
 * ※ 절기는 태양황경으로 정해진다. 정밀한 천문 계산 없이도
 *   1900~2100 구간에서는 근사식으로 분 단위까지 충분히 맞는다.
 *   여기서는 그 근사식을 쓰되, 경계에 가까우면 **경고를 함께 낸다**.
 *   30편: 「사람의 시주는 확실치 않은 경우가 많다」 — 경계는 밝히고 넘어간다.
 */

const 천간 = '甲乙丙丁戊己庚辛壬癸'.split('');
const 지지 = '子丑寅卯辰巳午未申酉戌亥'.split('');

// ─────────────────────────────────────────────
// 율리우스일
// ─────────────────────────────────────────────
function toJD(y, m, d, h = 0, min = 0) {
  let Y = y, M = m;
  if (M <= 2) { Y -= 1; M += 12; }
  const A = Math.floor(Y / 100), B = 2 - A + Math.floor(A / 4);
  return Math.floor(365.25 * (Y + 4716)) + Math.floor(30.6001 * (M + 1))
       + d + B - 1524.5 + (h + min / 60) / 24;
}

// ─────────────────────────────────────────────
// 절기 — 태양황경이 15°의 배수가 되는 순간
//   입춘(315°)부터 12절(節)만 쓴다. 중기(中氣)는 월주와 무관하다.
// ─────────────────────────────────────────────
const 절기 = [
  { 이름:'입춘', 황경:315, 월지:'寅' }, { 이름:'경칩', 황경:345, 월지:'卯' },
  { 이름:'청명', 황경:15,  월지:'辰' }, { 이름:'입하', 황경:45,  월지:'巳' },
  { 이름:'망종', 황경:75,  월지:'午' }, { 이름:'소서', 황경:105, 월지:'未' },
  { 이름:'입추', 황경:135, 월지:'申' }, { 이름:'백로', 황경:165, 월지:'酉' },
  { 이름:'한로', 황경:195, 월지:'戌' }, { 이름:'입동', 황경:225, 월지:'亥' },
  { 이름:'대설', 황경:255, 월지:'子' }, { 이름:'소한', 황경:285, 월지:'丑' },
];

const rad = Math.PI / 180;

// ─────────────────────────────────────────────
// 시간대 — 이 모듈 안에서 오가는 JD는 전부 **한국시(KST) 눈금**이다.
//   태양황경 계산은 세계시(UT) 기준 JD를 받으므로, 절입 시각을 낸 뒤
//   KST로 옮겨서 내보낸다. 생시로 만든 JD는 애초에 KST 눈금이므로
//   두 값을 곧바로 견줄 수 있다.
//   ※ 이 보정이 없으면 절입 경계가 아홉 시간 앞당겨진다.
// ─────────────────────────────────────────────
const KST = 9 / 24;

/** 태양황경 (도) — JD(TT 근사)에서 */
function 태양황경(jd) {
  const T = (jd - 2451545.0) / 36525;
  const L0 = 280.46646 + 36000.76983 * T + 0.0003032 * T * T;
  const M  = 357.52911 + 35999.05029 * T - 0.0001537 * T * T;
  const C  = (1.914602 - 0.004817 * T - 0.000014 * T * T) * Math.sin(M * rad)
           + (0.019993 - 0.000101 * T) * Math.sin(2 * M * rad)
           + 0.000289 * Math.sin(3 * M * rad);
  let L = L0 + C;
  // 행성 섭동 (Meeus) — 넣으면 평균 오차가 5.4분에서 4.3분으로 준다.
  // 이것으로도 분 단위까지는 못 간다. 정밀한 값은 절입표를 쓸 것(아래 절입표주입 참조)
  const A1 = 153.23 + 22518.7541 * T, B1 = 216.57 + 45037.5082 * T;
  const C1 = 312.69 + 32964.3577 * T, D1 = 350.74 + 445267.1142 * T - 0.00144 * T * T;
  const E1 = 231.19 + 20.20 * T;
  L += 0.00134 * Math.cos(A1 * rad) + 0.00154 * Math.cos(B1 * rad)
     + 0.00200 * Math.cos(C1 * rad) + 0.00179 * Math.sin(D1 * rad)
     + 0.00178 * Math.sin(E1 * rad);
  // 광행차·장동 보정 (근사)
  const Om = 125.04 - 1934.136 * T;
  L = L - 0.00569 - 0.00478 * Math.sin(Om * rad);
  return ((L % 360) + 360) % 360;
}

/** 지정한 황경에 도달하는 JD를 이분법으로 찾는다 */
function 절입시각(황경, 기준JD) {
  // 기준일 앞뒤 30일에서 찾는다
  let lo = 기준JD - 20, hi = 기준JD + 20;
  const diff = jd => {
    let d = 태양황경(jd) - 황경;
    while (d > 180) d -= 360;
    while (d < -180) d += 360;
    return d;
  };
  if (diff(lo) > 0) lo -= 30;
  for (let i = 0; i < 60; i++) {
    const mid = (lo + hi) / 2;
    if (diff(mid) < 0) lo = mid; else hi = mid;
  }
  return (lo + hi) / 2;
}

/**
 * 그 해의 12절 절입 시각을 다 낸다 (한국시 기준 JD)
 * @returns [{이름, 월지, jd}]
 */
// ─────────────────────────────────────────────
// 절입표 주입
//   근사식은 평균 4분, 최대 9분쯤 어긋난다. 경계에 선 사람에게는 그것이
//   월주 하나를 통째로 바꾼다. 천문연구원 역서 값을 표로 넣어 두면
//   그 표를 먼저 쓰고, 없는 해만 근사식으로 넘어간다.
//
//   표 모양: { 2026: { 입춘:'2026-02-04T05:02+09:00', 경칩:'…', … }, … }
// ─────────────────────────────────────────────
let 절입표 = null;
function 절입표주입(t) { 절입표 = t; }
function 표에서(year, 이름) {
  const v = 절입표?.[year]?.[이름];
  if (!v) return null;
  const d = new Date(v);
  if (isNaN(d)) return null;
  // Date → KST 눈금 JD
  const u = d.getTime() / 86400000 + 2440587.5;
  return u + KST;
}

function 그해절기(year) {
  const out = [];
  for (const s of 절기) {
    // 대략적인 달을 잡아 기준으로 준다
    const 대략월 = ({ 315:2, 345:3, 15:4, 45:5, 75:6, 105:7, 135:8, 165:9, 195:10, 225:11, 255:12, 285:1 })[s.황경];
    const y2 = s.황경 === 285 ? year + 1 : year;   // 소한은 다음 해 1월
    const 표값 = 표에서(y2, s.이름);
    if (표값 != null) { out.push({ ...s, jd: 표값, 근거: '역서' }); continue; }
    const 기준 = toJD(y2, 대략월, 5);
    out.push({ ...s, jd: 절입시각(s.황경, 기준) + KST, 근거: '근사식' });   // UT → KST 눈금
  }
  return out.sort((a, b) => a.jd - b.jd);
}

// ─────────────────────────────────────────────
// 사주 세우기
// ─────────────────────────────────────────────
const 월두 = { 甲:2, 己:2, 乙:4, 庚:4, 丙:6, 辛:6, 丁:8, 壬:8, 戊:0, 癸:0 };
const 시두 = { 甲:0, 己:0, 乙:2, 庚:2, 丙:4, 辛:4, 丁:6, 壬:6, 戊:8, 癸:8 };

/**
 * @param {number} y,m,d,h,min  양력 생년월일시 (한국 표준시)
 * @param {object} opt  { 진태양시보정: true }  기본 true (-32분)
 */
function 사주(y, m, d, h = 12, min = 0, opt = {}) {
  // 진태양시 보정(-32분)은 **시주에만** 쓴다.
  //   절입은 천문 사건이고 그 순간은 경도로 달라지지 않는다. 천문연구원이
  //   내는 절입시각도 한국 표준시라, 표준시끼리 견주는 것이 맞다.
  //   여기에 -32분을 섞으면 경계에 선 사람의 월주가 통째로 어긋난다.
  const 보정 = opt.진태양시보정 === false ? 0 : -32;   // 동경 135도 표준시 → 한국 실제 경도
  const jd = toJD(y, m, d, h, min);                    // 표준시 — 년주·월주 경계용

  // ── 년주: 입춘 전이면 전년 ──
  const 절 = 그해절기(y);
  const 전해절 = 그해절기(y - 1);
  const 입춘 = 절.find(x => x.이름 === '입춘');
  const 년 = jd < 입춘.jd ? y - 1 : y;
  const yi = (년 - 4) % 60;
  const 년주 = 천간[yi % 10] + 지지[yi % 12];

  // ── 월주: 절기로 가른다 ──
  const 전체 = [...전해절, ...절, ...그해절기(y + 1)].sort((a, b) => a.jd - b.jd);
  let 직전 = null, 다음 = null;
  for (let i = 0; i < 전체.length; i++) {
    if (전체[i].jd <= jd) { 직전 = 전체[i]; 다음 = 전체[i + 1] ?? null; }
  }
  const 년간 = 천간[yi % 10];
  const 寅부터 = 지지.indexOf(직전.월지) - 2;
  const 월순번 = ((寅부터 % 12) + 12) % 12;
  const 월주 = 천간[(월두[년간] + 월순번) % 10] + 직전.월지;

  // ── 일주 ──
  const 일JD = Math.floor(toJD(y, m, d, 12, 0) + 0.5);
  const di = (일JD + 49) % 60;
  const 일주 = 천간[di % 10] + 지지[di % 12];

  // ── 시주: 야자시(23시 이후)는 다음 날 일간으로 보는 설이 있으나
  //    자평진전은 그 논의가 없다. 여기서는 일간 그대로 쓰고 경고만 낸다.
  const 실시 = h + (min + 보정) / 60;
  const 시지idx = Math.floor(((실시 + 1) % 24) / 2);
  const 시주 = 천간[(시두[일주[0]] + 시지idx) % 10] + 지지[시지idx];

  // ── 절기 날수 (대운수용) ──
  const 지난날 = jd - 직전.jd;
  const 남은날 = 다음 ? 다음.jd - jd : null;

  // ── 경고 ──
  //   근사식은 최대 10분쯤 어긋난다. 그래서 경계를 두 단계로 나눈다.
  //   30분 안이면 우리 값으로는 가릴 수 없다고 분명히 말하고,
  //   하루 안이면 알아 두시라고만 한다. 한 단계로 두면 하루짜리 경고가
  //   3%에게 뜨는데, 늘 뜨는 경고는 아무도 안 읽는다.
  const 경고 = [];
  const 근사 = 직전.근거 !== '역서';
  const 가까움 = Math.min(지난날, 남은날 ?? Infinity);
  if (근사 && 가까움 < 30 / 1440) {
    경고.push(`절입(${가까움 === 지난날 ? 직전.이름 : 다음.이름})까지 ${(가까움 * 1440).toFixed(0)}분 — `
      + '우리 계산은 이 폭에서 어긋날 수 있어 월주를 확정하지 못한다. '
      + '천문연구원 역서의 절입시각으로 확인할 것');
  } else if (지난날 < 1) {
    경고.push(`절입(${직전.이름}) 직후 ${(지난날 * 24).toFixed(1)}시간 — 월주가 경계에 있다`);
  } else if (남은날 != null && 남은날 < 1) {
    경고.push(`다음 절입(${다음.이름})까지 ${(남은날 * 24).toFixed(1)}시간 — 월주가 경계에 있다`);
  }
  const 시경계 = Math.abs(((실시 + 1) % 2) - 1);
  if (시경계 > 0.83) 경고.push('시주가 경계에 가깝다 — 태어난 시각을 한 번 더 확인할 것');
  if (h >= 23 || h < 1) 경고.push('자시(子時)에 났다 — 야자시·조자시를 가르는 설이 있으나 자평진전에는 그 논의가 없다');

  // ── 대운에 쓸 날수 ──
  //   순행이면 다음 절입까지, 역행이면 지난 절입 이후다. 둘은 다른 값이고
  //   지난날을 순행인 사람에게 쓰면 대운 나이가 통째로 어긋난다.
  //   성별을 주면 여기서 바로 갈라 준다. 안 주면 null이니 호출부가 정해야 한다.
  let 대운날수 = null, 순행 = null;
  if (opt.성별 === '남' || opt.성별 === '여') {
    const 양간 = '甲丙戊庚壬'.includes(년주[0]);
    순행 = (양간 && opt.성별 === '남') || (!양간 && opt.성별 === '여');
    대운날수 = 순행 ? 남은날 : 지난날;
  }

  return {
    명식: {
      yeonGan: 년주[0], yeonJi: 년주[1],
      wolGan: 월주[0], wolJi: 월주[1],
      ilGan: 일주[0], ilJi: 일주[1],
      siGan: 시주[0], siJi: 시주[1],
      daysFromJeolip: Math.round(지난날),   // 조후 심천용 — 늘 '지난 절입 이후'
    },
    대운: 대운날수 == null ? null : {
      순행, 방향: 순행 ? '순행' : '역행',
      날수: +대운날수.toFixed(2),
      대운수: Math.max(1, Math.round(대운날수 / 3)),
    },
    사주: `${년주} ${월주} ${일주} ${시주}`,
    절기: { 직전: 직전.이름, 다음: 다음?.이름 ?? null,
            지난날: +지난날.toFixed(2), 남은날: 남은날 != null ? +남은날.toFixed(2) : null },
    보정: `진태양시 ${보정}분`,
    경고,
  };
}

/** 대운수 — 순행이면 다음 절입까지, 역행이면 지난 절입 이후, ÷3 */
function 대운수(결과, 성별) {
  const { GAN } = require('./jijanggan');
  const 년간음양 = GAN[결과.명식.yeonGan].eumyang;
  const 순행 = (년간음양 === '양' && 성별 === '남') || (년간음양 === '음' && 성별 === '여');
  const 날 = 순행 ? 결과.절기.남은날 : 결과.절기.지난날;
  return { 순행, 방향: 순행 ? '순행' : '역행', 날수: 날, 대운수: Math.max(1, Math.round(날 / 3)) };
}

