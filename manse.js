const rad = Math.PI / 180;

// ─────────────────────────────────────────────
// 시간대 — 이 모듈 안에서 오가는 JD는 전부 **한국시(KST) 눈금**이다.
//   태양황경 계산은 세계시(UT) 기준 JD를 받으므로, 절입 시각을 낸 뒤
//   KST로 옮겨서 내보낸다. 생시로 만든 JD는 애초에 KST 눈금이므로
//   두 값을 곧바로 견줄 수 있다.
//   ※ 이 보정이 없으면 절입 경계가 아홉 시간 앞당겨진다.
// ─────────────────────────────────────────────
const KST = 9 / 24;

/** 태양황경 (도) — JD(TT 근사)에서 */
function 태양황경(jd) {
  const T = (jd - 2451545.0) / 36525;
  const L0 = 280.46646 + 36000.76983 * T + 0.0003032 * T * T;
  const M  = 357.52911 + 35999.05029 * T - 0.0001537 * T * T;
  const C  = (1.914602 - 0.004817 * T - 0.000014 * T * T) * Math.sin(M * rad)
           + (0.019993 - 0.000101 * T) * Math.sin(2 * M * rad)
           + 0.000289 * Math.sin(3 * M * rad);
  let L = L0 + C;
  // 행성 섭동 (Meeus) — 넣으면 평균 오차가 5.4분에서 4.3분으로 준다.
  // 이것으로도 분 단위까지는 못 간다. 정밀한 값은 절입표를 쓸 것(아래 절입표주입 참조)
  const A1 = 153.23 + 22518.7541 * T, B1 = 216.57 + 45037.5082 * T;
  const C1 = 312.69 + 32964.3577 * T, D1 = 350.74 + 445267.1142 * T - 0.00144 * T * T;
  const E1 = 231.19 + 20.20 * T;
  L += 0.00134 * Math.cos(A1 * rad) + 0.00154 * Math.cos(B1 * rad)
     + 0.00200 * Math.cos(C1 * rad) + 0.00179 * Math.sin(D1 * rad)
     + 0.00178 * Math.sin(E1 * rad);
  // 광행차·장동 보정 (근사)
  const Om = 125.04 - 1934.136 * T;
  L = L - 0.00569 - 0.00478 * Math.sin(Om * rad);
  return ((L % 360) + 360) % 360;
}

/** 지정한 황경에 도달하는 JD를 이분법으로 찾는다 */
function 절입시각(황경, 기준JD) {
  // 기준일 앞뒤 30일에서 찾는다
  let lo = 기준JD - 20, hi = 기준JD + 20;
  const diff = jd => {
    let d = 태양황경(jd) - 황경;
    while (d > 180) d -= 360;
    while (d < -180) d += 360;
    return d;
  };
  if (diff(lo) > 0) lo -= 30;
  for (let i = 0; i < 60; i++) {
    const mid = (lo + hi) / 2;
    if (diff(mid) < 0) lo = mid; else hi = mid;
  }
  return (lo + hi) / 2;
}

/**
 * 그 해의 12절 절입 시각을 다 낸다 (한국시 기준 JD)
 * @returns [{이름, 월지, jd}]
 */
// ─────────────────────────────────────────────
// 절입표 주입
//   근사식은 평균 4분, 최대 9분쯤 어긋난다. 경계에 선 사람에게는 그것이
//   월주 하나를 통째로 바꾼다. 천문연구원 역서 값을 표로 넣어 두면
//   그 표를 먼저 쓰고, 없는 해만 근사식으로 넘어간다.
//
//   표 모양: { 2026: { 입춘:'2026-02-04T05:02+09:00', 경칩:'…', … }, … }
// ─────────────────────────────────────────────
let 절입표 = null;
function 절입표주입(t) { 절입표 = t; }
function 표에서(year, 이름) {
  let v = 절입표?.[year]?.[이름];
  // 주입된 표가 없으면 화면에 함께 실린 외부 만세력(manseryeok, KASI 절입표 1800~2300)을 쓴다.
  //   근사식은 1900~2050년 12절 1,661건 중 38%가 5분 이상, 110건이 10~15분 어긋났다(2026-10-07 대조) —
  //   경계에 선 사람의 월주·대운수를 통째로 바꾸는 폭이라, 표가 있는데 안 쓸 이유가 없다.
  if (!v) {
    const MS = (typeof globalThis !== 'undefined' && globalThis.manseryeok) || null;
    if (MS && typeof MS.getSolarTermsOfYear === 'function') {
      try {
        const t = MS.getSolarTermsOfYear(year).find(x => x.name === 이름);
        v = t?.date ?? null;
      } catch (e) { v = null; }
    }
  }
  if (!v) return null;
  const d = new Date(v);
  if (isNaN(d)) return null;
  // Date → KST 눈금 JD
  const u = d.getTime() / 86400000 + 2440587.5;
  return u + KST;
}

function 그해절기(year) {
  const out = [];
  for (const s of 절기) {
    // 대략적인 달을 잡아 기준으로 준다
    const 대략월 = ({ 315:2, 345:3, 15:4, 45:5, 75:6, 105:7, 135:8, 165:9, 195:10, 225:11, 255:12, 285:1 })[s.황경];
    const y2 = s.황경 === 285 ? year + 1 : year;   // 소한은 다음 해 1월
    const 표값 = 표에서(y2, s.이름);
    if (표값 != null) { out.push({ ...s, jd: 표값, 근거: '역서' }); continue; }
    const 기준 = toJD(y2, 대략월, 5);
    out.push({ ...s, jd: 절입시각(s.황경, 기준) + KST, 근거: '근사식' });   // UT → KST 눈금
  }
  return out.sort((a, b) => a.jd - b.jd);
}

// ─────────────────────────────────────────────
// 표준시 이력 — 한국 시민시가 UTC 보다 몇 분 앞섰나 (기본 540 = UTC+9)
//   표준시: 1908-04-01 UTC+8:30 → 1912-01-01 UTC+9 → 1954-03-21 UTC+8:30 → 1961-08-10 UTC+9
//   서머타임(+60): 1948-06-01~09-13 · 1949-04-03~09-11 · 1950-04-01~09-10 · 1951-05-06~09-09 ·
//     1955-05-05~09-09 · 1956-05-20~09-30 · 1957-05-05~09-22 · 1958-05-04~09-21 · 1959-05-03~09-20 ·
//     1960-05-01~09-18 · 1987-05-10 02시~10-11 03시 · 1988-05-08 02시~10-09 03시
// ─────────────────────────────────────────────
const 표준시표 = [[19080401, 510], [19120101, 540], [19540321, 510], [19610810, 540]];
const 서머타임표 = [
  [1948060100, 1948091324], [1949040300, 1949091124], [1950040100, 1950091024], [1951050600, 1951090924],
  [1955050500, 1955090924], [1956052000, 1956093024], [1957050500, 1957092224], [1958050400, 1958092124],
  [1959050300, 1959092024], [1960050100, 1960091824], [1987051002, 1987101103], [1988050802, 1988100903],
];
function 시민시오프셋분(y, m, d, h = 0) {
  const ymd = y * 10000 + m * 100 + d;
  let off = 540;
  for (const [from, v] of 표준시표) if (ymd >= from) off = v;
  const ymdh = ymd * 100 + Math.floor(h);
  for (const [a, b] of 서머타임표) if (ymdh >= a && ymdh < b) { off += 60; break; }
  return off;
}

// ─────────────────────────────────────────────
// 세계 만세력 (2026-10-07, docs/PROMPTS.md 4)
//   출생지 {tz, 경도, 이름} 을 받으면 ① 그 지역 표준시·서머타임 이력(IANA tz, 브라우저·Node 의 Intl)으로 시계 시각을 UTC 로 옮기고
//   ② 년주·월주 경계(절입)는 UTC 순간끼리 견주며(KST 눈금 JD 로 통일) ③ 일주·시주는 출생지 경도의 진태양시(UTC + 경도×4분, 균시차는 설정)로 세운다.
//   한국(Asia/Seoul)은 전부터 쓰던 표(시민시오프셋분)를 그대로 쓴다 — manseryeok 과 1945~1989 무작위 4,000건 불일치 0 으로 검증된 길이라 바꾸지 않는다.
//   야자시: '밤11시'(기본, 시중 관행 — 밤 11시부터 다음 날) | '자정'(날짜는 자정에 바뀌고 23~24시는 그날의 子시).
// ─────────────────────────────────────────────
/** JD → 양력 {y,m,d,h,min} (Meeus) — JD 눈금은 호출부가 정한다(UTC 눈금이면 UTC 시각) */
function fromJD(jd) {
  const Z = Math.floor(jd + 0.5), F = jd + 0.5 - Z;
  let A = Z;
  if (Z >= 2299161) { const a = Math.floor((Z - 1867216.25) / 36524.25); A = Z + 1 + a - Math.floor(a / 4); }
  const B = A + 1524, C = Math.floor((B - 122.1) / 365.25), D = Math.floor(365.25 * C), E = Math.floor((B - D) / 30.6001);
  const d = B - D - Math.floor(30.6001 * E);
  const m = E < 14 ? E - 1 : E - 13;
  const y = m > 2 ? C - 4716 : C - 4715;
  let 분 = Math.round(F * 1440);
  if (분 >= 1440) 분 = 1439;   // 자정 직전 반올림 — 날짜는 Z 가 이미 정했다
  return { y, m, d, h: Math.floor(분 / 60), min: 분 % 60 };
}

/** 균시차(분) — 진태양시 = 평균태양시 + 균시차. 연중 −14~+16분. 근사식(±1분) */
function 균시차분(jdUTC) {
  const { y } = fromJD(jdUTC);
  const N = jdUTC - toJD(y, 1, 1, 0, 0) + 1;   // 그 해 몇째 날(소수)
  const B = 2 * Math.PI * (N - 81) / 365;
  return 9.87 * Math.sin(2 * B) - 7.53 * Math.cos(B) - 1.5 * Math.sin(B);
}

/**
 * 시간대 오프셋(분) — 그 지역 시계가 UTC 보다 몇 분 앞서나. 표준시·서머타임 이력은 IANA tz 자료(Intl)로.
 *   한국은 자체 표. Intl 이 그 tz 를 모르면 null.
 */
function 시간대오프셋분(tz, y, m, d, h = 0, min = 0) {
  if (!tz || tz === 'Asia/Seoul') return 시민시오프셋분(y, m, d, h);
  let fmt;
  try {
    fmt = new Intl.DateTimeFormat('en-US', { timeZone: tz, hourCycle: 'h23', year: 'numeric', month: '2-digit', day: '2-digit', hour: '2-digit', minute: '2-digit', second: '2-digit' });
  } catch (e) { return null; }
  const 읽기 = ms => {
    const p = {}; for (const x of fmt.formatToParts(new Date(ms))) p[x.type] = x.value;
    return Date.UTC(+p.year, +p.month - 1, +p.day, (+p.hour) % 24, +p.minute, +p.second);
  };
  const 벽 = Date.UTC(y, m - 1, d, h, min, 0);
  let off = (읽기(벽) - 벽) / 60000;                       // 1차: 시계 시각을 UTC 로 보고 그 순간의 오프셋
  off = (읽기(벽 - off * 60000) - (벽 - off * 60000)) / 60000;   // 2차: 되돌린 순간으로 다시(서머타임 경계 보정)
  return Math.round(off);
}

