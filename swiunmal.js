function 용어단락나누기(본문) {
  const 글 = String(본문 || '');
  const i = 글.indexOf(머리.용어);
  if (i < 0) return { 본: 글, 용어: '' };
  return { 본: 글.slice(0, i), 용어: 글.slice(i) };
}

function 문장들(글) {
  return String(글)
    .replace(/^▶.*$/gm, '')
    .split(/(?<=[.!?。])\s+|\n+/)
    .map(s => s.replace(/\*\*/g, '').trim())
    .filter(s => s.length >= 6 && !/^[-•]\s/.test(s));
}

/**
 * @param {string} 본문
 * @param {string} 모드 상담 | 궁통 | 문답 | 설명
 * @returns {{오류:Array, 경고:Array, 통계:object}}
 */
function 검사(본문, 모드 = '상담') {
  const 오류 = [], 경고 = [];
  const 글 = String(본문 || '');
  const { 본, 용어 } = 용어단락나누기(글);

  // ① 첫머리 「한 줄로 말하면」
  const 첫줄있음 = 글.trimStart().startsWith(머리.한줄) || 글.slice(0, 60).includes('한 줄로 말하면');
  if (!첫줄있음) {
    const 항목 = { 규칙: '한 줄 답', 내용: `첫머리에 「${머리.한줄}」이 없음 — 결론을 전문어 없이 두 문장으로 먼저` };
    (모드 === '상담' || 모드 === '궁통') ? 오류.push(항목) : 경고.push(항목);
  } else {
    // 한 줄 답 단락에 전문어·한자가 섞였는가
    const 다음 = 글.indexOf('▶', 글.indexOf(머리.한줄) + 2);
    const 한줄단락 = 글.slice(글.indexOf(머리.한줄) + 머리.한줄.length, 다음 > 0 ? 다음 : undefined);
    const 섞인 = 전문어.filter(w => 한줄단락.includes(w));
    const 한자 = (한줄단락.match(/[一-鿿]/g) || []).length;
    if (섞인.length || 한자) 경고.push({ 규칙: '한 줄 답 말 높이', 내용: `한 줄 답에 ${[...섞인, 한자 ? `한자 ${한자}자` : ''].filter(Boolean).join('·')} — 이 단락은 전문어·한자 없이` });
  }

  // ② 머리말 차례 (상담·궁통)
  if (모드 === '상담' || 모드 === '궁통') {
    const 빠짐 = [머리.풀이, 머리.근거, 머리.노력, 머리.용어].filter(h => !글.includes(h));
    if (빠짐.length >= 2) 오류.push({ 규칙: '답의 모양', 내용: `머리말이 빠짐: ${빠짐.join(', ')} — 다섯 머리말을 차례로` });
    else if (빠짐.length) 경고.push({ 규칙: '답의 모양', 내용: `머리말이 빠짐: ${빠짐.join(', ')}` });
  }

  // ③ 쓴 전문어가 용어 풀이에 있는가
  const 쓴말 = 전문어.filter(w => 본.includes(w));
  const 안풀린 = 쓴말.filter(w => !용어.includes(w));
  const 용어필요 = 모드 === '상담' || 모드 === '궁통' || 모드 === '설명' || 쓴말.length >= 2;
  if (용어필요 && 쓴말.length && !용어) {
    const 항목 = { 규칙: '용어 풀이', 내용: `전문어 ${쓴말.length}개(${쓴말.slice(0, 5).join('·')}…)를 썼는데 「${머리.용어}」가 없음` };
    (모드 === '상담' || 모드 === '궁통') ? 오류.push(항목) : 경고.push(항목);
  } else if (용어 && 안풀린.length >= 2) {
    경고.push({ 규칙: '용어 풀이', 내용: `본문에 쓰고 풀이에 없는 말: ${안풀린.slice(0, 6).join('·')}` });
  }

  // ④ 문장 길이·한 문장 전문어 밀도
  const 문 = 문장들(본);
  const 길이 = 문.map(s => s.replace(/\s/g, '').length);
  const 평균 = 길이.length ? Math.round(길이.reduce((a, b) => a + b, 0) / 길이.length) : 0;
  const 긴문장 = 길이.filter(n => n > 75).length;
  if (평균 > 48) 경고.push({ 규칙: '문장 길이', 내용: `문장 평균 ${평균}자 — 40자 안팎으로 끊을 것` });
  if (긴문장 >= 4) 경고.push({ 규칙: '긴 문장', 내용: `75자 넘는 문장 ${긴문장}개` });
  const 빽빽 = 문.filter(s => 전문어.filter(w => s.includes(w)).length + (s.match(/[甲乙丙丁戊己庚辛壬癸][子丑寅卯辰巳午未申酉戌亥]?/g) || []).length >= 4);
  if (빽빽.length >= 2) 경고.push({ 규칙: '빽빽한 문장', 내용: `한 문장에 전문어·간지가 넷 이상: 「${빽빽[0].slice(0, 36)}…」 등 ${빽빽.length}곳 — 나눠 쓸 것` });

  return { 오류, 경고, 통계: { 평균문장: 평균, 긴문장, 쓴전문어: 쓴말.length, 풀이없음: 안풀린.length } };
}

