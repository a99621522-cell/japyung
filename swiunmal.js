const 설명신호 = /무슨\s*(말|뜻|의미)|뭐(야|예요|죠|냐|니)|뭔\s*(뜻|말|소리)|이해가?\s*(안|잘)|모르겠|쉽게|풀어|왜\s*그(런|렇)|근거|조문|원문|출처|어디서\s*나(온|와)|설명해|알려\s*줘|이란|란\s*무엇|이게\s*뭐|그게\s*뭐|무엇인가|어떤\s*뜻/;
function 설명요청인가(질문) {
  const 원 = String(질문 || '').replace(/^\[이어묻기\][^⇒]*⇒\s*새 질문:\s*/, '');
  return 설명신호.test(원);
}

