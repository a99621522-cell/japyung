/**
 * verify_manse.js — 만세력 검증
 *
 * 격국 조문이 아무리 정확해도 명식이 틀리면 전부 헛것이다.
 * 여기서 보는 것은 조문이 아니라 **여덟 글자가 맞느냐**다.
 *
 * 기준값 출처: 한국천문연구원(KASI) 역서 / NASA DE441, 한국 표준시.
 *   2026년 12절 절입시각을 못박아 두었다. 다른 해를 더 넣으려면
 *   KASI2026 아래에 같은 모양으로 붙이면 된다.
 *
 * 실행: node verify_manse.js
 */
const { 사주, 대운수, 그해절기, toJD, 절입표주입 } = require('./manse');

let 통과 = 0, 실패 = 0;
const 실패목록 = [];
function 검사(이름, 조건, 덧말 = '') {
  if (조건) { 통과++; }
  else { 실패++; 실패목록.push(이름 + (덧말 ? ' — ' + 덧말 : '')); }
}
function 마디(t) { console.log('\n── ' + t + ' ' + '─'.repeat(Math.max(0, 46 - t.length))); }

// ═══════════════════════════════════════════════
// 기준값 — KASI 2026 (12절만. 중기는 월주와 무관하다)
// ═══════════════════════════════════════════════
const KASI2026 = {
  소한: [2026, 1, 5, 17, 23], 입춘: [2026, 2, 4, 5, 2],
  경칩: [2026, 3, 5, 22, 58], 청명: [2026, 4, 5, 3, 39],
  입하: [2026, 5, 5, 20, 48], 망종: [2026, 6, 6, 0, 48],
  소서: [2026, 7, 7, 10, 56], 입추: [2026, 8, 7, 20, 42],
  백로: [2026, 9, 7, 23, 41], 한로: [2026, 10, 8, 15, 29],
  입동: [2026, 11, 7, 18, 52], 대설: [2026, 12, 7, 11, 52],
};
// 각 절기 뒤에 오는 월지 — 절입을 넘기면 이 월지로 바뀐다
const 절기월지 = { 소한:'丑', 입춘:'寅', 경칩:'卯', 청명:'辰', 입하:'巳', 망종:'午',
                   소서:'未', 입추:'申', 백로:'酉', 한로:'戌', 입동:'亥', 대설:'子' };
const 앞월지  = { 丑:'子', 寅:'丑', 卯:'寅', 辰:'卯', 巳:'辰', 午:'巳',
                  未:'午', 申:'未', 酉:'申', 戌:'酉', 亥:'戌', 子:'亥' };

const 천간 = '甲乙丙丁戊己庚辛壬癸'.split('');
const 지지 = '子丑寅卯辰巳午未申酉戌亥'.split('');

// ═══════════════════════════════════════════════
마디('[1] 절입시각 — 근사식이 역서와 얼마나 벌어지는가');
{
  const 오차 = [];
  for (const s of 그해절기(2026)) {
    // 그해절기(2026)의 소한은 2027년 1월 것이라 2026 표와 짝이 안 맞는다
    const t = s.이름 === '소한' ? null : KASI2026[s.이름];
    if (!t) continue;
    오차.push({ 이름: s.이름, 분: (s.jd - toJD(t[0], t[1], t[2], t[3], t[4])) * 1440 });
  }
  for (const o of 오차) console.log(`   ${o.이름}  ${o.분 >= 0 ? '+' : ''}${o.분.toFixed(1)}분`);
  const a = 오차.map(o => Math.abs(o.분));
  const 최대 = Math.max(...a), 평균 = a.reduce((x, y) => x + y, 0) / a.length;
  console.log(`   평균 ${평균.toFixed(1)}분 · 최대 ${최대.toFixed(1)}분`);
  // 근사식의 한계가 이 언저리다. 여기를 넘으면 공식이 망가진 것이다.
  검사('절입 근사 오차 15분 이내', 최대 < 15, `최대 ${최대.toFixed(1)}분`);
  검사('절입 근사 평균 8분 이내', 평균 < 8, `평균 ${평균.toFixed(1)}분`);
}

// ═══════════════════════════════════════════════
마디('[2] 절입표를 주입하면 오차가 사라지는가');
{
  const 표 = { 2026: {} };
  for (const [이름, t] of Object.entries(KASI2026)) {
    const p = n => String(n).padStart(2, '0');
    표[2026][이름] = `${t[0]}-${p(t[1])}-${p(t[2])}T${p(t[3])}:${p(t[4])}:00+09:00`;
  }
  절입표주입(표);
  let 최대 = 0, 역서건수 = 0;
  for (const s of 그해절기(2026)) {
    const t = s.이름 === '소한' ? null : KASI2026[s.이름];
    if (!t) continue;
    if (s.근거 === '역서') 역서건수++;
    최대 = Math.max(최대, Math.abs((s.jd - toJD(t[0], t[1], t[2], t[3], t[4])) * 1440));
  }
  검사('주입한 절기가 역서로 표시됨', 역서건수 >= 10, `${역서건수}건`);
  검사('주입 후 오차 1분 미만', 최대 < 1, `최대 ${최대.toFixed(2)}분`);
  절입표주입(null);   // 뒤 검사는 근사식으로
}

// ═══════════════════════════════════════════════
마디('[3] 12절 경계 — 앞뒤 두 시간에서 월지가 갈리는가');
{
  // 근사식 오차(최대 10분)를 피해 넉넉히 두 시간을 벌린다.
  for (const [이름, t] of Object.entries(KASI2026)) {
    if (이름 === '소한') continue;   // 해가 걸쳐 있어 [4]에서 따로 본다
    const 뒤월지 = 절기월지[이름], 전월지 = 앞월지[뒤월지];
    const base = new Date(Date.UTC(t[0], t[1] - 1, t[2], t[3], t[4]));
    const 전 = new Date(base.getTime() - 2 * 3600e3);
    const 후 = new Date(base.getTime() + 2 * 3600e3);
    const A = 사주(전.getUTCFullYear(), 전.getUTCMonth() + 1, 전.getUTCDate(),
                   전.getUTCHours(), 전.getUTCMinutes());
    const B = 사주(후.getUTCFullYear(), 후.getUTCMonth() + 1, 후.getUTCDate(),
                   후.getUTCHours(), 후.getUTCMinutes());
    검사(`${이름} 2시간 전 → ${전월지}월`, A.명식.wolJi === 전월지, `나온 값 ${A.명식.wolJi}`);
    검사(`${이름} 2시간 후 → ${뒤월지}월`, B.명식.wolJi === 뒤월지, `나온 값 ${B.명식.wolJi}`);
  }
}

// ═══════════════════════════════════════════════
마디('[4] 입춘 경계 — 년주가 함께 넘어가는가');
{
  // 2025 = 乙巳, 2026 = 丙午. 입춘 2026-02-04 05:02
  const A = 사주(2026, 2, 4, 3, 0);    // 입춘 두 시간 전
  const B = 사주(2026, 2, 4, 7, 0);    // 입춘 두 시간 후
  검사('입춘 전 년주 乙巳', A.명식.yeonGan + A.명식.yeonJi === '乙巳', A.사주);
  검사('입춘 전 월주 己丑', A.명식.wolGan + A.명식.wolJi === '己丑', A.사주);
  검사('입춘 후 년주 丙午', B.명식.yeonGan + B.명식.yeonJi === '丙午', B.사주);
  검사('입춘 후 월주 庚寅', B.명식.wolGan + B.명식.wolJi === '庚寅', B.사주);

  // 1월생은 늘 앞 해다
  const C = 사주(2026, 1, 15, 12, 0);
  검사('1월 15일생 년주 乙巳', C.명식.yeonGan + C.명식.yeonJi === '乙巳', C.사주);
  검사('1월 15일생 월주 丑월', C.명식.wolJi === '丑', C.사주);   // 소한(1/5) 이후
  const D = 사주(2026, 1, 3, 12, 0);
  검사('1월 3일생 월주 子월', D.명식.wolJi === '子', D.사주);     // 소한 이전 = 대설월
}

// ═══════════════════════════════════════════════
마디('[5] 일주 — 60갑자 연속성과 앵커');
{
  // 앵커: 2000-01-01 = 戊午일 (율리우스일 2451545)
  const A = 사주(2000, 1, 1, 12, 0);
  검사('2000-01-01 일주 戊午', A.명식.ilGan + A.명식.ilJi === '戊午', A.사주);
  // 연속성: 하루 지나면 60갑자가 정확히 한 칸
  let 끊김 = 0;
  let 전 = null;
  for (let d = 0; d < 400; d++) {
    const dt = new Date(Date.UTC(2024, 0, 1 + d));
    const r = 사주(dt.getUTCFullYear(), dt.getUTCMonth() + 1, dt.getUTCDate(), 12, 0);
    const i = 지지.indexOf(r.명식.ilJi) + 12 * ((천간.indexOf(r.명식.ilGan) - 지지.indexOf(r.명식.ilJi) + 120) % 60);
    const idx = (() => { for (let k = 0; k < 60; k++)
      if (천간[k % 10] === r.명식.ilGan && 지지[k % 12] === r.명식.ilJi) return k; })();
    if (전 != null && idx !== (전 + 1) % 60) 끊김++;
    전 = idx;
  }
  검사('일주 400일 연속 (윤일 포함)', 끊김 === 0, `${끊김}건 끊김`);
}

// ═══════════════════════════════════════════════
마디('[6] 월두법(五虎遁) — 년간 10개 전수');
{
  // 甲己→丙寅 乙庚→戊寅 丙辛→庚寅 丁壬→壬寅 戊癸→甲寅
  const 기대 = { 甲:'丙', 己:'丙', 乙:'戊', 庚:'戊', 丙:'庚', 辛:'庚', 丁:'壬', 壬:'壬', 戊:'甲', 癸:'甲' };
  let 틀림 = [];
  for (let y = 1984; y < 1984 + 10; y++) {
    const r = 사주(y, 3, 1, 12, 0);          // 확실히 寅월인 날
    if (r.명식.wolJi !== '寅') { 틀림.push(`${y} 寅월 아님(${r.명식.wolJi})`); continue; }
    if (r.명식.wolGan !== 기대[r.명식.yeonGan]) 틀림.push(`${y} ${r.명식.yeonGan}년 → ${r.명식.wolGan}寅`);
  }
  검사('월두법 10간 전수', 틀림.length === 0, 틀림.join(' / '));
}

// ═══════════════════════════════════════════════
마디('[7] 시두법(五鼠遁) — 일간 10개 전수');
{
  // 甲己→甲子 乙庚→丙子 丙辛→戊子 丁壬→庚子 戊癸→壬子
  const 기대 = { 甲:'甲', 己:'甲', 乙:'丙', 庚:'丙', 丙:'戊', 辛:'戊', 丁:'庚', 壬:'庚', 戊:'壬', 癸:'壬' };
  const 본 = new Set();
  let 틀림 = [];
  for (let d = 0; d < 60; d++) {
    const dt = new Date(Date.UTC(2026, 5, 1 + d));
    // 진태양시를 끄고 정오 子시 확인 — 子시는 00:30으로 잡는다
    const r = 사주(dt.getUTCFullYear(), dt.getUTCMonth() + 1, dt.getUTCDate(), 0, 30,
                   { 진태양시보정: false });
    본.add(r.명식.ilGan);
    if (r.명식.siJi !== '子') { 틀림.push(`00:30이 子시가 아님(${r.명식.siJi})`); continue; }
    if (r.명식.siGan !== 기대[r.명식.ilGan]) 틀림.push(`${r.명식.ilGan}일 → ${r.명식.siGan}子`);
  }
  검사('시두법 10간 전수', 틀림.length === 0 && 본.size === 10,
       틀림.slice(0, 3).join(' / ') + ` (본 일간 ${본.size}개)`);
}

// ═══════════════════════════════════════════════
마디('[8] 시지 — 두 시간마다 한 칸, 자시가 23시부터');
{
  const 기대 = ['子','丑','丑','寅','寅','卯','卯','辰','辰','巳','巳','午',
                '午','未','未','申','申','酉','酉','戌','戌','亥','亥','子'];
  let 틀림 = [];
  for (let h = 0; h < 24; h++) {
    const r = 사주(2026, 6, 15, h, 30, { 진태양시보정: false });
    if (r.명식.siJi !== 기대[h]) 틀림.push(`${h}시30분 → ${r.명식.siJi} (기대 ${기대[h]})`);
  }
  검사('24시간 시지 배속', 틀림.length === 0, 틀림.slice(0, 4).join(' / '));
}

// ═══════════════════════════════════════════════
마디('[9] 대운 — 방향과 날수');
{
  // 양남·음녀 순행 / 음남·양녀 역행
  let 틀림 = [];
  for (let y = 1980; y < 1992; y++) {
    for (const g of ['남', '여']) {
      const r = 사주(y, 6, 15, 12, 0, { 성별: g });
      const 양간 = '甲丙戊庚壬'.includes(r.명식.yeonGan);
      const 기대순행 = (양간 && g === '남') || (!양간 && g === '여');
      if (r.대운.순행 !== 기대순행) 틀림.push(`${y}${g} ${r.명식.yeonGan}`);
      // 순행이면 남은날, 역행이면 지난날을 써야 한다
      const 써야할 = 기대순행 ? r.절기.남은날 : r.절기.지난날;
      if (Math.abs(r.대운.날수 - 써야할) > 0.02) 틀림.push(`${y}${g} 날수 ${r.대운.날수}≠${써야할}`);
    }
  }
  검사('대운 방향·날수 24건', 틀림.length === 0, 틀림.slice(0, 4).join(' / '));

  // 순행인 사람에게 '지난날'을 주면 대운수가 달라진다 — 그 차이를 못박는다
  const r = 사주(1984, 3, 20, 12, 0, { 성별: '남' });   // 甲子년 양남 → 순행
  검사('순행자는 남은날을 쓴다', r.대운.순행 === true, JSON.stringify(r.대운));
  const 잘못 = Math.max(1, Math.round(r.절기.지난날 / 3));
  console.log(`   1984-03-20 남: 대운수 ${r.대운.대운수} (지난날로 잘못 계산하면 ${잘못})`);
}

// ═══════════════════════════════════════════════
마디('[10] 진태양시 — 시주에만 걸리고 월주 경계는 안 건드린다');
{
  // 경칩 2026-03-05 22:58. 그 22분 전(22:36)은 표준시로는 寅월이어야 한다.
  // -32분 보정을 월주에 적용하면 22:04로 밀려 결과가 흔들린다.
  const a = 사주(2026, 3, 5, 22, 36, { 진태양시보정: true });
  const b = 사주(2026, 3, 5, 22, 36, { 진태양시보정: false });
  검사('진태양시 켜고 끄고 월주 동일', a.명식.wolJi === b.명식.wolJi,
       `${a.명식.wolJi} vs ${b.명식.wolJi}`);
  검사('진태양시 켜고 끄고 년주 동일', a.명식.yeonJi === b.명식.yeonJi);
  // 시지는 달라질 수 있어야 한다 (경계 근처에서)
  const c = 사주(2026, 3, 5, 13, 10, { 진태양시보정: true });
  const d = 사주(2026, 3, 5, 13, 10, { 진태양시보정: false });
  검사('진태양시가 시지에는 걸린다', c.명식.siJi !== d.명식.siJi,
       `${c.명식.siJi} vs ${d.명식.siJi} — 13:10은 보정하면 12:38이라 午시`);
}

// ═══════════════════════════════════════════════
마디('[11] 예외 없이 도는가 — 40년 무작위 전수');
{
  let 예외 = 0, 절기경고 = 0, 자시경고 = 0, 총 = 0;
  for (let y = 1960; y <= 2040; y += 2) {
    for (let m = 1; m <= 12; m++) {
      for (const d of [1, 15, 28]) {
        for (const h of [0, 5, 13, 23]) {
          총++;
          try {
            const r = 사주(y, m, d, h, 0, { 성별: '남' });
            if (!r.명식.yeonGan || !r.명식.wolJi || !r.명식.ilGan || !r.명식.siJi) 예외++;
            if (r.경고.some(w => w.includes('절입'))) 절기경고++;
            if (r.경고.some(w => w.includes('자시'))) 자시경고++;
          } catch (e) { 예외++; }
        }
      }
    }
  }
  console.log(`   ${총}건 · 절기경계 ${절기경고}건 (${(절기경고 / 총 * 100).toFixed(1)}%)`
    + ` · 자시 ${자시경고}건 (${(자시경고 / 총 * 100).toFixed(1)}%, 표본이 0시·23시를 반씩 포함)`);
  검사('전수 예외 0', 예외 === 0, `${예외}건`);
  // 절기경계 경고는 드물어야 한다. 늘 뜨는 경고는 아무도 안 읽는다
  검사('절기경계 경고 8% 미만', 절기경고 / 총 < 0.08,
       `${(절기경고 / 총 * 100).toFixed(1)}%`);
}

// ═══════════════════════════════════════════════
console.log('\n' + '═'.repeat(50));
console.log(`통과 ${통과} · 실패 ${실패}`);
if (실패목록.length) {
  console.log('\n실패한 것:');
  for (const f of 실패목록) console.log('  ✗ ' + f);
}
process.exit(실패 ? 1 : 0);
