/**
 * jeoul.js — 「무엇이 얇은가」를 가린다 (원문의 저울)
 *
 * 원문 40편: 「煞重食輕則助食，煞輕食重則助煞，煞食均而日主根輕則助身」
 *   ─ 취운 조문의 상당수가 이런 저울 문장이다. 그런데 엔진이 이것을 읽고
 *     실행하지 않으면 「희」가 비어버려 상담에서 아무 말도 못 한다.
 *
 * ※ 다만 이것이 이 방법에서 가장 미끄러운 자리다.
 *   무게를 숫자로 재기 시작하면 억부로 흘러가고, 그것은 30편이 논파한 길이다.
 *   그래서 **세지 않고 본다**:
 *     ① 천간에 드러났는가            ← 27편 「干主天，動而有爲」
 *     ② 지지에 뿌리가 있는가          ← 3편 통근
 *     ③ 몇 자리에 걸쳐 있는가         ← 자릿수만 센다. 세력 점수가 아니다
 *   그리고 확실히 갈리지 않으면 **「판단 보류」**를 낸다.
 *   모르는 것을 아는 척하게 만들면 47편의 정신을 어긴다.
 */

const { GAN, sipseong, JIJANGGAN } = require('./jijanggan');

const 무리 = {
  비겁: ['비견', '겁재'], 식상: ['식신', '상관'], 재: ['정재', '편재'],
  관살: ['정관', '편관'], 인: ['정인', '편인'],
};
const 무리찾기 = ss => Object.keys(무리).find(k => 무리[k].includes(ss)) ?? null;

/** 한 무리가 명식에서 어떻게 놓였는지 — 세지 않고 본다 */
function 놓임(m, 대상무리) {
  const 목 = 무리[대상무리] ?? [대상무리];
  const 천간 = [['년', m.yeonGan], ['월', m.wolGan], ['시', m.siGan]].filter(x => x[1]);
  const 지지 = [['년', m.yeonJi], ['월', m.wolJi], ['일', m.ilJi], ['시', m.siJi]].filter(x => x[1]);

  const 드러남 = 천간.filter(([, g]) => 목.includes(sipseong(m.ilGan, g)))
                    .map(([p, g]) => `${g}(${p})`);
  const 숨음 = [];
  for (const [p, j] of 지지)
    for (const x of JIJANGGAN[j])
      if (목.includes(sipseong(m.ilGan, x.gan)))
        숨음.push({ 자리: p, 지지: j, 글자: x.gan, 위: x.wi });

  // 뿌리 — 천간에 난 것이 지지에도 있는가
  const 뿌리 = 드러남.length > 0 && 숨음.length > 0;
  // 자릿수 — 몇 군데에 걸쳐 있나 (세력 점수가 아니라 「퍼짐」)
  const 자리수 = new Set([...드러남.map(x => x.match(/\((.)\)/)[1]), ...숨음.map(x => x.자리)]).size;

  return { 무리: 대상무리, 드러남, 숨음, 뿌리, 자리수,
    상태: 드러남.length && 뿌리 ? '드러나고 뿌리 있음'
        : 드러남.length ? '드러났으나 뿌리 없음'
        : 숨음.length ? '지지에만 있음'
        : '없음' };
}

const 등급 = { '드러나고 뿌리 있음': 3, '드러났으나 뿌리 없음': 2, '지지에만 있음': 1, '없음': 0 };

/**
 * 두 무리(또는 셋)를 견주어 「어느 쪽이 얇은가」를 가린다.
 * @returns {{얇은쪽, 두꺼운쪽, 확실한가, 사유, 놓임}}
 */
function 견주기(m, 무리들) {
  const 본 = 무리들.map(x => 놓임(m, x));
  const 점 = 본.map(x => 등급[x.상태] + Math.min(1, (x.자리수 - 1) * 0.5));
  const 최소 = Math.min(...점), 최대 = Math.max(...점);
  const 얇은 = 본[점.indexOf(최소)], 두꺼운 = 본[점.indexOf(최대)];
  const 확실 = (최대 - 최소) >= 1;   // 한 등급 이상 벌어져야 판단한다

  return {
    얇은쪽: 확실 ? 얇은.무리 : null,
    두꺼운쪽: 확실 ? 두꺼운.무리 : null,
    확실한가: 확실,
    사유: 확실
      ? `${얇은.무리}은 ${얇은.상태}이고 ${두꺼운.무리}은 ${두꺼운.상태}이라 ${얇은.무리} 쪽이 얇다`
      : '어느 쪽이 얇은지 뚜렷하지 않다 — 판단을 보류한다',
    놓임: 본,
    원문: '煞重食輕則助食，煞輕食重則助煞，煞食均而日主根輕則助身',
    주의: '세력을 숫자로 재지 않는다. 드러났는가·뿌리가 있는가·몇 자리에 걸쳤는가만 본다',
  };
}

/**
 * 취운 조문이 저울 문장일 때 「희」를 채운다.
 * 격·상신에 따라 무엇과 무엇을 견줄지가 정해진다.
 */
const 저울짝 = {
  '편관/식신': ['관살', '식상'],   // 살과 식신
  '편관/양인': ['관살', '비겁'],
  '상관/정재': ['식상', '재'],
  '식신/정재': ['식상', '재'],
  '정재/정관': ['재', '관살'],
  '건록/정재': ['재', '비겁'],
};

function 저울로희기(격, 상신, m) {
  const 짝 = 저울짝[`${격}/${상신}`];
  if (!짝) return null;
  const r = 견주기(m, 짝);
  const 몸 = 놓임(m, '비겁');

  // 둘이 고르면 — 원문의 셋째 조항으로 간다.
  //   「煞食均而日主根輕則助身」 — 둘이 고른데 일간의 뿌리가 얇으면 몸을 돕는다.
  //   즉 「고르다」는 판단 불가가 아니라 **그 자체가 하나의 답**이다.
  if (!r.확실한가) {
    if (등급[몸.상태] <= 1) {
      return { 희: ['비겁', '인'], 보류: false,
        사유: `${짝.join('과 ')}이 고른데 일간이 ${몸.상태}이라 몸을 돕는 것이 마땅하다`,
        조항: '셋째 — 둘이 고르고 일간이 얇을 때', 놓임: r.놓임 };
    }
    return { 희: [], 보류: true,
      사유: `${짝.join('과 ')}이 고르고 일간도 두터워, 어느 쪽을 채울지 뚜렷하지 않다`,
      놓임: r.놓임 };
  }

  // 얇은 쪽을 채운다. 일간까지 얇으면 몸을 돕는 것도 함께.
  const 희 = [r.얇은쪽];
  if (등급[몸.상태] <= 1 && !희.includes('비겁')) 희.push('비겁');
  return { 희, 보류: false, 사유: r.사유, 조항: '첫째·둘째 — 얇은 쪽을 채움', 놓임: r.놓임 };
}

module.exports = { 놓임, 견주기, 저울로희기, 무리찾기 };
